/** How many samples a drawn sound has in a second. */
const SAMPLE_RATE = 8000;

/** The bytes of a WAV file's header (RIFF). */
const WAV_HEADER = 44;

/** Draw a sound of plucked notes as a WAV data URL, so an example plays one without a file. */
export function sound(notes: readonly number[], seconds: number): string {
    // write the header of eight bit samples in one channel
    const count = SAMPLE_RATE * seconds;
    const bytes = new Uint8Array(WAV_HEADER + count);
    const view = new DataView(bytes.buffer);
    const words = [...new TextEncoder().encode("RIFF____WAVEfmt ____________________data")];
    bytes.set(words);
    view.setUint32(4, WAV_HEADER - 8 + count, true);
    view.setUint32(16, 16, true);
    view.setUint16(20, 1, true);
    view.setUint16(22, 1, true);
    view.setUint32(24, SAMPLE_RATE, true);
    view.setUint32(28, SAMPLE_RATE, true);
    view.setUint16(32, 1, true);
    view.setUint16(34, 8, true);
    view.setUint32(40, count, true);

    // pluck a note each half second
    for (let i = 0; i < count; i++) {
        const time = i / SAMPLE_RATE;
        const note = notes[Math.floor(time * 2) % notes.length] ?? 0;
        const wave = Math.sin(time * note * Math.PI * 2) * Math.exp(-(time % 0.5) * 6);
        bytes[WAV_HEADER + i] = 128 + Math.round(wave * 60);
    }

    return `data:audio/wav;base64,${bytes.toBase64()}`;
}

