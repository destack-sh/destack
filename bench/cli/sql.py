def _generate_pg_schema():
    """Generate the .py custom SQL schema describing the current Bench types."""
    chunks: list[str] = [
        # standardized generated notice
        "# This file was automatically generated by Bench. DO NOT EDIT!",
        "from bench.sql.core import Table, CascadeAction, Column, PrimitiveType, Constraint, ConstraintType, Index, IndexType",
        # append VERSION
        f'VERSION = "{VERSION}"',
    ]
    for node_t in NodeType:
        node_cls = NODE_CLASS_BY_TYPE[node_t]
        if node_cls.__is_stored__ and not node_cls.__is_stored_custom__:
            table = map_node_class_to_pg_table(node_cls)
            const_name = f"{node_cls.metatype.name}_TABLE"
            table_def = f"{const_name} = {table.source_repr()}"
            chunks.append(table_def)
    source = "\n\n".join(chunks)
    source = format_python(source)
    return source


@app.command()
def regen():
    start = time.time()
    source = _generate_pg_schema()
    Path("bench/sql/schema.py").write_text(source)
    logger.info("sql.generate", duration=time.time() - start)


@app.command(help="generate global AND local SQL migrations")
@async_to_sync_blocking
async def makemigrations(
    bench: str = typer.Option(default="bench", help="the bench to use as local reference"),
    no_downgrade: bool = typer.Option(default=False, help="exclude downgrade operations"),
    no_local: bool = typer.Option(default=False, help="exclude local operations"),
    dry_run: bool = typer.Option(default=False, help="only print, don't store"),
    overwrite: bool = typer.Option(default=False, help="overwrite existing migration for version"),
):
    start = time.time()

    # defensively check existing migrations for inconsistencies
    known_migrations = read_migrations_from_fs()
    conflicting_migration = first((m for m in known_migrations if m.version == VERSION), None)
    if conflicting_migration:
        if overwrite:
            logger.info("makemigrations.overwrite", migration=conflicting_migration)
            assert conflicting_migration.path
            Path(conflicting_migration.path).unlink()
            known_migrations.remove(conflicting_migration)
        else:
            raise RuntimeError(
                f"existing migration for version {VERSION}: {conflicting_migration!r}"
            )
    async with global_pg_cursor() as cur:
        stored_migrations = await read_migrations_from_pg(cur)
    if any(m.applied_at is None for m in stored_migrations):
        # we introspect DB state, so we can't makemigrations if we have unapplied migrations
        raise RuntimeError(f"unapplied migrations: {stored_migrations!r}")
    max_known_id = max(m.id for m in known_migrations) if known_migrations else 0
    max_stored_id = max(m.id for m in stored_migrations) if stored_migrations else 0
    if max_stored_id > max_known_id:
        raise RuntimeError(
            f"stored migrations are ahead of known migrations:\nstored={stored_migrations!r}\nknown={known_migrations!r}"
        )

    # diff local
    if not no_local:
        async with global_session():
            try:
                bench = await Bench.descendants(Environment, Store).include_all().get(slug=bench)
                async with pg_cursor_to_store(bench.main_environment.store) as cur:
                    old_local_tables = await introspect_tables_from_pg(cur)
            except (NodeNotFoundError, SqlUndefinedObjectError):
                old_local_tables = ()  # initial migration
        local_migration_ops = generate_migration_ops(old_local_tables, LOCAL_TABLES)
    else:
        local_migration_ops = []

    # diff global
    async with global_pg_cursor() as cur:
        old_global_tables = await introspect_tables_from_pg(cur)
    global_migration_ops = generate_migration_ops(old_global_tables, GLOBAL_TABLES)

    # generate migration
    if not global_migration_ops and not local_migration_ops:
        logger.info("makemigrations.noop")
        return
    latest_migration = max(known_migrations, key=lambda m: m.id, default=None)
    new_migration = Migration(
        id=latest_migration.id + 1 if latest_migration is not None else 1,
        version=VERSION,
        has_global=bool(global_migration_ops),
        has_local=bool(local_migration_ops),
        applied_at=None,
    )
    migration_code = generate_migration_code(
        new_migration,
        global_ops=global_migration_ops,
        local_ops=local_migration_ops,
        exclude_inverse=no_downgrade,
    )
    if not dry_run:
        add_migration_to_fs(migration=new_migration, code=migration_code)
    else:
        print(migration_code)

    logger.info("makemigrations", duration=time.time() - start)


@app.command(help="apply global OR local SQL migrations")
@async_to_sync_blocking
async def migrate(
    target: Optional[str] = typer.Option(
        default=None, help="the migration to migrate to [default=latest]"
    ),
    bench: Optional[str] = typer.Option(
        default=None, help="the local bench to migrate, global otherwise"
    ),
    dry_run: bool = typer.Option(default=False, help="only try, don't commit"),
):
    start = time.time()

    # resolve local_pg_name (determine local/global migration)
    if bench is not None:
        async with global_session():
            if bench != "*":
                bench = await Bench.descendants(Environment, Store).include_all().get(slug=bench)
                stores = tuple(e.store for e in bench.environments)
            else:
                benches = await Bench.descendants(Environment, Store).include_all().tolist()
                stores = tuple(e.store for b in benches for e in b.environments)
    else:
        stores = (GLOBAL_STORE,)

    for store in stores:
        async with pg_cursor_to_store(store) as cur:
            await migrate_to(cur=cur, target=target, is_global=bench is None)
            if not dry_run:
                await cur.connection.commit()
            else:
                await cur.connection.rollback()

    logger.info("migrate", duration=time.time() - start)


@app.command(help="delete migrations")
@async_to_sync_blocking
async def clearmigrations(from_id: int, to_id: int):
    start = time.time()

    delete_migrations_in_fs(from_id, to_id)
    async with global_pg_cursor() as cur:
        await delete_migrations_in_pg(cur, from_id=from_id, to_id=to_id)
        await cur.connection.commit()
    async with global_session():
        benches = await Bench.tolist()
        for bench in benches:
            stores = tuple(e.store for e in bench.environments)
            for store in stores:
                async with pg_cursor_to_store(store) as cur:
                    await delete_migrations_in_pg(cur, from_id=from_id, to_id=to_id)
                    await cur.connection.commit()

    logger.info("clear_migrations", duration=time.time() - start)


@app.command()
@async_to_sync_blocking
async def introspect(bench: str = None):
    """Introspect the current schema of the Postgres instance."""
    start = time.perf_counter()

    if bench is not None:
        async with global_session():
            bench = Bench.descendants(NodeType.ENVIRONMENT, NodeType.STORE).get(slug=bench)
            async with pg_cursor_to_store(bench.main_environment.store) as cur:
                tables = await introspect_tables_from_pg(
                    cur, include_columns=True, include_indexes=True, include_constraints=True
                )
    else:
        async with global_pg_cursor() as cur:
            tables = await introspect_tables_from_pg(
                cur, include_columns=True, include_indexes=True, include_constraints=True
            )
            await cur.connection.rollback()

    # generate schema
    chunks: list[str] = []
    for table in tables:
        const_name = f"{table.name}_TABLE".upper()
        if const_name.startswith("BENCH_"):
            const_name = const_name[6:]
        table_def = f"{const_name} = {table.source_repr()}"
        chunks.append(table_def)
    source = "\n\n".join(chunks)
    source = format_python(source)
    print(source)

    logger.info("sql.introspect", duration=time.perf_counter() - start)


@app.command()
@async_to_sync_blocking
async def shell(bench: str = None):  # type: ignore
    """Open a psql shell to either the global or a Bench-local database."""
    if bench is not None:
        async with global_session():
            bench = await Bench.descendants(Environment, Store).include_all().get(slug=bench)
        connection_str = get_pg_connection_str(bench.main_environment.store)
    else:
        connection_str = get_pg_connection_str(GLOBAL_STORE)

    logger.info(
        "shell.psql", bench=bench, connection_str=re.sub(r":[^@]+@", ":*****@", connection_str)
    )
    sigint_handler = signal.getsignal(signal.SIGINT)
    try:
        # allow SIGINT to pass to psql to abort queries
        signal.signal(signal.SIGINT, signal.SIG_IGN)
        subprocess.run(["psql", connection_str], check=True)
    finally:
        signal.signal(signal.SIGINT, sigint_handler)
