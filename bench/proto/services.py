ServiceStubT = TypeVar("ServiceStubT", bound=ServiceStub)

logger = structlog.get_logger(__name__)
StubT = TypeVar("StubT", bound=ServiceStub)

# We amend the signature generated by betterproto (e.g., to pass in the request subject)
UnaryRpcCallable = Callable[[Subject, betterproto.Message], betterproto.Message]
ServerStreamingRpcCallable = Callable[
    [Subject, betterproto.Message], AsyncIterable[betterproto.Message]
]
RpcCallable = UnaryRpcCallable | ServerStreamingRpcCallable


class BenchServiceBase((IServable, Generic[StubT]) if TYPE_CHECKING else Generic[StubT]):
    """gRPC service with some extra stuff for custom loops, auth, logging, metadata, ..."""

    def __init__(self, loopback_stub_to: type[StubT] | None = None):
        self._loopback_stub: type[StubT] | None = None
        self._needs_loopback_stub = loopback_stub_to

    @property
    def loopback(self) -> StubT:
        if self._loopback_stub is not None:
            return self._loopback_stub
        elif self._needs_loopback_stub is None:
            raise RuntimeError(f"loopback stub not configured for {self!r}")
        else:
            raise RuntimeError(f"loopback stub not ready for {self!r}")

    async def log_and_check_access(self, request: Request):
        """Logs accesses for the audit log (soon). Raises if access was denied."""
        if request.decision == PolicyEffect.ALLOW:
            logger.debug("access.allow", request=request)
        else:
            logger.debug("access.deny", request=request)
            raise AccessError(request)

    async def start(self) -> None:
        """Start the service. Should be ready for service when returning."""
        if self._needs_loopback_stub:
            # create a loopback like the one used for testing
            channel = ChannelFor([self])
            await channel.__aenter__()
            self._loopback_stub = self._loopback_stub(channel)

    def close(self) -> None:
        """Close the service.."""
        pass

    async def wait_closed(self) -> None:
        """Wait for the service to be fully closed."""
        if self._loopback_stub is not None:
            await self._loopback_stub.channel.__aexit__(None, None, None)

    def __mapping__(self) -> Mapping[str, grpclib.const.Handler]:
        # combine mappings from non-overlapping superclasses
        patched_mapping = {}
        for cls in self.__class__.__bases__:
            if cls is BenchServiceBase:
                continue
            for method, handler in cls.__mapping__(self).items():
                patched_mapping[method] = self._wrap_rpc(method, handler)
        assert len(patched_mapping) > 0, f"no RPCs found in {self!r}"
        return patched_mapping

    def _wrap_rpc_func(
        self, func: RpcCallable, method_name: str, handler: grpclib.const.Handler
    ) -> Callable:
        return func

    @final
    def _validate_request(self, subject: Subject, request: betterproto.Message) -> None:
        """Validate a request message."""
        self._validate_message(request)
        self._validate_request_self(subject, request)

    @final
    def _validate_message(self, message: betterproto.Message, path: tuple[str, ...] = ()) -> None:
        # ensure every Bench struct has its metatype set
        struct_cls = BENCH_CLASS_BY_PROTO_CLASS.get(message.__class__)
        if struct_cls is not None:
            if message.metatype is None:
                raise ValidationError(message, f"missing metatype for {message.__class__.__name__}")
            if message.metatype != struct_cls.metatype:
                raise ValidationError(
                    message, f"invalid metatype {message.metatype} for {message.__class__.__name__}"
                )

        # walk message recursively
        defaults = message._betterproto.default_gen
        for field_name, field in message._betterproto_meta.meta_by_field_name.items():
            field_is_repeated = defaults[field_name] is list
            if field.proto_type == betterproto.TYPE_MESSAGE:
                value = getattr(message, field_name)
                if isinstance(value, betterproto.Message):
                    inner_path = path + (field_name,)
                    if field_is_repeated:
                        for sub_message in value:
                            self._validate_message(sub_message, inner_path)
                    elif value is not None:
                        self._validate_message(value, inner_path)

    def _validate_request_self(self, subject: Subject, request: betterproto.Message) -> None:
        """Validate a request message for this service."""
        pass

    @final
    def _wrap_rpc(self, method: str, handler: grpclib.const.Handler) -> grpclib.const.Handler:
        _, cardinality, request_type, reply_type = handler
        service_slug = to_casing(self.__class__.__name__, Casing.SNAKE)
        method_slug = to_casing(method.split("/")[-1], Casing.SNAKE)
        rpc_name = f"{service_slug}.{method_slug}"
        func = self.__getattribute__(method_slug)  # bypass the generated __rpc wrapper methods
        func = self._wrap_rpc_func(func, method_slug, handler)  # custom wrap per service

        @functools.wraps(func)
        async def _managed_rpc(stream: grpclib.server.Stream) -> None:
            """Managed RPC call with some instrumentation and error handling."""

            start = asyncio.get_running_loop().time()
            log = logger.bind(service=self, method=method)
            try:
                # prepare
                metadata = RpcMetadata().from_headers(stream.metadata)
                subject = await get_subject_from_metadata(metadata)
                log = log.bind(subject=subject)

                # call
                if cardinality == grpclib.const.Cardinality.UNARY_UNARY:
                    request = await stream.recv_message()
                    self._validate_request(subject, request)
                    response = await func(subject, request)
                    await stream.send_message(response)
                elif cardinality == grpclib.const.Cardinality.UNARY_STREAM:
                    request = await stream.recv_message()
                    self._validate_request(subject, request)
                    async for response in func(subject, request):
                        log.debug(f"{rpc_name}.stream", response=response)
                        await stream.send_message(response)
                else:
                    raise NotImplementedError(f"unsupported cardinality {cardinality}")
                duration = asyncio.get_running_loop().time() - start
                log.info(f"{rpc_name}", duration=duration)

            except GRPCError as e:
                # pass through GRPC errors
                duration = asyncio.get_running_loop().time() - start
                sentry_capture(e)
                log.exception(rpc_name, duration=duration, error=e)
                raise

            except BenchError as e:
                # wrap error
                duration = asyncio.get_running_loop().time() - start
                log.exception(rpc_name, duration=duration, error=e)
                status_map: Mapping[type, GRPCStatus] = {
                    NotImplementedError: GRPCStatus.UNIMPLEMENTED,
                    NodeNotFoundError: GRPCStatus.NOT_FOUND,
                    SqlNotExistsError: GRPCStatus.NOT_FOUND,
                    SqlAlreadyExistsError: GRPCStatus.ALREADY_EXISTS,
                    AccessError: GRPCStatus.PERMISSION_DENIED,
                    ValidationError: GRPCStatus.INVALID_ARGUMENT,
                }
                status = status_map.get(e.__class__, GRPCStatus.INVALID_ARGUMENT)
                raise GRPCError(status, str(e)) from e

            except Exception as e:
                # internal error
                duration = asyncio.get_running_loop().time() - start
                sentry_capture(e)
                log.exception(f"{rpc_name}.internal_error", duration=duration, error=e)
                if IS_DEBUG or IS_TEST:
                    details = f"{e.__class__.__name__}: {e}"
                else:
                    details = e.__class__.__name__
                raise GRPCError(GRPCStatus.INTERNAL, details) from e

        return grpclib.const.Handler(_managed_rpc, cardinality, request_type, reply_type)


class MonitoredServiceBase(BenchServiceBase, Monitored):
    pass


class BenchServer(grpclib.server.Server):
    """gRPC server with extra bells and whistles."""

    @functools.wraps(grpclib.server.Server.__init__)
    def __init__(self, handlers: Collection["IServable"], **kwargs):
        super().__init__(handlers, **kwargs)
        self._custom_handlers: tuple[BenchServiceBase, ...] = tuple(
            h for h in handlers if isinstance(h, BenchServiceBase)
        )
        self._host: str | None = None
        self._port: int | None = None

    def __str__(self):
        return f"services={self._custom_handlers}, host={self._host}, port={self._port}"

    def __repr__(self):
        return f"<BenchServer {self}>"

    @functools.wraps(grpclib.server.Server.start)
    async def start(self, host: str = None, port: int = None, **kwargs) -> None:
        self._host = host
        self._port = port
        logger.info("server.start", server=self)
        await asyncio.gather(*(h.start() for h in self._custom_handlers))
        await super().start(host=host, port=port, **kwargs)
        logger.info("server.ready", server=self)

    def close(self) -> None:
        logger.info("server.close", server=self)
        for task in self._custom_handlers:
            task.close()
        super().close()

    @functools.wraps(grpclib.server.Server.wait_closed)
    async def wait_closed(self) -> None:
        await super().wait_closed()
        await asyncio.gather(*(h.wait_closed() for h in self._custom_handlers))
        logger.info("server.closed", server=self)
