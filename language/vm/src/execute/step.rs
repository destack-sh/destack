// advance to the next instruction in one block
macro_rules! next {
    ($state:expr, $block:expr, $pc:expr) => {{
        $state.maybe_profile_instruction(&$block[$pc]);
        let next_pc = $pc + 1;
        become $crate::execute::step_instruction($state, $block, next_pc)
    }};
}

pub(crate) use next;
