use crate::{
    Compiler, GenerateError, GenerateResult, Task, TaskDebug, TaskDependencyError, TaskOutput,
};

use destack_dir::{GlobalNodeIdAny, LocalNodeIdAny, NodeType};
use destack_source::ModuleId;
use destack_workspace::{ArtifactId, OutputFormat, Program, Target};

/// Task to generate code for a module into an artifact.
#[derive(Debug, Clone, Hash, PartialEq, Eq)]
pub enum GenerateTask {
    /// Generate a module for a specific target.
    GenerateModule {
        /// The module to generate.
        module: ModuleId,
        /// The target name (looked up on the module's package).
        target: String,
    },
}

impl GenerateTask {
    /// Get the sub code for the task.
    pub fn sub_code(&self) -> u8 {
        match self {
            Self::GenerateModule { .. } => 1,
        }
    }
}

impl TaskDebug for GenerateTask {
    fn name(&self) -> &'static str {
        match self {
            Self::GenerateModule { .. } => "module",
        }
    }

    fn trace_args(&self, program: &Program) -> String {
        match self {
            Self::GenerateModule { module, target } => {
                let module = program.modules.get(*module);
                let uri = module.read().uri.clone().to_string();
                format!(r#"module="{uri}" target="{target}""#)
            }
        }
    }
}

impl From<GenerateTask> for Task {
    fn from(task: GenerateTask) -> Self {
        Task::Generate(task)
    }
}

/// Output of a generate task.
#[derive(Debug, Clone, PartialEq)]
pub struct GenerateOutput {
    /// The artifact ids generated by this task.
    pub artifacts: Vec<ArtifactId>,
}

impl From<GenerateOutput> for TaskOutput {
    fn from(output: GenerateOutput) -> Self {
        TaskOutput::Generate(output)
    }
}

impl From<TaskDependencyError> for GenerateError {
    fn from(e: TaskDependencyError) -> Self {
        match e {
            TaskDependencyError::NotReady { dependency } => Self::Yield { dependency },
            TaskDependencyError::Failed { dependency } => {
                Self::UnsatisfiedDependency { dependency }
            }
        }
    }
}

impl Compiler {
    /// Process a generate task.
    pub fn process_generate(&self, task: GenerateTask) -> GenerateResult<GenerateOutput> {
        match task {
            GenerateTask::GenerateModule { module, target } => {
                self.generate_module(module, &target)
            }
        }
    }

    /// Generate code for a module.
    fn generate_module(
        &self,
        module_id: ModuleId,
        target_name: &str,
    ) -> GenerateResult<GenerateOutput> {
        // look up target from module's package
        let target = {
            let module_ref = self.program.modules.get(module_id);
            let module = module_ref.read();
            let package_ref = self.program.packages.get(module.package_id);
            let package = package_ref.read();
            package.targets.get(target_name).cloned()
        };

        let target = target.ok_or_else(|| GenerateError::Internal {
            node: Self::placeholder_node(module_id),
            message: format!("target '{target_name}' not found"),
        })?;

        // dispatch based on output format
        match target.output {
            OutputFormat::Js | OutputFormat::Ts => self.generate_js(module_id, &target),
            OutputFormat::Native | OutputFormat::Wasm => {
                self.generate_cranelift(module_id, &target)
            }
        }
    }

    /// Generate JS/TS code for a module.
    fn generate_js(&self, module_id: ModuleId, target: &Target) -> GenerateResult<GenerateOutput> {
        // yield to Elaborate if not ready
        self.ensure_elaborated(module_id)?;

        // dispatch to JS codegen
        let registry_next_id = || self.program.artifacts.next_id();
        let artifacts = destack_codegen_js::generate_module(
            self.program.clone(),
            module_id,
            target,
            registry_next_id,
        )
        .map_err(|e| GenerateError::Internal {
            node: Self::placeholder_node(module_id),
            message: e.to_string(),
        })?;

        // store artifacts in registry
        let artifact_ids: Vec<ArtifactId> = artifacts
            .into_iter()
            .map(|artifact| self.program.artifacts.insert(artifact))
            .collect();

        Ok(GenerateOutput {
            artifacts: artifact_ids,
        })
    }

    /// Generate native/WASM code for a module using Cranelift.
    fn generate_cranelift(
        &self,
        module_id: ModuleId,
        target: &Target,
    ) -> GenerateResult<GenerateOutput> {
        // yield to Optimize if not ready
        self.ensure_optimized(module_id)?;

        // dispatch to Cranelift codegen
        let registry_next_id = || self.program.artifacts.next_id();
        let artifacts = destack_codegen_cranelift::generate_module(
            self.program.clone(),
            module_id,
            target,
            registry_next_id,
        )
        .map_err(|e| GenerateError::Internal {
            node: Self::placeholder_node(module_id),
            message: e.to_string(),
        })?;

        // store artifacts in registry
        let artifact_ids: Vec<ArtifactId> = artifacts
            .into_iter()
            .map(|artifact| self.program.artifacts.insert(artifact))
            .collect();

        Ok(GenerateOutput {
            artifacts: artifact_ids,
        })
    }

    /// Create a placeholder node for error reporting.
    fn placeholder_node(module_id: ModuleId) -> GlobalNodeIdAny {
        GlobalNodeIdAny::new(
            module_id,
            LocalNodeIdAny {
                id: 0,
                ty: NodeType::Expression,
            },
        )
    }

    /// Ensure a module has been generated.
    pub fn ensure_generated(
        &self,
        module: ModuleId,
        target: &str,
    ) -> Result<(), TaskDependencyError> {
        self.require_task(GenerateTask::GenerateModule {
            module,
            target: target.to_string(),
        })
    }
}
