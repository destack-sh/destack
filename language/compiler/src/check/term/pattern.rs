/// Pattern relation term with source ownership.
///
/// Examples:
/// ```ds
/// const { name } = user
/// match (value) { Some(item) => item }
/// ```
#[derive(Debug, Clone, PartialEq)]
pub(in crate::check) struct PatternTerm {
    /// The source that induced this pattern term.
    pub(in crate::check) source: PatternSource,
    /// The pattern operation.
    pub(in crate::check) target: PatternTarget,
}

impl PatternTerm {
    /// Create one source-backed pattern term.
    pub(in crate::check) fn node(source: dir::GlobalNodeIdAny, target: PatternTarget) -> Self {
        Self {
            source: PatternSource::Node(source),
            target,
        }
    }

    /// Create one generated pattern term.
    pub(in crate::check) fn generated(origin: Origin, target: PatternTarget) -> Self {
        Self {
            source: PatternSource::Generated(origin),
            target,
        }
    }

    /// Return the source node when this pattern came from source.
    pub(in crate::check) fn source_node(&self) -> Option<dir::GlobalNodeIdAny> {
        match self.source {
            PatternSource::Node(source) => Some(source),
            PatternSource::Generated(_) => None,
        }
    }
}

/// Source that induced one pattern term.
///
/// Examples:
/// ```ds
/// const value = input
/// const [head, ...tail] = input
/// ```
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::check) enum PatternSource {
    /// Pattern came from one DIR node.
    ///
    /// Examples:
    /// ```ds
    /// const value = input
    /// ```
    Node(dir::GlobalNodeIdAny),
    /// Pattern was generated by check.
    ///
    /// Examples:
    /// ```ds
    /// const [head, ...tail] = input
    /// ```
    Generated(Origin),
}

/// Pattern operation selected from source syntax.
///
/// Examples:
/// ```ds
/// _
/// Some(value)
/// { name }
/// ```
#[derive(Debug, Clone, PartialEq)]
pub(in crate::check) enum PatternTarget {
    /// Wildcard pattern.
    ///
    /// Examples:
    /// ```ds
    /// _
    /// ```
    Wildcard,
    /// Required value pattern.
    ///
    /// Examples:
    /// ```ds
    /// value
    /// ```
    Must {
        /// The checked pattern.
        pattern: TermId<PatternTerm>,
    },
    /// Defaulted pattern.
    ///
    /// Examples:
    /// ```ds
    /// value = fallback
    /// ```
    Assign {
        /// The checked pattern.
        pattern: TermId<PatternTerm>,
        /// The default value type.
        value: TypeOperand,
    },
    /// Borrow pattern.
    ///
    /// Examples:
    /// ```ds
    /// &value
    /// ```
    BorrowOf {
        /// The borrow mutability.
        mutability: Option<dir::Mutability>,
        /// The checked pattern.
        pattern: TermId<PatternTerm>,
    },
    /// Move pattern.
    ///
    /// Examples:
    /// ```ds
    /// ^value
    /// ```
    MoveOf {
        /// The move mutability.
        mutability: Option<dir::Mutability>,
        /// The checked pattern.
        pattern: TermId<PatternTerm>,
    },
    /// Dereference pattern.
    ///
    /// Examples:
    /// ```ds
    /// *value
    /// ```
    DereferenceOf {
        /// The checked pattern.
        pattern: TermId<PatternTerm>,
    },
    /// Binding pattern.
    ///
    /// Examples:
    /// ```ds
    /// value
    /// Some(value)
    /// ```
    Binding {
        /// The bound symbol.
        symbol: Option<dir::GlobalSymbolId>,
        /// The nested pattern.
        pattern: Option<TermId<PatternTerm>>,
    },
    /// Value expression pattern.
    ///
    /// Examples:
    /// ```ds
    /// 1
    /// "ready"
    /// ```
    Expression {
        /// The expression value type.
        value: TypeOperand,
    },
    /// Range pattern.
    ///
    /// Examples:
    /// ```ds
    /// 0..10
    /// 0..=10
    /// ```
    Range {
        /// The start value type.
        start: Option<TypeOperand>,
        /// The end value type.
        end: Option<TypeOperand>,
        /// The range end kind.
        end_kind: dir::RangeEnd,
    },
    /// Type expression pattern.
    ///
    /// Examples:
    /// ```ds
    /// value is Ready
    /// ```
    Type {
        /// The matched type.
        ty: TypeOperand,
    },
    /// Tuple pattern.
    ///
    /// Examples:
    /// ```ds
    /// [left, right]
    /// ```
    Tuple {
        /// The tuple fields.
        fields: SmallVec<[PatternField; 4]>,
    },
    /// Newtype wrapper pattern.
    ///
    /// Examples:
    /// ```ds
    /// UserId(raw)
    /// ```
    Newtype {
        /// The tag type.
        ty: TypeOperand,
        /// The tuple fields.
        fields: SmallVec<[PatternField; 3]>,
    },
    /// Sequence pattern.
    ///
    /// Examples:
    /// ```ds
    /// [head, ...tail]
    /// ```
    Sequence {
        /// The sequence fields.
        fields: SmallVec<[PatternField; 4]>,
    },
    /// Object pattern.
    ///
    /// Examples:
    /// ```ds
    /// { name, age }
    /// ```
    Object {
        /// The object fields.
        fields: SmallVec<[PatternField; 4]>,
    },
    /// Nominal object pattern.
    ///
    /// Examples:
    /// ```ds
    /// Point { x, y }
    /// ```
    NominalObject {
        /// The tag type.
        ty: TypeOperand,
        /// The object fields.
        fields: SmallVec<[PatternField; 3]>,
    },
    /// Union pattern.
    ///
    /// Examples:
    /// ```ds
    /// Some(value) | Ok(value)
    /// ```
    Union {
        /// The alternative patterns.
        patterns: Vec<TermId<PatternTerm>>,
    },
}

/// One field inside a pattern.
///
/// Examples:
/// ```ds
/// { name }
/// [head, ...tail]
/// ```
#[derive(Debug, Clone, Copy, PartialEq)]
pub(in crate::check) enum PatternField {
    /// Named field.
    ///
    /// Examples:
    /// ```ds
    /// { name }
    /// ```
    Named {
        /// The source pattern field node.
        source: dir::GlobalNodeIdAny,
        /// The selected key.
        key: dir::StaticKey,
        /// The shorthand binding symbol.
        binding: Option<dir::GlobalSymbolId>,
        /// The resolved field type.
        value: Option<VariableId>,
        /// The field pattern.
        pattern: Option<TermId<PatternTerm>>,
    },
    /// Computed field.
    ///
    /// Examples:
    /// ```ds
    /// { [key]: value }
    /// ```
    Computed {
        /// The source pattern field node.
        source: dir::GlobalNodeIdAny,
        /// The computed key type.
        key: TypeOperand,
        /// The field pattern.
        pattern: TermId<PatternTerm>,
    },
    /// Positional field.
    ///
    /// Examples:
    /// ```ds
    /// [head]
    /// ```
    Positional {
        /// The source pattern field node.
        source: dir::GlobalNodeIdAny,
        /// The field pattern.
        pattern: TermId<PatternTerm>,
    },
    /// Spread field.
    ///
    /// Examples:
    /// ```ds
    /// [...rest]
    /// ```
    Spread {
        /// The source pattern field node.
        source: dir::GlobalNodeIdAny,
        /// The spread pattern.
        pattern: Option<TermId<PatternTerm>>,
    },
    /// Elided field.
    ///
    /// Examples:
    /// ```ds
    /// [, second]
    /// ```
    Elision {
        /// The source pattern field node.
        source: dir::GlobalNodeIdAny,
    },
}

/// Assignment target pattern checked against an assigned value type.
///
/// Examples:
/// ```ds
/// target = value
/// [head, ...tail] = values
/// ```
#[derive(Debug, Clone, PartialEq)]
pub(in crate::check) enum AssignPatternTerm {
    /// Expression assignment target.
    ///
    /// Examples:
    /// ```ds
    /// target = value
    /// ```
    Expression {
        /// The target storage type.
        target: TypeOperand,
    },
    /// Defaulted assignment target.
    ///
    /// Examples:
    /// ```ds
    /// target = fallback
    /// ```
    Assign {
        /// The target pattern.
        pattern: TermId<AssignPatternTerm>,
        /// The default value type.
        value: TypeOperand,
    },
    /// Sequence destructuring target.
    ///
    /// Examples:
    /// ```ds
    /// [head, ...tail] = values
    /// ```
    Sequence {
        /// The sequence fields.
        fields: SmallVec<[AssignPatternField; 8]>,
    },
    /// Object destructuring target.
    ///
    /// Examples:
    /// ```ds
    /// { name } = user
    /// ```
    Object {
        /// The object fields.
        fields: SmallVec<[AssignPatternField; 8]>,
    },
}

