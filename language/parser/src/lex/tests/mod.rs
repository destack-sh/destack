use std::sync::Arc;

use crate::{Lexer, Parser, ParserOptions, ParserTriviaMode};
use destack_core::StringPool;
use destack_dir::{NumberBase, Token, TokenLiteral, TokenSpan, TokenType, render_tokens};
use destack_source::{File, FileId, FileType, LanguageType, Span, Uri};

/// Lex the given source input string into its constituent tokens and side tokens.
fn lex_source(input: &str, language: LanguageType) -> (Vec<TokenSpan>, Vec<TokenSpan>, TokenSpan) {
    let file = File::from_text(
        FileId::new(0),
        "<string>".to_string(),
        Uri::from_string("<string>"),
        None,
        FileType::Destack,
        input.to_string(),
    );
    Lexer::lex(Arc::new(file), language)
}

fn lex_source_tokens(input: &str, language: LanguageType) -> (Vec<Token>, Vec<Token>) {
    let (semantic_tokens, side_tokens, _) = lex_source(input, language);
    let semantic_tokens = semantic_tokens
        .into_iter()
        .map(|token| token_without_line_boundary(token.token))
        .collect();
    let side_tokens = side_tokens
        .into_iter()
        .map(|token| token_without_line_boundary(token.token))
        .collect();

    (semantic_tokens, side_tokens)
}

fn token_without_line_boundary(token: Token) -> Token {
    token.with_on_new_line(false)
}

fn assert_single_string_literal_token(
    input: &str,
    language: LanguageType,
    has_invalid_escape: bool,
) {
    let (semantic_tokens, side_tokens) = lex_source_tokens(input, language);

    assert_eq!(
        semantic_tokens,
        vec![
            Token::new(
                TokenType::Literal,
                input.len() as u32,
                Some(TokenLiteral::String {
                    is_terminated: true,
                    has_invalid_escape,
                }),
            ),
            Token::end(),
        ],
    );

    assert_eq!(side_tokens, vec![]);
}

fn assert_legacy_string_escape_is_invalid_across_languages(input: &str) {
    for language in [
        LanguageType::default(),
        LanguageType::TypeScript,
        LanguageType::TypeScriptXml,
        LanguageType::JavaScript,
        LanguageType::JavaScriptXml,
    ] {
        assert_single_string_literal_token(input, language, true);
    }
}

fn lex_source_with_tree_literals(
    input: &str,
    language: LanguageType,
) -> (Vec<TokenSpan>, Vec<TokenSpan>, TokenSpan) {
    let file = File::from_text(
        FileId::new(0),
        "<string>".to_string(),
        Uri::from_string("<string>"),
        None,
        FileType::Destack,
        input.to_string(),
    );
    let file = Arc::new(file);
    let eof_token = TokenSpan {
        token: Token::end(),
        span: Span::new(file.id, file.len, file.len),
    };
    let mut parser = Parser::lex_file_with_options(
        file,
        language,
        ParserOptions {
            trivia_mode: ParserTriviaMode::Full,
            ..ParserOptions::default()
        },
        Arc::new(StringPool::new()),
    );

    // parse without attaching comments so parser drives tree child tokenization like production code
    let _ = parser.parse_without_attaching_comments();
    let (semantic_tokens, side_tokens) = parser.take_tokens();

    (semantic_tokens, side_tokens, eof_token)
}

/// Assert that the tokens generated by `tokenize` match the expected tokens.
macro_rules! assert_tokenize_eq_roundtrip {
    ($src:expr, $($expected:expr),* $(,)?) => {
        use TokenSpan;
        // tokenize
        let language = LanguageType::default();
        let (semantic_tokens, side_tokens, _) = lex_source($src, language);

        // merge and sort by position to get all tokens in order
        let mut all_tokens: Vec<TokenSpan> = semantic_tokens.into_iter().chain(side_tokens).collect();
        all_tokens.sort_by_key(|t| t.span.start);
        let tokens: Vec<Token> = all_tokens
            .into_iter()
            .map(|token| token_without_line_boundary(token.token))
            .collect();

        // must match the expected tokens
        let mut expected_tokens = vec![$($expected),*];

        // ensure the last token is an EOF token
        if !matches!(expected_tokens.last(), Some(token) if token.ty == TokenType::End) {
            expected_tokens.push(Token::end());
        }
        assert_eq!(tokens, expected_tokens);

        // render back to input string
        let rendered_input = render_tokens(&tokens, $src);
        assert_eq!(rendered_input, $src);

        // re-tokenize on the rendered input
        let (semantic_again, side_again, _) = lex_source(&rendered_input, language);
        let mut all_again: Vec<TokenSpan> = semantic_again.into_iter().chain(side_again).collect();
        all_again.sort_by_key(|t| t.span.start);
        let tokens_again: Vec<Token> = all_again
            .into_iter()
            .map(|token| token_without_line_boundary(token.token))
            .collect();
        assert_eq!(tokens_again, tokens);
    };
}

