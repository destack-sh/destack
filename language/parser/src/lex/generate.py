#!/usr/bin/env python3
"""Generate the Rust HTML entity lookup table for the lexer."""

import json
import os
import sys
from pathlib import Path
from typing import Iterable
from urllib.request import urlopen


ENTITIES_URL = "https://html.spec.whatwg.org/entities.json"

def _ensure_entities_json(target: Path) -> None:
    if target.exists():
        return

    print(f"Downloading {ENTITIES_URL} -> {target}")
    data = urlopen(ENTITIES_URL, timeout=60).read()
    target.write_bytes(data)


def _load_entities(raw_json: Path) -> list[tuple[str, int]]:
    with raw_json.open("r", encoding="utf-8") as handle:
        entities = json.load(handle)

    seen: dict[str, int] = {}
    for key, payload in entities.items():
        if not (key.startswith("&") and key.endswith(";")):
            continue

        codepoints = payload.get("codepoints")
        if not codepoints or len(codepoints) != 1:
            continue

        codepoint = int(codepoints[0])
        if 0xD800 <= codepoint <= 0xDFFF:
            continue

        name = key[1:-1]
        seen.setdefault(name, codepoint)

    return sorted(seen.items(), key=lambda item: item[0])


def _generate_rust(entries: Iterable[tuple[str, int]], destination: Path) -> None:
    entries = list(entries)
    count = len(entries)

    with destination.open("w", encoding="utf-8") as handle:
        handle.write(
            "// NOTE: DO NOT EDIT. Generated by generate.py\n"
        )
        handle.write("#![allow(clippy::too_many_lines)]\n")
        handle.write("#![allow(clippy::large_const_arrays)]\n")
        handle.write(
            f"pub(crate) const HTML_NAMED_ENTITIES: [(&str, char); {count}] = [\n"
        )
        for name, codepoint in entries:
            handle.write(f"    (\"{name}\", '\\u{{{codepoint:X}}}'),\n")
        handle.write("];\n")


def main() -> None:
    script_dir = Path(__file__).resolve().parent
    raw_json = script_dir / "html_entities.json"
    _ensure_entities_json(raw_json)

    entries = _load_entities(raw_json)
    if not entries:
        print("No HTML entities parsed", file=sys.stderr)
        sys.exit(1)

    destination = script_dir / "html_entities.rs"
    _generate_rust(entries, destination)

    os.system("cargo fmt")


if __name__ == "__main__":
    main()

