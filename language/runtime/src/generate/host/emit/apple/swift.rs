/// Build one Swift ingress sender with explicit parameters.
fn build_validate_ingress_swift_method(
    documentation: &'static str,
    qualifiers: Vec<&'static str>,
    name: &'static str,
    parameters: Vec<SwiftBridgeParameter>,
    bindings_method: &'static str,
    arguments: Vec<&'static str>,
    operation: &'static str,
) -> SwiftBridgeMethod {
    let mut body_lines = vec![
        format!("let status = bindings.{bindings_method}("),
        "  sessionHandle: sessionHandle,".to_string(),
    ];

    for (index, argument) in arguments.iter().enumerate() {
        let trailing = if index + 1 == arguments.len() {
            ""
        } else {
            ","
        };
        body_lines.push(format!("  {argument}{trailing}"));
    }

    body_lines.extend([
        ")".to_string(),
        String::new(),
        "validateRuntimeIngressStatus(".to_string(),
        "  status,".to_string(),
        format!("  operation: \"{operation}\""),
        ")".to_string(),
    ]);

    SwiftBridgeMethod {
        documentation: documentation.to_string(),
        qualifiers,
        name: name.to_string(),
        parameters,
        return_type: None,
        body_lines,
    }
}

