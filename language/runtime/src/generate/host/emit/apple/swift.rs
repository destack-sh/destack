pub(super) fn render_swift_runtime_bridge(modules: &[&HostModule]) -> String {
    let mut output = String::new();

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("import RuntimeHostAppleBridgeC\n");
    output.push_str("import RuntimeHostAppleCore\n\n");
    push_swift_doc_comment(
        &mut output,
        "One generated iOS runtime-bridge base carrying the shared host lane glue.",
        0,
    );
    output.push_str("@MainActor\n");
    output.push_str("public class GeneratedRuntimeBridge {\n");
    output.push_str("  let sessionHandle: HostSessionHandle\n");
    output.push_str("  let runtimeApi: any RuntimeIngress\n\n");
    push_swift_doc_comment(&mut output, "Create one generated runtime-bridge base.", 2);
    output.push_str("  init(\n");
    output.push_str("    sessionHandle: HostSessionHandle,\n");
    output.push_str("    runtimeApi: any RuntimeIngress\n");
    output.push_str("  ) {\n");
    output.push_str("    self.sessionHandle = sessionHandle\n");
    output.push_str("    self.runtimeApi = runtimeApi\n");
    output.push_str("  }\n");

    if !modules.is_empty() {
        output.push('\n');
    }

    let mut is_first_method = true;
    for module in modules {
        if let Some(ingress) = module.single_ingress() {
            if !is_first_method {
                output.push('\n');
            }

            render_swift_runtime_bridge_ingress_method(&mut output, module, ingress);
            is_first_method = false;
        }

        for request in module.requests() {
            if !is_first_method {
                output.push('\n');
            }

            render_swift_runtime_bridge_request_method(&mut output, module, request);
            is_first_method = false;
        }
    }

    output.push_str("}\n");
    output
}

pub(super) fn render_swift_runtime_abi(ingress_modules: &[&HostModule]) -> String {
    let mut output = String::new();

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("import Foundation\n");
    output.push_str("import RuntimeHostAppleBridgeC\n");
    output.push_str("import RuntimeHostAppleCore\n\n");
    push_swift_doc_comment(
        &mut output,
        "One generated low-level runtime ABI surface for one iOS host bridge.",
        0,
    );
    output.push_str("protocol RuntimeAbi {\n");

    for module in ingress_modules {
        render_swift_runtime_abi_protocol_method(&mut output, module);
        output.push('\n');
    }

    push_swift_doc_comment(
        &mut output,
        "Attach one bridge instance to one runtime session.",
        2,
    );
    output.push_str("  func attachBridge(\n");
    output.push_str("    sessionHandle: HostSessionHandle,\n");
    output.push_str("    bridge: RuntimeBridge\n");
    output.push_str("  ) -> HostAbiStatus\n\n");

    push_swift_doc_comment(
        &mut output,
        "Detach one bridge instance from one runtime session.",
        2,
    );
    output.push_str("  func detachBridge(\n");
    output.push_str("    sessionHandle: HostSessionHandle\n");
    output.push_str("  )\n");
    output.push_str("}\n\n");

    push_swift_doc_comment(
        &mut output,
        "One generated default runtime ABI surface loaded through the iOS bridge C shim.",
        0,
    );
    output.push_str("final class ProcessRuntimeAbi: RuntimeAbi, @unchecked Sendable {\n");
    push_swift_doc_comment(
        &mut output,
        "Attach one bridge instance to one runtime session.",
        2,
    );
    output.push_str("  func attachBridge(\n");
    output.push_str("    sessionHandle: HostSessionHandle,\n");
    output.push_str("    bridge: RuntimeBridge\n");
    output.push_str("  ) -> HostAbiStatus {\n");
    output.push_str("    return destack_runtime_host_ios_register_runtime_bridge_bindings(\n");
    output.push_str("      sessionHandle.rawValue,\n");
    output.push_str("      makeGeneratedRuntimeBridgeBindings()\n");
    output.push_str("    )\n");
    output.push_str("  }\n\n");

    push_swift_doc_comment(
        &mut output,
        "Detach one bridge instance from one runtime session.",
        2,
    );
    output.push_str("  func detachBridge(\n");
    output.push_str("    sessionHandle: HostSessionHandle\n");
    output.push_str("  ) {\n");
    output.push_str(
        "    destack_runtime_host_ios_unregister_runtime_bridge_bindings(sessionHandle.rawValue)\n",
    );
    output.push_str("  }\n");

    if !ingress_modules.is_empty() {
        output.push('\n');
    }

    for (index, module) in ingress_modules.iter().enumerate() {
        render_swift_runtime_abi_impl_method(&mut output, module);
        if index + 1 != ingress_modules.len() {
            output.push('\n');
        }
    }

    output.push_str("}\n");

    output
}

/// Render one generated Swift ABI bridge file.
pub(super) fn render_swift_abi(module: &HostModule) -> String {
    let mut output = String::new();
    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("import Foundation\n");
    output.push_str("import RuntimeHostAppleBridgeC\n");
    output.push_str("import RuntimeHostAppleCore\n\n");

    for request in module.requests() {
        push_swift_doc_comment(&mut output, request.documentation(), 0);
        output.push_str(&format!(
            "typealias {} =\n",
            apple_swift_callback_type_name(module.abi(), request.abi())
        ));
        output.push_str("  @convention(c) (\n");

        for (index, parameter) in request.parameters().iter().enumerate() {
            let trailing = if index + 1 == request.parameters().len() {
                ""
            } else {
                ","
            };
            output.push_str("    ");
            output.push_str(&render_apple_swift_callback_type(&parameter.ty));
            output.push_str(trailing);
            output.push('\n');
        }

        output.push_str("  ) -> ");
        output.push_str(&render_apple_swift_callback_result_type(
            &request.abi().result,
        ));
        output.push_str("\n\n");
    }

    for request in module.requests() {
        render_swift_callback_binding(&mut output, module.abi(), request.abi());
        output.push('\n');
    }

    render_swift_callback_bundle(&mut output, module.abi());
    output.push('\n');
    render_swift_request_handlers(&mut output, module);
    output.push('\n');
    render_swift_helper_section(&mut output, module.abi());
    while output.ends_with("\n\n") {
        output.pop();
    }

    output
}

fn render_swift_runtime_abi_protocol_method(output: &mut String, module: &HostModule) {
    let ingress = module
        .single_ingress()
        .expect("expected one ingress while rendering aggregate Swift runtime ABI");

    render_swift_ingress_signature(output, module, ingress, 2);
}

fn render_swift_runtime_abi_impl_method(output: &mut String, module: &HostModule) {
    let ingress = module
        .single_ingress()
        .expect("expected one ingress while rendering aggregate Swift runtime ABI");

    render_swift_ingress_signature(output, module, ingress, 2);
    output.push_str(" {\n");
    render_swift_ingress_body(output, module, ingress, 4);
    output.push_str("  }\n");
}

/// Render one generated Swift runtime ingress forwarder.
fn render_swift_runtime_bridge_ingress_method(
    output: &mut String,
    module: &HostModule,
    ingress: &HostIngress,
) {
    render_swift_ingress_signature(output, module, ingress, 2);
    output.push_str(" {\n");
    render_swift_ingress_body(output, module, ingress, 4);
    output.push_str("  }\n");
}

/// Render one generated Swift runtime-host request forwarder.
fn render_swift_runtime_bridge_request_method(
    output: &mut String,
    module: &HostModule,
    request: &HostRequest,
) {
    let return_type = apple_swift_request_return_type(module.abi(), request);
    let method_name = apple_runtime_bridge_method_name(module.abi(), request.abi());
    let module_name = apple_swift_parameter_label(module.name());
    let target_name = apple_swift_parameter_label(request.name());

    push_swift_doc_comment(output, request.documentation(), 2);
    output.push_str(&format!("  public func {method_name}(\n"));
    output.push_str("    runtimeHost: RuntimeHost");

    let input_parameters = request.input_parameters();
    if input_parameters.is_empty() {
        output.push('\n');
        output.push_str(&format!("  ) -> {return_type} {{\n"));
    } else {
        output.push_str(",\n");
        for (index, parameter) in input_parameters.iter().enumerate() {
            let trailing = if index + 1 == input_parameters.len() {
                ""
            } else {
                ","
            };
            let label = apple_swift_parameter_label(parameter.name);
            let parameter_type = render_apple_swift_native_type(module.abi(), &parameter.ty);
            let external_label = if index == 0 { "_" } else { &label };

            output.push_str(&format!(
                "    {external_label} {label}: {parameter_type}{trailing}\n"
            ));
        }
        output.push_str(&format!("  ) -> {return_type} {{\n"));
    }

    output.push_str(&format!(
        "    return runtimeHost.{module_name}.{target_name}("
    ));
    for (index, parameter) in input_parameters.iter().enumerate() {
        let label = apple_swift_parameter_label(parameter.name);

        if index > 0 {
            output.push_str(", ");
        }

        if index == 0 {
            output.push_str(&label);
        } else {
            output.push_str(&format!("{label}: {label}"));
        }
    }
    output.push_str(")\n");
    output.push_str("  }\n");
}

/// Render one generated Swift encoding-helper section.
fn render_swift_helper_section(output: &mut String, module: &HostAbiModule) {
    if module.types.is_empty() {
        return;
    }
    let decode_names = collect_apple_request_decode_named_types(module);
    let slice_names = collect_apple_native_slice_named_types(module);
    let uses_u8_slice =
        apple_module_uses_type(module, &HostAbiType::NativeSlice(Box::new(HostAbiType::U8)));
    let uses_i8_slice =
        apple_module_uses_type(module, &HostAbiType::NativeSlice(Box::new(HostAbiType::I8)));
    let uses_i16_slice = apple_module_uses_type(
        module,
        &HostAbiType::NativeSlice(Box::new(HostAbiType::I16)),
    );
    let decode_slice_names: Vec<_> = slice_names
        .iter()
        .copied()
        .filter(|name| decode_names.contains(name))
        .collect();

    render_swift_bridge_arena(output, module);
    output.push('\n');

    for name in &decode_names {
        let named_type = apple_named_type(module, name);
        if let HostAbiNamedTypeDefinition::Enum { .. } = named_type.definition {
            render_swift_enum_decode_helper(output, &named_type);
            output.push('\n');
        }
    }

    for name in &decode_names {
        let named_type = apple_named_type(module, name);
        if let HostAbiNamedTypeDefinition::Struct { .. } = named_type.definition {
            render_swift_struct_decode_helper(output, module, &named_type);
            output.push('\n');
        }
    }

    for name in &decode_slice_names {
        render_swift_named_slice_decode_helper(output, module, name);
        output.push('\n');
    }

    if uses_u8_slice {
        render_swift_primitive_slice_decode_helper(output, &HostAbiType::U8);
        output.push('\n');
    }
    if uses_i8_slice {
        render_swift_primitive_slice_decode_helper(output, &HostAbiType::I8);
        output.push('\n');
    }
    if uses_i16_slice {
        render_swift_primitive_slice_decode_helper(output, &HostAbiType::I16);
        output.push('\n');
    }

    for named_type in &module.types {
        if let HostAbiNamedTypeDefinition::Enum { .. } = named_type.definition {
            render_swift_enum_encode_helper(output, named_type);
            output.push('\n');

            if slice_names.contains(named_type.name) {
                render_swift_named_slice_encode_helper(output, module, named_type);
                output.push('\n');
                render_swift_named_slice_with_native_helper(output, module, named_type);
                output.push('\n');
            }
        }
    }

    for named_type in &module.types {
        if let HostAbiNamedTypeDefinition::Struct { .. } = named_type.definition {
            render_swift_struct_encode_helper(output, module, named_type);
            output.push('\n');
            render_swift_named_with_native_helper(output, module, named_type);
            output.push('\n');
            if slice_names.contains(named_type.name) {
                render_swift_named_slice_encode_helper(output, module, named_type);
                output.push('\n');
                render_swift_named_slice_with_native_helper(output, module, named_type);
                output.push('\n');
            }
        }
    }

    if uses_u8_slice {
        render_swift_primitive_slice_encode_helper(output, module, &HostAbiType::U8);
        output.push('\n');
    }
    if uses_i8_slice {
        render_swift_primitive_slice_encode_helper(output, module, &HostAbiType::I8);
        output.push('\n');
    }
    if uses_i16_slice {
        render_swift_primitive_slice_encode_helper(output, module, &HostAbiType::I16);
        output.push('\n');
    }
}

/// Collect the named ABI types reachable from request input payloads.
fn collect_apple_request_decode_named_types(module: &HostAbiModule) -> Vec<&'static str> {
    let mut names = Vec::new();

    for request in &module.requests {
        for parameter in &request.parameters {
            if matches!(
                parameter.ty,
                HostAbiType::HostSessionHandle | HostAbiType::OutputPointer(_)
            ) {
                continue;
            }

            collect_apple_request_decode_names_from_type(module, &parameter.ty, &mut names);
        }
    }

    names
}

/// Collect the named ABI types reachable from one request input type.
fn collect_apple_request_decode_names_from_type(
    module: &HostAbiModule,
    ty: &HostAbiType,
    names: &mut Vec<&'static str>,
) {
    match ty {
        HostAbiType::Named(name) => {
            if names.iter().any(|existing| existing == name) {
                return;
            }

            names.push(name);

            if let HostAbiNamedTypeDefinition::Struct { fields } =
                apple_named_type(module, name).definition
            {
                for field in fields {
                    collect_apple_request_decode_names_from_type(module, &field.ty, names);
                }
            }
        }
        HostAbiType::Optional(inner) => {
            collect_apple_request_decode_names_from_type(module, inner, names);
        }
        HostAbiType::NativeArray(inner)
        | HostAbiType::NativeSlice(inner)
        | HostAbiType::OutputPointer(inner) => {
            collect_apple_request_decode_names_from_type(module, inner, names);
        }
        _ => {}
    }
}

/// Collect the named ABI types used as native slices in one module surface.
fn collect_apple_native_slice_named_types(module: &HostAbiModule) -> BTreeSet<&'static str> {
    let mut names = BTreeSet::new();

    for request in &module.requests {
        for parameter in &request.parameters {
            collect_apple_native_slice_names_from_type(module, &parameter.ty, &mut names);
        }

        collect_apple_native_slice_names_from_type(module, &request.result, &mut names);
    }

    for ingress in &module.ingress {
        for parameter in &ingress.parameters {
            collect_apple_native_slice_names_from_type(module, &parameter.ty, &mut names);
        }
    }

    names
}

/// Collect the named ABI types used as native slices in one ABI type.
fn collect_apple_native_slice_names_from_type(
    module: &HostAbiModule,
    ty: &HostAbiType,
    names: &mut BTreeSet<&'static str>,
) {
    match ty {
        HostAbiType::Named(name) => {
            if let HostAbiNamedTypeDefinition::Struct { fields } =
                apple_named_type(module, name).definition
            {
                for field in fields {
                    collect_apple_native_slice_names_from_type(module, &field.ty, names);
                }
            }
        }
        HostAbiType::NativeSlice(inner) => {
            if let HostAbiType::Named(name) = inner.as_ref() {
                names.insert(name);
            }

            collect_apple_native_slice_names_from_type(module, inner, names);
        }
        HostAbiType::OutputPointer(inner) => {
            collect_apple_native_slice_names_from_type(module, inner, names);
        }
        _ => {}
    }
}

/// Return whether one module uses one nested ABI type anywhere in its surface.
fn apple_module_uses_type(module: &HostAbiModule, ty: &HostAbiType) -> bool {
    module
        .types
        .iter()
        .any(|named_type| apple_named_type_uses_type(module, named_type, ty))
        || module.requests.iter().any(|request| {
            request.result == *ty
                || request
                    .parameters
                    .iter()
                    .any(|parameter| apple_type_contains_type(module, &parameter.ty, ty))
        })
        || module.ingress.iter().any(|ingress| {
            ingress.result == *ty
                || ingress
                    .parameters
                    .iter()
                    .any(|parameter| apple_type_contains_type(module, &parameter.ty, ty))
        })
}

/// Return whether one named type contains one nested ABI type.
fn apple_named_type_uses_type(
    module: &HostAbiModule,
    named_type: &HostAbiNamedType,
    ty: &HostAbiType,
) -> bool {
    match &named_type.definition {
        HostAbiNamedTypeDefinition::Struct { fields } => fields
            .iter()
            .any(|field| apple_type_contains_type(module, &field.ty, ty)),
        HostAbiNamedTypeDefinition::Enum { .. } => false,
        HostAbiNamedTypeDefinition::TaggedEnum { variants } => variants.iter().any(|variant| {
            apple_type_contains_type(module, &HostAbiType::Named(variant.payload_type), ty)
        }),
    }
}

/// Return whether one ABI type contains one nested ABI type.
fn apple_type_contains_type(
    module: &HostAbiModule,
    outer: &HostAbiType,
    inner: &HostAbiType,
) -> bool {
    if outer == inner {
        return true;
    }

    match outer {
        HostAbiType::Named(name) if !apple_named_type_is_enum(module, name) => module
            .types
            .iter()
            .find(|named_type| named_type.name == *name)
            .map(|named_type| apple_named_type_uses_type(module, named_type, inner))
            .unwrap_or(false),
        HostAbiType::NativeArray(element)
        | HostAbiType::NativeSlice(element)
        | HostAbiType::OutputPointer(element) => apple_type_contains_type(module, element, inner),
        _ => false,
    }
}

/// Return the generated Swift bridge arena type name for one module.
fn apple_swift_bridge_arena_name(module: &HostAbiModule) -> String {
    format!("{}BridgeArena", apple_pascal_case(module.name))
}

/// Return the generated Swift bridge arena accessor for one module.
fn apple_swift_current_bridge_arena_name(module: &HostAbiModule) -> String {
    format!("current{}BridgeArena", apple_pascal_case(module.name))
}

/// Render one generated Swift bridge arena.
fn render_swift_bridge_arena(output: &mut String, module: &HostAbiModule) {
    let arena_name = apple_swift_bridge_arena_name(module);
    let current_arena_name = apple_swift_current_bridge_arena_name(module);

    push_swift_doc_comment(
        output,
        "One temporary native allocation arena for one bridge callback.",
        0,
    );
    output.push_str(&format!("final class {arena_name} {{\n"));
    output.push_str("  /// The raw deallocation actions recorded for this callback.\n");
    output.push_str("  private var deallocations: [() -> Void] = []\n\n");
    output.push_str(
        "  /// Remove every recorded allocation before one new callback payload is encoded.\n",
    );
    output.push_str("  func reset() {\n");
    output.push_str("    for deallocate in deallocations.reversed() {\n");
    output.push_str("      deallocate()\n");
    output.push_str("    }\n\n");
    output.push_str("    deallocations.removeAll(keepingCapacity: true)\n");
    output.push_str("  }\n\n");
    output.push_str("  /// Release every recorded native allocation.\n");
    output.push_str("  deinit {\n");
    output.push_str("    for deallocate in deallocations.reversed() {\n");
    output.push_str("      deallocate()\n");
    output.push_str("    }\n");
    output.push_str("  }\n\n");
    output.push_str("  /// Allocate one copied UTF-8 buffer for one Swift string.\n");
    output.push_str("  func makeStringRef(\n");
    output.push_str("    _ value: String\n");
    output.push_str("  ) -> DestackRustStringRef {\n");
    output.push_str("    let bytes = Array(value.utf8)\n");
    output.push_str("    if bytes.isEmpty {\n");
    output.push_str("      return DestackRustStringRef(data: nil, len: 0)\n");
    output.push_str("    }\n\n");
    output.push_str(
        "    let storage = UnsafeMutablePointer<UInt8>.allocate(capacity: bytes.count)\n",
    );
    output.push_str("    storage.initialize(from: bytes, count: bytes.count)\n");
    output.push_str("    deallocations.append {\n");
    output.push_str("      storage.deinitialize(count: bytes.count)\n");
    output.push_str("      storage.deallocate()\n");
    output.push_str("    }\n\n");
    output.push_str("    return DestackRustStringRef(\n");
    output.push_str("      data: UnsafePointer(storage),\n");
    output.push_str("      len: UInt32(bytes.count)\n");
    output.push_str("    )\n");
    output.push_str("  }\n\n");
    output.push_str("  /// Allocate one copied string-slice payload.\n");
    output.push_str("  func makeStringSlice(\n");
    output.push_str("    _ values: [String]\n");
    output.push_str("  ) -> DestackRustStringSlice {\n");
    output.push_str("    let data = makeArray(count: values.count) { buffer in\n");
    output.push_str("      for (index, value) in values.enumerated() {\n");
    output.push_str("        buffer[index] = makeStringRef(value)\n");
    output.push_str("      }\n");
    output.push_str("    }\n\n");
    output.push_str("    return DestackRustStringSlice(\n");
    output.push_str("      data: data,\n");
    output.push_str("      len: UInt32(values.count)\n");
    output.push_str("    )\n");
    output.push_str("  }\n\n");
    output
        .push_str("  /// Allocate one copied native array and fill it with one builder closure.\n");
    output.push_str("  func makeArray<Element>(\n");
    output.push_str("    count: Int,\n");
    output.push_str("    fill: (UnsafeMutableBufferPointer<Element>) -> Void\n");
    output.push_str("  ) -> UnsafeMutablePointer<Element>? {\n");
    output.push_str("    if count == 0 {\n");
    output.push_str("      return nil\n");
    output.push_str("    }\n\n");
    output.push_str("    let storage = UnsafeMutablePointer<Element>.allocate(capacity: count)\n");
    output.push_str("    let buffer = UnsafeMutableBufferPointer(start: storage, count: count)\n");
    output.push_str("    fill(buffer)\n");
    output.push_str("    deallocations.append {\n");
    output.push_str("      storage.deinitialize(count: count)\n");
    output.push_str("      storage.deallocate()\n");
    output.push_str("    }\n\n");
    output.push_str("    return storage\n");
    output.push_str("  }\n");
    output.push_str("}\n\n");

    let key = format!("dev.destack.runtime.apple.{}-bridge-arena", module.name);
    push_swift_doc_comment(
        output,
        "Return the thread-local bridge arena for one callback thread.",
        0,
    );
    output.push_str(&format!("func {current_arena_name}() -> {arena_name} {{\n"));
    output.push_str("  let dictionary = Thread.current.threadDictionary\n");
    output.push_str(&format!("  let key = \"{key}\"\n\n"));
    output.push_str(&format!(
        "  if let arena = dictionary[key] as? {arena_name} {{\n"
    ));
    output.push_str("    arena.reset()\n\n");
    output.push_str("    return arena\n");
    output.push_str("  }\n\n");
    output.push_str(&format!("  let arena = {arena_name}()\n"));
    output.push_str("  dictionary[key] = arena\n\n");
    output.push_str("  return arena\n");
    output.push_str("}\n");
}

/// Render one generic Swift enum decode helper.
fn render_swift_enum_decode_helper(output: &mut String, named_type: &HostAbiNamedType) {
    let HostAbiNamedTypeDefinition::Enum { repr, .. } = &named_type.definition else {
        panic!("expected Apple enum helper for {}", named_type.name);
    };

    let runtime_name = apple_swift_named_type(named_type.name);
    let raw_value = match repr {
        HostAbiEnumRepresentation::U32 | HostAbiEnumRepresentation::I32 => {
            ".init(value)".to_string()
        }
    };

    push_swift_doc_comment(
        output,
        &format!(
            "Build one Swift {} from one bridge raw value.",
            render_external_abi_name(named_type.name)
        ),
        0,
    );
    output.push_str(&format!(
        "func decodeBridge{}(\n  _ value: {}\n) throws -> {} {{\n",
        named_type.name,
        render_apple_swift_callback_type(&HostAbiType::Named(named_type.name)),
        runtime_name
    ));
    output.push_str(&format!(
        "  guard let value = {runtime_name}(rawValue: {raw_value}) else {{\n"
    ));
    output.push_str("    throw BridgeStringError.invalidStringSlice\n");
    output.push_str("  }\n\n");
    output.push_str("  return value\n");
    output.push_str("}\n");
}

/// Render one generic Swift struct decode helper.
fn render_swift_struct_decode_helper(
    output: &mut String,
    module: &HostAbiModule,
    named_type: &HostAbiNamedType,
) {
    let HostAbiNamedTypeDefinition::Struct { fields } = &named_type.definition else {
        panic!("expected Apple struct helper for {}", named_type.name);
    };
    let runtime_name = apple_swift_named_type(named_type.name);
    let can_throw = apple_type_decode_can_throw(module, &HostAbiType::Named(named_type.name));
    let throws_suffix = if can_throw { " throws" } else { "" };

    push_swift_doc_comment(
        output,
        &format!(
            "Build one Swift {} from one bridge payload.",
            render_external_abi_name(named_type.name)
        ),
        0,
    );
    output.push_str(&format!(
        "func decodeBridge{}(\n  _ value: {}\n){} -> {} {{\n",
        named_type.name,
        render_apple_swift_callback_type(&HostAbiType::Named(named_type.name)),
        throws_suffix,
        runtime_name
    ));
    output.push_str(&format!("  {runtime_name}(\n"));
    let mut field_lines = Vec::new();

    let mut index = 0;
    while index < fields.len() {
        let field = &fields[index];
        field_lines.push(format!(
            "    {}:\n      {}",
            apple_swift_parameter_label(field.name),
            render_swift_decode_value_expr(module, &format!("value.{}", field.name), &field.ty)
        ));
        index += 1;
    }

    for (index, field_line) in field_lines.iter().enumerate() {
        let trailing = if index + 1 == field_lines.len() {
            ""
        } else {
            ","
        };
        output.push_str(field_line);
        output.push_str(trailing);
        output.push('\n');
    }

    output.push_str("  )\n");
    output.push_str("}\n");
}

/// Render one generic Swift named-slice decode helper.
fn render_swift_named_slice_decode_helper(output: &mut String, module: &HostAbiModule, name: &str) {
    let named_type = apple_named_type(module, name);
    let decode_can_throw =
        apple_type_decode_can_throw(module, &HostAbiType::Named(named_type.name));
    let decode_prefix = if decode_can_throw { "try " } else { "" };
    let map_prefix = if decode_can_throw { "try " } else { "" };

    push_swift_doc_comment(
        output,
        &format!(
            "Build one Swift {} slice from one bridge payload.",
            render_external_abi_name(name)
        ),
        0,
    );
    output.push_str(&format!(
        "func decodeBridge{}Slice(\n  _ value: {}\n) throws -> [{}] {{\n",
        name,
        format!("DestackRust{}Slice", render_external_abi_name(name)),
        apple_swift_named_type(name),
    ));
    output.push_str("  if value.len == 0 {\n");
    output.push_str("    return []\n");
    output.push_str("  }\n\n");
    output.push_str("  guard let data = value.data else {\n");
    output.push_str("    throw BridgeStringError.invalidStringSlice\n");
    output.push_str("  }\n\n");
    output.push_str("  let buffer = UnsafeBufferPointer(\n");
    output.push_str("    start: data,\n");
    output.push_str("    count: Int(value.len)\n");
    output.push_str("  )\n\n");
    output.push_str("  return ");
    output.push_str(map_prefix);
    output.push_str("buffer.map { ");
    output.push_str(decode_prefix);
    output.push_str(&format!("decodeBridge{name}($0)"));
    output.push_str(" }\n");
    output.push_str("}\n");
}

/// Render one Swift decode expression for one ABI field.
fn render_swift_decode_value_expr(
    module: &HostAbiModule,
    source: &str,
    ty: &HostAbiType,
) -> String {
    match ty {
        HostAbiType::U8 | HostAbiType::U16 | HostAbiType::I8 | HostAbiType::I16 => {
            source.to_string()
        }
        HostAbiType::U32
        | HostAbiType::U64
        | HostAbiType::Bool
        | HostAbiType::F64
        | HostAbiType::HostStatus
        | HostAbiType::RuntimeStatus => source.to_string(),
        HostAbiType::I32 => format!("Int({source})"),
        HostAbiType::HostRequestId => format!("HostRequestID(rawValue: {source})"),
        HostAbiType::StringRef | HostAbiType::OsPath => {
            format!("try tryDecodeNativeString({source})")
        }
        HostAbiType::StringSlice => format!("try tryDecodeNativeStringSlice({source})"),
        HostAbiType::Named(name) => {
            let prefix = if apple_type_decode_can_throw(module, ty) {
                "try "
            } else {
                ""
            };
            format!("{prefix}decodeBridge{name}({source})")
        }
        HostAbiType::Optional(inner) => {
            render_swift_optional_decode_value_expr(module, source, inner)
        }
        HostAbiType::NativeSlice(inner) => {
            if apple_native_slice_uses_string_transport(inner) {
                format!("try tryDecodeNativeStringSlice({source})")
            } else if let HostAbiType::Named(name) = inner.as_ref() {
                format!("try decodeBridge{name}Slice({source})")
            } else if let Some(slice_suffix) = apple_primitive_slice_suffix(inner) {
                format!("decodeBridge{slice_suffix}Slice({source})")
            } else {
                panic!("unsupported Apple decode expression for {:?}", ty);
            }
        }
        other => panic!("unsupported Apple decode expression for {:?}", other),
    }
}

/// Render one Swift decode expression for one optional callback payload.
fn render_swift_optional_decode_value_expr(
    module: &HostAbiModule,
    source: &str,
    inner: &HostAbiType,
) -> String {
    let decode_expression = match inner {
        HostAbiType::U8
        | HostAbiType::U16
        | HostAbiType::I8
        | HostAbiType::I16
        | HostAbiType::U32
        | HostAbiType::U64
        | HostAbiType::Bool
        | HostAbiType::F64
        | HostAbiType::HostStatus
        | HostAbiType::RuntimeStatus => format!("{source}.value"),
        HostAbiType::I32 => format!("Int({source}.value)"),
        HostAbiType::HostRequestId => format!("HostRequestID(rawValue: {source}.value)"),
        HostAbiType::StringRef | HostAbiType::OsPath => {
            format!("try tryDecodeNativeString({source}.value)")
        }
        HostAbiType::StringSlice => format!("try tryDecodeNativeStringSlice({source}.value)"),
        HostAbiType::Named(name) => {
            let prefix = if apple_type_decode_can_throw(module, inner) {
                "try "
            } else {
                ""
            };
            format!("{prefix}decodeBridge{name}({source}.value)")
        }
        HostAbiType::NativeSlice(element) => {
            if apple_native_slice_uses_string_transport(element) {
                format!("try tryDecodeNativeStringSlice({source}.value)")
            } else if let HostAbiType::Named(name) = element.as_ref() {
                format!("try decodeBridge{name}Slice({source}.value)")
            } else if let Some(slice_suffix) = apple_primitive_slice_suffix(element) {
                format!("decodeBridge{slice_suffix}Slice({source}.value)")
            } else {
                panic!(
                    "unsupported Apple optional decode expression for {:?}",
                    inner
                );
            }
        }
        other => panic!(
            "unsupported Apple optional decode expression for {:?}",
            other
        ),
    };

    format!("({source}.has_value ? Optional({decode_expression}) : nil)")
}

