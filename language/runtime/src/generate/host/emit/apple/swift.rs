/// Render one generated Swift bridge file.
#[allow(dead_code)]
fn render_swift_bridge_spec(bridge: &SwiftBridgeSpec) -> String {
    let mut output = String::new();

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    for import in &bridge.imports {
        output.push_str(&format!("import {import}\n"));
    }
    output.push('\n');
    push_swift_doc_comment(&mut output, &bridge.documentation, 0);
    output.push_str("@MainActor\n");
    output.push_str(&format!("final class {}", bridge.class_name));
    if let Some(protocol_name) = &bridge.implemented_protocol {
        output.push_str(&format!(": {protocol_name}"));
    }
    output.push_str(" {\n");

    for property in &bridge.stored_properties {
        output.push_str("  ");
        output.push_str(property);
        output.push('\n');
    }

    if !bridge.stored_properties.is_empty() {
        output.push('\n');
    }

    if !bridge.initializer_parameters.is_empty() {
        if let Some(documentation) = &bridge.initializer_documentation {
            push_swift_doc_comment(&mut output, documentation, 2);
        }
        output.push_str("  init(\n");
        for (index, parameter) in bridge.initializer_parameters.iter().enumerate() {
            output.push_str("    ");
            output.push_str(&render_swift_bridge_parameter(parameter));
            if index + 1 != bridge.initializer_parameters.len() {
                output.push(',');
            }
            output.push('\n');
        }
        output.push_str("  ) {\n");
        for assignment in &bridge.initializer_assignments {
            output.push_str("    ");
            output.push_str(assignment);
            output.push('\n');
        }
        output.push_str("  }\n");

        if !bridge.methods.is_empty() {
            output.push('\n');
        }
    }

    for (index, method) in bridge.methods.iter().enumerate() {
        render_swift_bridge_method(&mut output, method);
        if index + 1 != bridge.methods.len() {
            output.push('\n');
        }
    }

    output.push_str("}\n");

    output
}

/// Render one generated Swift bridge method.
fn render_swift_bridge_method(output: &mut String, method: &SwiftBridgeMethod) {
    let is_protocol_method = method.name.starts_with("send");

    push_swift_doc_comment(output, &method.documentation, 2);
    output.push_str("  ");
    if is_protocol_method {
        output.push_str("public ");
    }
    if !method.qualifiers.is_empty() {
        output.push_str(&format!("{} ", method.qualifiers.join(" ")));
    }
    output.push_str(&format!("func {}(\n", method.name));
    for (index, parameter) in method.parameters.iter().enumerate() {
        output.push_str("    ");
        output.push_str(&render_swift_bridge_parameter(parameter));
        if index + 1 != method.parameters.len() {
            output.push(',');
        }
        output.push('\n');
    }
    output.push_str("  )");
    if let Some(return_type) = &method.return_type {
        output.push_str(&format!(" -> {return_type}"));
    }
    output.push_str(" {\n");
    for line in &method.body_lines {
        if line.is_empty() {
            output.push('\n');
            continue;
        }
        output.push_str("    ");
        output.push_str(line);
        output.push('\n');
    }
    output.push_str("  }\n");
}

fn render_swift_runtime_ingress_signature(
    output: &mut String,
    runtime_ingress: &RuntimeIngress,
    indent: usize,
) {
    push_swift_doc_comment(output, runtime_ingress.documentation(), indent);
    output.push_str(&" ".repeat(indent));
    output.push_str(&format!("func {}(\n", runtime_ingress.method_name()));
    for (index, parameter) in runtime_ingress.parameters().iter().enumerate() {
        output.push_str(&" ".repeat(indent + 2));
        output.push_str(parameter.name);
        output.push_str(": ");
        output.push_str(parameter.ty.swift_name());
        if index + 1 != runtime_ingress.parameters().len() {
            output.push(',');
        }
        output.push('\n');
    }
    output.push_str(&" ".repeat(indent));
    output.push_str(") -> RuntimeAbiStatus");
}

fn render_swift_runtime_dispatch_case(output: &mut String, case: &RuntimeIngressDispatchCase) {
    output.push_str(&format!(
        "    case .{}(",
        apple_swift_parameter_label(case.variant_name)
    ));
    for (index, binding) in case.bindings.iter().enumerate() {
        if index != 0 {
            output.push_str(", ");
        }
        output.push_str(&format!("let {binding}"));
    }
    output.push_str("):\n");
    render_swift_runtime_binding_call_body(output, &case.call, 6);
}

fn render_swift_runtime_binding_call_body(
    output: &mut String,
    binding_call: &crate::host::model::RuntimeIngressBindingCall,
    indent: usize,
) {
    render_swift_runtime_binding_wrappers(output, binding_call, 0, indent);
}

fn render_swift_runtime_binding_wrappers(
    output: &mut String,
    binding_call: &crate::host::model::RuntimeIngressBindingCall,
    parameter_index: usize,
    indent: usize,
) {
    if parameter_index == binding_call.arguments.len() {
        render_swift_runtime_binding_terminal(output, binding_call, indent);
        return;
    }

    let parameter = &binding_call.binding.parameters[parameter_index + 1];
    let argument = &binding_call.arguments[parameter_index];
    let prefix = " ".repeat(indent);

    match parameter.ty {
        RuntimeBindingType::StringRef => {
            let parameter_label = apple_swift_runtime_binding_local_name(
                parameter.name,
                RuntimeBindingType::StringRef,
            );
            output.push_str(&format!(
                "{prefix}return withNativeStringRef({}) {{ {} in\n",
                render_swift_runtime_ingress_expr(argument),
                parameter_label
            ));
            render_swift_runtime_binding_wrappers(
                output,
                binding_call,
                parameter_index + 1,
                indent + 2,
            );
            output.push_str(&format!("{prefix}}}\n"));
        }
        RuntimeBindingType::StringSlice => {
            let parameter_label = apple_swift_runtime_binding_local_name(
                parameter.name,
                RuntimeBindingType::StringSlice,
            );
            output.push_str(&format!(
                "{prefix}return withNativeStringSlice({}) {{ {} in\n",
                render_swift_runtime_ingress_expr(argument),
                parameter_label
            ));
            render_swift_runtime_binding_wrappers(
                output,
                binding_call,
                parameter_index + 1,
                indent + 2,
            );
            output.push_str(&format!("{prefix}}}\n"));
        }
        _ => {
            render_swift_runtime_binding_wrappers(output, binding_call, parameter_index + 1, indent)
        }
    }
}

fn render_swift_runtime_binding_terminal(
    output: &mut String,
    binding_call: &crate::host::model::RuntimeIngressBindingCall,
    indent: usize,
) {
    let prefix = " ".repeat(indent);
    output.push_str(&format!(
        "{prefix}let status = destack_runtime_host_ios_{}(\n",
        binding_call.binding.field_name
    ));
    output.push_str(&format!("{prefix}  sessionHandle.rawValue"));

    for (parameter, argument) in binding_call
        .binding
        .parameters
        .iter()
        .skip(1)
        .zip(&binding_call.arguments)
    {
        output.push_str(",\n");
        output.push_str(&format!(
            "{prefix}  {}",
            render_swift_runtime_binding_argument(parameter.ty, parameter.name, argument)
        ));
    }

    output.push_str(&format!("\n{prefix})\n\n"));
    output.push_str(&format!("{prefix}return RuntimeAbiStatus(\n"));
    output.push_str(&format!("{prefix}  code: status.code,\n"));
    output.push_str(&format!("{prefix}  errorID: status.error_id\n"));
    output.push_str(&format!("{prefix})\n"));
}

fn render_swift_runtime_binding_argument(
    binding_type: RuntimeBindingType,
    parameter_name: &str,
    argument: &RuntimeIngressExpr,
) -> String {
    match binding_type {
        RuntimeBindingType::StringRef | RuntimeBindingType::StringSlice => {
            apple_swift_runtime_binding_local_name(parameter_name, binding_type)
        }
        RuntimeBindingType::LocationSample => {
            let sample = render_swift_runtime_ingress_expr(argument);
            format!(
                "DestackRustLocationSample(\n          latitude_degrees: {sample}.latitudeDegrees,\n          longitude_degrees: {sample}.longitudeDegrees,\n          altitude_meters: {sample}.altitudeMeters,\n          horizontal_accuracy_meters: {sample}.horizontalAccuracyMeters,\n          vertical_accuracy_meters: {sample}.verticalAccuracyMeters,\n          speed_meters_per_second: {sample}.speedMetersPerSecond,\n          heading_degrees: {sample}.headingDegrees,\n          timestamp_unix_ns: {sample}.timestampUnixNs\n        )"
            )
        }
        _ => render_swift_runtime_ingress_expr(argument),
    }
}

fn render_swift_runtime_ingress_expr(expr: &RuntimeIngressExpr) -> String {
    match expr {
        RuntimeIngressExpr::Parameter(name) => (*name).to_string(),
        RuntimeIngressExpr::ParameterIsSome(name) => format!("{name} != nil"),
        RuntimeIngressExpr::Field { base, field } => format!("{base}.{field}"),
        RuntimeIngressExpr::OptionalIsSome { base, field } => format!("{base}.{field} != nil"),
    }
}

fn apple_swift_runtime_binding_local_name(
    parameter_name: &str,
    binding_type: RuntimeBindingType,
) -> String {
    let parameter_label = apple_swift_parameter_label(parameter_name);

    match binding_type {
        RuntimeBindingType::StringRef => format!("{parameter_label}Ref"),
        RuntimeBindingType::StringSlice => format!("{parameter_label}Slice"),
        _ => parameter_label,
    }
}

fn render_swift_runtime_bridge_methods(
    module: &HostAbiModule,
    methods: Vec<SwiftBridgeMethod>,
) -> Vec<SwiftBridgeMethod> {
    methods
        .into_iter()
        .map(|mut method| {
            let is_request_method = method
                .parameters
                .first()
                .is_some_and(|parameter| parameter.local_name == "runtimeHost");

            if is_request_method {
                let request = module
                    .requests
                    .iter()
                    .find(|request| apple_swift_method_name(request.name) == method.name)
                    .unwrap_or_else(|| {
                        panic!(
                            "missing Swift runtime-bridge request mapping for {}.{}",
                            module.name, method.name
                        )
                    });

                method.name = apple_runtime_bridge_method_name(module, request);
            }

            method
        })
        .collect()
}

/// Render one generated Swift bridge parameter.
fn render_swift_bridge_parameter(parameter: &SwiftBridgeParameter) -> String {
    match &parameter.external_label {
        Some(label) if label == &parameter.local_name => {
            format!("{label}: {}", parameter.ty)
        }
        Some(label) => format!("{label} {}", render_swift_bridge_parameter_tail(parameter)),
        None => format!("_ {}", render_swift_bridge_parameter_tail(parameter)),
    }
}

/// Render the trailing local-name and type for one Swift bridge parameter.
fn render_swift_bridge_parameter_tail(parameter: &SwiftBridgeParameter) -> String {
    format!("{}: {}", parameter.local_name, parameter.ty)
}

/// Render one generated Swift call expression.
fn render_swift_call_expression(call: &SwiftCallSpec) -> String {
    if call.arguments.is_empty() {
        return format!("{}.{}()", call.receiver, call.method);
    }

    let arguments = call
        .arguments
        .iter()
        .map(|argument| match &argument.label {
            Some(label) => format!("{label}: {}", argument.value),
            None => argument.value.clone(),
        })
        .collect::<Vec<_>>()
        .join(", ");

    format!("{}.{}({arguments})", call.receiver, call.method)
}

/// Render one generated Swift encoding-helper section.
fn render_swift_helper_section(output: &mut String, module: &HostAbiModule) {
    if module.types.is_empty() {
        return;
    }
    let decode_names = collect_apple_request_decode_named_types(module);
    let slice_names = collect_apple_native_slice_named_types(module);
    let uses_u8_slice =
        apple_module_uses_type(module, &HostAbiType::NativeSlice(Box::new(HostAbiType::U8)));
    let uses_i8_slice =
        apple_module_uses_type(module, &HostAbiType::NativeSlice(Box::new(HostAbiType::I8)));
    let uses_i16_slice = apple_module_uses_type(
        module,
        &HostAbiType::NativeSlice(Box::new(HostAbiType::I16)),
    );
    let decode_slice_names: Vec<_> = slice_names
        .iter()
        .copied()
        .filter(|name| decode_names.contains(name))
        .collect();

    render_swift_bridge_arena(output, module);
    output.push('\n');

    for name in &decode_names {
        let named_type = apple_named_type(module, name);
        if let HostAbiNamedTypeDefinition::Enum { .. } = named_type.definition {
            render_swift_enum_decode_helper(output, &named_type);
            output.push('\n');
        }
    }

    for name in &decode_names {
        let named_type = apple_named_type(module, name);
        if let HostAbiNamedTypeDefinition::Struct { .. } = named_type.definition {
            render_swift_struct_decode_helper(output, module, &named_type);
            output.push('\n');
        }
    }

    for name in &decode_slice_names {
        render_swift_named_slice_decode_helper(output, module, name);
        output.push('\n');
    }

    if uses_u8_slice {
        render_swift_primitive_slice_decode_helper(output, &HostAbiType::U8);
        output.push('\n');
    }
    if uses_i8_slice {
        render_swift_primitive_slice_decode_helper(output, &HostAbiType::I8);
        output.push('\n');
    }
    if uses_i16_slice {
        render_swift_primitive_slice_decode_helper(output, &HostAbiType::I16);
        output.push('\n');
    }

    for named_type in &module.types {
        if let HostAbiNamedTypeDefinition::Enum { .. } = named_type.definition {
            render_swift_enum_encode_helper(output, named_type);
            output.push('\n');

            if slice_names.contains(named_type.name) {
                render_swift_named_slice_encode_helper(output, module, named_type);
                output.push('\n');
                render_swift_named_slice_with_native_helper(output, module, named_type);
                output.push('\n');
            }
        }
    }

    for named_type in &module.types {
        if let HostAbiNamedTypeDefinition::Struct { .. } = named_type.definition {
            render_swift_struct_encode_helper(output, module, named_type);
            output.push('\n');
            render_swift_named_with_native_helper(output, module, named_type);
            output.push('\n');
            if slice_names.contains(named_type.name) {
                render_swift_named_slice_encode_helper(output, module, named_type);
                output.push('\n');
                render_swift_named_slice_with_native_helper(output, module, named_type);
                output.push('\n');
            }
        }
    }

    if uses_u8_slice {
        render_swift_primitive_slice_encode_helper(output, module, &HostAbiType::U8);
        output.push('\n');
    }
    if uses_i8_slice {
        render_swift_primitive_slice_encode_helper(output, module, &HostAbiType::I8);
        output.push('\n');
    }
    if uses_i16_slice {
        render_swift_primitive_slice_encode_helper(output, module, &HostAbiType::I16);
        output.push('\n');
    }
}

/// Indent every line in one Swift code block.
fn indent_swift_lines(value: &str, indent: usize) -> String {
    let prefix = " ".repeat(indent);

    value
        .lines()
        .map(|line| format!("{prefix}{line}"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Indent every line after the first in one Swift code block.
fn indent_swift_following_lines(value: &str, indent: usize) -> String {
    let prefix = " ".repeat(indent);
    let mut lines = value.lines();
    let Some(first_line) = lines.next() else {
        return String::new();
    };
    let mut output = first_line.to_string();

    for line in lines {
        output.push('\n');
        output.push_str(&prefix);
        output.push_str(line);
    }

    output
}

/// Collect the named ABI types reachable from request input payloads.
fn collect_apple_request_decode_named_types(module: &HostAbiModule) -> Vec<&'static str> {
    let mut names = Vec::new();

    for request in &module.requests {
        for parameter in &request.parameters {
            if matches!(
                parameter.ty,
                HostAbiType::HostSessionHandle | HostAbiType::OutputPointer(_)
            ) {
                continue;
            }

            collect_apple_request_decode_names_from_type(module, &parameter.ty, &mut names);
        }
    }

    names
}

/// Collect the named ABI types reachable from one request input type.
fn collect_apple_request_decode_names_from_type(
    module: &HostAbiModule,
    ty: &HostAbiType,
    names: &mut Vec<&'static str>,
) {
    match ty {
        HostAbiType::Named(name) => {
            if names.iter().any(|existing| existing == name) {
                return;
            }

            names.push(name);

            if let HostAbiNamedTypeDefinition::Struct { fields } =
                apple_named_type(module, name).definition
            {
                for field in fields {
                    collect_apple_request_decode_names_from_type(module, &field.ty, names);
                }
            }
        }
        HostAbiType::NativeArray(inner)
        | HostAbiType::NativeSlice(inner)
        | HostAbiType::OutputPointer(inner) => {
            collect_apple_request_decode_names_from_type(module, inner, names);
        }
        _ => {}
    }
}

/// Collect the named ABI types used as native slices in one module surface.
fn collect_apple_native_slice_named_types(module: &HostAbiModule) -> BTreeSet<&'static str> {
    let mut names = BTreeSet::new();

    for request in &module.requests {
        for parameter in &request.parameters {
            collect_apple_native_slice_names_from_type(module, &parameter.ty, &mut names);
        }

        collect_apple_native_slice_names_from_type(module, &request.result, &mut names);
    }

    for ingress in &module.ingress {
        for parameter in &ingress.parameters {
            collect_apple_native_slice_names_from_type(module, &parameter.ty, &mut names);
        }
    }

    names
}

/// Collect the named ABI types used as native slices in one ABI type.
fn collect_apple_native_slice_names_from_type(
    module: &HostAbiModule,
    ty: &HostAbiType,
    names: &mut BTreeSet<&'static str>,
) {
    match ty {
        HostAbiType::Named(name) => {
            if let HostAbiNamedTypeDefinition::Struct { fields } =
                apple_named_type(module, name).definition
            {
                for field in fields {
                    collect_apple_native_slice_names_from_type(module, &field.ty, names);
                }
            }
        }
        HostAbiType::NativeSlice(inner) => {
            if let HostAbiType::Named(name) = inner.as_ref() {
                names.insert(name);
            }

            collect_apple_native_slice_names_from_type(module, inner, names);
        }
        HostAbiType::OutputPointer(inner) => {
            collect_apple_native_slice_names_from_type(module, inner, names);
        }
        _ => {}
    }
}

/// Return whether one module uses one nested ABI type anywhere in its surface.
fn apple_module_uses_type(module: &HostAbiModule, ty: &HostAbiType) -> bool {
    module
        .types
        .iter()
        .any(|named_type| apple_named_type_uses_type(module, named_type, ty))
        || module.requests.iter().any(|request| {
            request.result == *ty
                || request
                    .parameters
                    .iter()
                    .any(|parameter| apple_type_contains_type(module, &parameter.ty, ty))
        })
        || module.ingress.iter().any(|ingress| {
            ingress.result == *ty
                || ingress
                    .parameters
                    .iter()
                    .any(|parameter| apple_type_contains_type(module, &parameter.ty, ty))
        })
}

/// Return whether one named type contains one nested ABI type.
fn apple_named_type_uses_type(
    module: &HostAbiModule,
    named_type: &HostAbiNamedType,
    ty: &HostAbiType,
) -> bool {
    match &named_type.definition {
        HostAbiNamedTypeDefinition::Struct { fields } => fields
            .iter()
            .any(|field| apple_type_contains_type(module, &field.ty, ty)),
        HostAbiNamedTypeDefinition::Enum { .. } => false,
    }
}

/// Return whether one ABI type contains one nested ABI type.
fn apple_type_contains_type(
    module: &HostAbiModule,
    outer: &HostAbiType,
    inner: &HostAbiType,
) -> bool {
    if outer == inner {
        return true;
    }

    match outer {
        HostAbiType::Named(name) if !apple_named_type_is_enum(module, name) => module
            .types
            .iter()
            .find(|named_type| named_type.name == *name)
            .map(|named_type| apple_named_type_uses_type(module, named_type, inner))
            .unwrap_or(false),
        HostAbiType::NativeArray(element)
        | HostAbiType::NativeSlice(element)
        | HostAbiType::OutputPointer(element) => apple_type_contains_type(module, element, inner),
        _ => false,
    }
}

/// Return the generated Swift bridge arena type name for one module.
fn apple_swift_bridge_arena_name(module: &HostAbiModule) -> String {
    format!("{}BridgeArena", apple_pascal_case(module.name))
}

