/// Return the generated Swift bridge return type for one request.
fn render_swift_bridge_request_return_type(
    module: &HostAbiModule,
    request: &HostAbiFunction,
) -> String {
    if let Some(output_parameter) = request
        .parameters
        .iter()
        .find(|parameter| matches!(parameter.ty, HostAbiType::OutputPointer(_)))
    {
        let HostAbiType::OutputPointer(inner) = &output_parameter.ty else {
            unreachable!();
        };

        return render_apple_swift_native_type(module, inner);
    }

    render_apple_swift_native_type(module, &request.result)
}

/// Build the plain Swift parameters for one request bridge method.
fn build_plain_swift_request_parameters(
    module: &HostAbiModule,
    request: &HostAbiFunction,
) -> Vec<SwiftBridgeParameter> {
    let mut parameters = vec![SwiftBridgeParameter {
        external_label: Some("runtimeHost".to_string()),
        local_name: "runtimeHost".to_string(),
        ty: "RuntimeHost".to_string(),
    }];

    let input_parameters = request
        .parameters
        .iter()
        .filter(|parameter| {
            !matches!(
                parameter.ty,
                HostAbiType::HostSessionHandle | HostAbiType::OutputPointer(_)
            )
        })
        .collect::<Vec<_>>();

    let unlabeled_single_named =
        input_parameters.len() == 1 && matches!(input_parameters[0].ty, HostAbiType::Named(_));

    for parameter in input_parameters {
        parameters.push(SwiftBridgeParameter {
            external_label: if unlabeled_single_named {
                None
            } else {
                Some(apple_swift_parameter_label(parameter.name))
            },
            local_name: apple_swift_parameter_label(parameter.name),
            ty: render_apple_swift_native_type(module, &parameter.ty),
        });
    }

    parameters
}

/// Build one runtime-host Swift request call.
fn build_apple_runtime_host_call(
    module: &HostAbiModule,
    request: &HostAbiFunction,
) -> SwiftCallSpec {
    let receiver = format!("runtimeHost.{}", apple_runtime_host_request_target(module));
    let method = apple_runtime_host_request_method_name(module, request);
    let arguments = request
        .parameters
        .iter()
        .filter(|parameter| {
            !matches!(
                parameter.ty,
                HostAbiType::HostSessionHandle | HostAbiType::OutputPointer(_)
            )
        })
        .map(|parameter| SwiftCallArgument {
            label: apple_runtime_host_request_argument_label(module, request, parameter),
            value: apple_swift_parameter_label(parameter.name),
        })
        .collect();

    SwiftCallSpec {
        receiver,
        method,
        arguments,
    }
}

