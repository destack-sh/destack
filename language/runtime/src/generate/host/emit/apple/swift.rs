pub(super) fn render_swift_runtime_bridge(modules: &[HostAbiModule]) -> String {
    let mut imports = BTreeSet::new();
    let mut methods = Vec::new();

    for module in modules {
        let Some(bridge) = build_swift_bridge_spec(module) else {
            continue;
        };

        imports.extend(bridge.imports);
        methods.extend(render_swift_runtime_bridge_methods(module, bridge.methods));
    }

    let mut output = String::new();

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    for import in imports {
        output.push_str(&format!("import {import}\n"));
    }
    output.push('\n');
    push_swift_doc_comment(
        &mut output,
        "One generated iOS runtime-bridge base carrying the shared host lane glue.",
        0,
    );
    output.push_str("@MainActor\n");
    output.push_str("public class GeneratedRuntimeBridge {\n");
    output.push_str("  let sessionHandle: HostSessionHandle\n");
    output.push_str("  let bindings: any RuntimeAbi\n");
    output.push_str("  let timestampNs: () -> UInt64\n");
    output.push_str("  private var nextSequence: UInt64 = 1\n\n");
    push_swift_doc_comment(&mut output, "Create one generated runtime-bridge base.", 2);
    output.push_str("  init(\n");
    output.push_str("    sessionHandle: HostSessionHandle,\n");
    output.push_str("    bindings: any RuntimeAbi,\n");
    output.push_str("    timestampNs: @escaping () -> UInt64\n");
    output.push_str("  ) {\n");
    output.push_str("    self.sessionHandle = sessionHandle\n");
    output.push_str("    self.bindings = bindings\n");
    output.push_str("    self.timestampNs = timestampNs\n");
    output.push_str("  }\n");

    if !methods.is_empty() {
        output.push('\n');
    }

    for (index, method) in methods.iter().enumerate() {
        render_swift_bridge_method(&mut output, method);
        if index + 1 != methods.len() {
            output.push('\n');
        }
    }

    output.push_str("}\n");

    output
}

pub(super) fn render_swift_runtime_abi(runtime_ingresses: &[RuntimeIngress]) -> String {
    let mut output = String::new();

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("import Foundation\n");
    output.push_str("import RuntimeHostAppleBridgeC\n");
    output.push_str("import RuntimeHostAppleCore\n\n");
    push_swift_doc_comment(
        &mut output,
        "One generated low-level runtime ABI surface for one iOS host bridge.",
        0,
    );
    output.push_str("protocol RuntimeAbi {\n");

    for runtime_ingress in runtime_ingresses {
        render_swift_runtime_abi_protocol_method(&mut output, runtime_ingress);
        output.push('\n');
    }

    push_swift_doc_comment(
        &mut output,
        "Attach one bridge instance to one runtime session.",
        2,
    );
    output.push_str("  func attachBridge(\n");
    output.push_str("    sessionHandle: HostSessionHandle,\n");
    output.push_str("    bridge: RuntimeBridge\n");
    output.push_str("  ) -> HostAbiStatus\n\n");

    push_swift_doc_comment(
        &mut output,
        "Detach one bridge instance from one runtime session.",
        2,
    );
    output.push_str("  func detachBridge(\n");
    output.push_str("    sessionHandle: HostSessionHandle\n");
    output.push_str("  )\n");
    output.push_str("}\n\n");

    push_swift_doc_comment(
        &mut output,
        "One generated default runtime ABI surface loaded through the iOS bridge C shim.",
        0,
    );
    output.push_str("final class ProcessRuntimeAbi: RuntimeAbi, @unchecked Sendable {\n");
    push_swift_doc_comment(
        &mut output,
        "Attach one bridge instance to one runtime session.",
        2,
    );
    output.push_str("  func attachBridge(\n");
    output.push_str("    sessionHandle: HostSessionHandle,\n");
    output.push_str("    bridge: RuntimeBridge\n");
    output.push_str("  ) -> HostAbiStatus {\n");
    output.push_str("    return destack_runtime_host_ios_register_runtime_bridge_bindings(\n");
    output.push_str("      sessionHandle.rawValue,\n");
    output.push_str("      makeGeneratedRuntimeBridgeBindings()\n");
    output.push_str("    )\n");
    output.push_str("  }\n\n");

    push_swift_doc_comment(
        &mut output,
        "Detach one bridge instance from one runtime session.",
        2,
    );
    output.push_str("  func detachBridge(\n");
    output.push_str("    sessionHandle: HostSessionHandle\n");
    output.push_str("  ) {\n");
    output.push_str(
        "    destack_runtime_host_ios_unregister_runtime_bridge_bindings(sessionHandle.rawValue)\n",
    );
    output.push_str("  }\n");

    if !runtime_ingresses.is_empty() {
        output.push('\n');
    }

    for (index, runtime_ingress) in runtime_ingresses.iter().enumerate() {
        render_swift_runtime_abi_impl_method(&mut output, runtime_ingress);
        if index + 1 != runtime_ingresses.len() {
            output.push('\n');
        }
    }

    output.push_str("}\n");

    output
}

/// Render one generated Swift ABI bridge file.
pub(super) fn render_swift_abi(module: &HostModule) -> String {
    let mut output = String::new();
    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("import Foundation\n");
    output.push_str("import RuntimeHostAppleBridgeC\n");
    output.push_str("import RuntimeHostAppleCore\n\n");

    if module.name() == "location" {
        output.push_str("typealias RuntimeLocationAccuracy = RuntimeHostLocationAccuracy\n");
        output
            .push_str("typealias RuntimeLocationWatchOptions = RuntimeHostLocationWatchOptions\n");
        output.push_str("typealias RuntimeLocationSample = RuntimeHostLocationSample\n\n");
    }

    for request in module.requests() {
        push_swift_doc_comment(&mut output, request.documentation(), 0);
        output.push_str(&format!(
            "typealias {} =\n",
            apple_swift_callback_type_name(module.abi(), request.abi())
        ));
        output.push_str("  @convention(c) (\n");

        for (index, parameter) in request.parameters().iter().enumerate() {
            let trailing = if index + 1 == request.parameters().len() {
                ""
            } else {
                ","
            };
            output.push_str("    ");
            output.push_str(&render_apple_swift_callback_type(&parameter.ty));
            output.push_str(trailing);
            output.push('\n');
        }

        output.push_str("  ) -> ");
        output.push_str(&render_apple_swift_callback_result_type(
            &request.abi().result,
        ));
        output.push_str("\n\n");
    }

    for request in module.requests() {
        render_swift_callback_binding(&mut output, module.abi(), request.abi());
        output.push('\n');
    }

    render_swift_callback_bundle(&mut output, module.abi());
    output.push('\n');
    render_swift_request_handlers(&mut output, module);
    output.push('\n');
    render_swift_helper_section(&mut output, module.abi());
    while output.ends_with("\n\n") {
        output.pop();
    }

    output
}

fn render_swift_runtime_abi_protocol_method(output: &mut String, runtime_ingress: &RuntimeIngress) {
    match runtime_ingress.lowering() {
        RuntimeIngressLowering::ModuleIngress => {
            let module = runtime_ingress.module();
            let ingress = module
                .single_ingress()
                .expect("expected one ingress while rendering aggregate Swift runtime ABI");
            render_swift_ingress_signature(output, module, ingress, 2);
        }
        _ => render_swift_runtime_ingress_signature(output, runtime_ingress, 2),
    }
}

fn render_swift_runtime_abi_impl_method(output: &mut String, runtime_ingress: &RuntimeIngress) {
    match runtime_ingress.lowering() {
        RuntimeIngressLowering::ModuleIngress => {
            let module = runtime_ingress.module();
            let ingress = module
                .single_ingress()
                .expect("expected one ingress while rendering aggregate Swift runtime ABI");
            render_swift_ingress_signature(output, module, ingress, 2);
            output.push_str(" {\n");
            render_swift_ingress_body(output, module, ingress, 4);
            output.push_str("  }\n");
        }
        RuntimeIngressLowering::EnumDispatch {
            enum_parameter,
            enum_field,
            cases,
        } => {
            render_swift_runtime_ingress_signature(output, runtime_ingress, 2);
            output.push_str(" {\n");
            output.push_str(&format!("    switch {enum_parameter}.{enum_field} {{\n"));
            for case in cases {
                render_swift_runtime_dispatch_case(output, case);
            }
            output.push_str("    }\n");
            output.push_str("  }\n");
        }
    }
}

/// One generated Swift bridge file.
#[derive(Clone, Debug)]
#[allow(dead_code)]
struct SwiftBridgeSpec {
    /// The bridge imports.
    imports: BTreeSet<String>,
    /// The class name.
    class_name: String,
    /// The class documentation.
    documentation: String,
    /// The implemented protocol, when needed.
    implemented_protocol: Option<String>,
    /// The stored properties.
    stored_properties: Vec<String>,
    /// The initializer parameters.
    initializer_parameters: Vec<SwiftBridgeParameter>,
    /// The initializer assignments.
    initializer_assignments: Vec<String>,
    /// The initializer documentation.
    initializer_documentation: Option<String>,
    /// The generated methods.
    methods: Vec<SwiftBridgeMethod>,
}

/// One generated Swift bridge method.
#[derive(Clone, Debug)]
struct SwiftBridgeMethod {
    /// The method documentation.
    documentation: String,
    /// The method qualifiers.
    qualifiers: Vec<&'static str>,
    /// The method name.
    name: String,
    /// The method parameters.
    parameters: Vec<SwiftBridgeParameter>,
    /// The optional return type.
    return_type: Option<String>,
    /// The method body lines.
    body_lines: Vec<String>,
}

/// One generated Swift bridge parameter.
#[derive(Clone, Debug)]
struct SwiftBridgeParameter {
    /// The optional external label.
    external_label: Option<String>,
    /// The local name.
    local_name: String,
    /// The parameter type.
    ty: String,
}

/// Build one generated Swift bridge spec for one ABI module.
fn build_swift_bridge_spec(module: &HostAbiModule) -> Option<SwiftBridgeSpec> {
    let mut bridge = SwiftBridgeSpec {
        imports: BTreeSet::new(),
        class_name: format!("{}Bridge", apple_pascal_case(module.name)),
        documentation: format!(
            "One {} bridge lane for one attached iOS runtime host.",
            apple_swift_bridge_label(module.name)
        ),
        implemented_protocol: None,
        stored_properties: Vec::new(),
        initializer_parameters: Vec::new(),
        initializer_assignments: Vec::new(),
        initializer_documentation: None,
        methods: Vec::new(),
    };

    bridge.imports.insert("RuntimeHostAppleCore".to_string());

    match module.name {
        "background" => build_background_swift_bridge(module, &mut bridge),
        "calendar" => build_calendar_swift_bridge(module, &mut bridge),
        "contact" => build_plain_swift_bridge(module, &mut bridge),
        "document" => build_document_swift_bridge(module, &mut bridge),
        "intent" => build_intent_swift_bridge(module, &mut bridge),
        "location" => build_location_swift_bridge(module, &mut bridge),
        "media" => build_plain_swift_bridge(module, &mut bridge),
        "notification" => build_notification_swift_bridge(module, &mut bridge),
        "permission" => build_permission_swift_bridge(module, &mut bridge),
        "text" => build_text_swift_bridge(module, &mut bridge),
        _ => return None,
    }

    Some(bridge)
}

