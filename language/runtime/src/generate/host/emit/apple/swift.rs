/// Return one Swift bridge payload default value for one ABI type.
fn render_swift_default_encoded_value(module: &HostAbiModule, ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::U8 => "0".to_string(),
        HostAbiType::I8 => "0".to_string(),
        HostAbiType::I16 => "0".to_string(),
        HostAbiType::U32 => "0".to_string(),
        HostAbiType::I32 => "0".to_string(),
        HostAbiType::U64 | HostAbiType::HostRequestId => "0".to_string(),
        HostAbiType::Bool => "false".to_string(),
        HostAbiType::F64 => "0.0".to_string(),
        HostAbiType::HostStatus | HostAbiType::RuntimeStatus => "0".to_string(),
        HostAbiType::StringRef => "DestackRustStringRef(data: nil, len: 0)".to_string(),
        HostAbiType::StringSlice => "DestackRustStringSlice(data: nil, len: 0)".to_string(),
        HostAbiType::Named(name) if apple_named_type_is_enum(module, name) => "0".to_string(),
        HostAbiType::Named(name) => {
            let HostAbiNamedTypeDefinition::Struct { fields } =
                apple_named_type(module, name).definition
            else {
                panic!("expected Apple named struct default for {name}");
            };
            let callback_type = render_apple_swift_callback_type(&HostAbiType::Named(name));
            let mut output = format!("{callback_type}(\n");

            for (index, field) in fields.iter().enumerate() {
                let trailing = if index + 1 == fields.len() { "" } else { "," };
                let default_value = render_swift_default_encoded_value(module, &field.ty);
                let default_value = indent_swift_following_lines(&default_value, 2);
                output.push_str(&format!(
                    "  {}: {}{}\n",
                    field.name, default_value, trailing
                ));
            }

            output.push(')');
            output
        }
        HostAbiType::NativeSlice(inner) => {
            if let HostAbiType::Named(name) = inner.as_ref() {
                let external_name = render_external_abi_name(name);
                format!("DestackRust{external_name}Slice(data: nil, len: 0)")
            } else if let Some(slice_suffix) = apple_primitive_slice_suffix(inner) {
                format!("DestackRust{slice_suffix}Slice(data: nil, len: 0)")
            } else {
                panic!("unsupported Apple default encoded slice");
            }
        }
        other => panic!("unsupported Apple default encoded value for {:?}", other),
    }
}

/// Return one Swift encode expression for one runtime field.
fn render_swift_encode_value_expr(
    module: &HostAbiModule,
    source: &str,
    ty: &HostAbiType,
    arena_name: &str,
) -> String {
    match ty {
        HostAbiType::U8 | HostAbiType::I8 | HostAbiType::I16 => source.to_string(),
        HostAbiType::U32 => format!("UInt32({source})"),
        HostAbiType::I32 => format!("Int32({source})"),
        HostAbiType::U64 => source.to_string(),
        HostAbiType::HostRequestId => format!("{source}.rawValue"),
        HostAbiType::Bool
        | HostAbiType::F64
        | HostAbiType::HostStatus
        | HostAbiType::RuntimeStatus => source.to_string(),
        HostAbiType::StringRef => format!("{arena_name}.makeStringRef({source})"),
        HostAbiType::StringSlice => format!("{arena_name}.makeStringSlice({source})"),
        HostAbiType::Named(name) if apple_named_type_is_enum(module, name) => {
            format!("encodeBridge{name}({source})")
        }
        HostAbiType::Named(name) => format!("encodeBridge{name}({source}, arena: {arena_name})"),
        HostAbiType::NativeSlice(inner) => {
            if let HostAbiType::Named(name) = inner.as_ref() {
                format!(
                    "encodeBridge{}Slice({}, arena: {})",
                    name, source, arena_name
                )
            } else if let Some(slice_suffix) = apple_primitive_slice_suffix(inner) {
                format!("encodeBridge{slice_suffix}Slice({source}, arena: {arena_name})")
            } else {
                panic!("unsupported Apple encode slice expression");
            }
        }
        other => panic!("unsupported Apple encode expression for {:?}", other),
    }
}

/// Return one Swift optional encode expression for one runtime field.
fn render_swift_optional_encode_value_expr(
    module: &HostAbiModule,
    source: &str,
    ty: &HostAbiType,
    arena_name: &str,
) -> String {
    match ty {
        HostAbiType::StringRef => format!(
            "{source}.map {{ {arena_name}.makeStringRef($0) }}\n?? {}",
            render_swift_default_encoded_value(module, ty)
        ),
        HostAbiType::StringSlice => format!(
            "{source}.map {{ {arena_name}.makeStringSlice($0) }}\n?? {}",
            render_swift_default_encoded_value(module, ty)
        ),
        HostAbiType::Named(name) if apple_named_type_is_enum(module, name) => format!(
            "{source}.map(encodeBridge{name}) ?? {}",
            render_swift_default_encoded_value(module, ty)
        ),
        HostAbiType::Named(name) => format!(
            "{source}.map {{ encodeBridge{name}($0, arena: {arena_name}) }}\n?? {}",
            render_swift_default_encoded_value(module, ty)
        ),
        HostAbiType::NativeSlice(inner) => {
            let encode_expr = if let HostAbiType::Named(name) = inner.as_ref() {
                format!("encodeBridge{name}Slice($0, arena: {arena_name})")
            } else if let Some(slice_suffix) = apple_primitive_slice_suffix(inner) {
                format!("encodeBridge{slice_suffix}Slice($0, arena: {arena_name})")
            } else {
                panic!("unsupported Apple optional encode slice expression");
            };

            format!(
                "{source}.map {{ {encode_expr} }}\n?? {}",
                render_swift_default_encoded_value(module, ty)
            )
        }
        HostAbiType::HostRequestId => {
            format!(
                "{source}.map(\\.rawValue) ?? {}",
                render_swift_default_encoded_value(module, ty)
            )
        }
        _ => format!(
            "{source} ?? {}",
            render_swift_default_encoded_value(module, ty)
        ),
    }
}

/// Render one Swift ingress method signature.
fn render_swift_ingress_signature(
    output: &mut String,
    module: &HostModule,
    ingress: &HostIngress,
    indent: usize,
) {
    let prefix = " ".repeat(indent);
    push_swift_doc_comment(output, ingress.documentation(), indent);
    output.push_str(&format!(
        "{prefix}func {}(\n",
        apple_swift_method_name(ingress.name())
    ));

    for (index, parameter) in ingress.parameters().iter().enumerate() {
        let trailing = if index + 1 == ingress.parameters().len() {
            ""
        } else {
            ","
        };
        let parameter_type = render_apple_swift_native_type(module.abi(), &parameter.ty);

        output.push_str(&format!(
            "{prefix}  {}: {}{}\n",
            apple_swift_parameter_label(parameter.name),
            parameter_type,
            trailing
        ));
    }

    output.push_str(&format!("{prefix}) -> RuntimeAbiStatus"));
}

