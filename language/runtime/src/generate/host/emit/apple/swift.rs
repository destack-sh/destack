/// Render the generated Swift request handler body.
fn render_swift_request_handler_body(
    output: &mut String,
    module: &HostModule,
    request: &HostRequest,
) {
    let input_parameters = request.input_parameters();
    let output_parameter = request.output_parameter();
    let input_arguments = apple_swift_request_arguments(input_parameters);

    if let Some(output_parameter) = output_parameter {
        let output_name = apple_swift_parameter_label(output_parameter.name);
        output.push_str(&format!("  guard let {output_name} else {{\n"));
        output.push_str("    return hostStatusInvalidArgument\n");
        output.push_str("  }\n");
    }

    for parameter in input_parameters {
        render_swift_request_decode(output, module, request, parameter);
    }

    if let Some(output_parameter) = output_parameter {
        render_swift_request_output_call(
            output,
            module,
            request,
            &input_arguments,
            output_parameter,
            &apple_swift_parameter_label(output_parameter.name),
        );
    } else {
        render_swift_runtime_host_call(output, module, request, &input_arguments);
    }
}

/// Render one decoded request argument.
fn render_swift_request_decode(
    output: &mut String,
    module: &HostModule,
    request: &HostRequest,
    parameter: &HostAbiParameter,
) {
    let decoded_name = apple_swift_decoded_request_name(request, parameter);
    let decoded_expr = render_swift_decode_value_expr(
        module.abi(),
        &apple_swift_parameter_label(parameter.name),
        &parameter.ty,
    );

    if apple_type_decode_can_throw(module.abi(), &parameter.ty) {
        render_swift_decoded_value_header(
            output,
            &decoded_name,
            &render_apple_swift_native_type(module.abi(), &parameter.ty),
        );
        output.push_str(&format!("    {decoded_name} = {decoded_expr}\n"));
        render_swift_invalid_argument_footer(output);
    } else {
        output.push_str(&format!("  let {decoded_name} = {decoded_expr}\n\n"));
    }
}

/// Render one request handler that writes into one response pointer.
fn render_swift_request_output_call(
    output: &mut String,
    module: &HostModule,
    request: &HostRequest,
    arguments: &[String],
    output_parameter: &HostAbiParameter,
    output_name: &str,
) {
    let HostAbiType::OutputPointer(inner) = &output_parameter.ty else {
        panic!("unsupported Apple output parameter for {}", request.name());
    };
    let response_type = render_apple_swift_native_type(module.abi(), inner);
    let method_name = apple_runtime_bridge_method_name(module.abi(), request.abi());

    output.push_str(&format!(
        "  let bridgeResponse: {response_type}? = runOnMainThread {{\n"
    ));
    output.push_str("    withResolvedRuntimeBridge(\n");
    output.push_str("      sessionHandle: sessionHandle,\n");
    output.push_str("      onMissing: { nil }\n");
    output.push_str("    ) { bridge, runtimeHost in\n");
    output.push_str(&format!("      bridge.{method_name}(\n"));
    output.push_str("        runtimeHost: runtimeHost");

    for argument in arguments {
        output.push_str(",\n");
        output.push_str("        ");
        output.push_str(argument);
    }

    output.push_str("\n");
    output.push_str("      )\n");
    output.push_str("    }\n");
    output.push_str("  }\n");
    output.push_str("  guard let bridgeResponse else {\n");
    output.push_str("    return hostStatusNotFound\n");
    output.push_str("  }\n");

    let arena_name = apple_swift_current_bridge_arena_name(module.abi());
    let encoded_response =
        render_swift_encode_value_expr(module.abi(), "bridgeResponse", inner, "arena");

    match inner.as_ref() {
        HostAbiType::Named(_) | HostAbiType::StringRef | HostAbiType::StringSlice => {
            output.push_str(&format!("  let arena = {arena_name}()\n"));
            output.push_str(&format!("  {output_name}.pointee = {encoded_response}\n\n"));
        }
        HostAbiType::NativeSlice(_) => {
            output.push_str(&format!("  let arena = {arena_name}()\n"));
            output.push_str(&format!("  {output_name}.pointee = {encoded_response}\n\n"));
        }
        _ => {
            output.push_str(&format!("  {output_name}.pointee = {encoded_response}\n\n"));
        }
    }

    if let HostAbiType::Named(name) = inner.as_ref() {
        if name.ends_with("Response") {
            output.push_str("  return bridgeResponse.status\n");
            return;
        }
    }

    output.push_str("  return hostStatusOk\n");
}

/// Render the header for one throwing decode block.
fn render_swift_decoded_value_header(output: &mut String, variable_name: &str, type_name: &str) {
    output.push_str(&format!("  let {variable_name}: {type_name}\n"));
    output.push_str("  do {\n");
}

/// Render the invalid-argument footer for one throwing decode block.
fn render_swift_invalid_argument_footer(output: &mut String) {
    output.push_str("  } catch {\n");
    output.push_str("    return hostStatusInvalidArgument\n");
    output.push_str("  }\n\n");
}

/// Render one request handler that only returns one status code.
fn render_swift_runtime_host_call(
    output: &mut String,
    module: &HostModule,
    request: &HostRequest,
    arguments: &[String],
) {
    let method_name = apple_runtime_bridge_method_name(module.abi(), request.abi());

    output.push_str("  return runOnMainThread {\n");
    output.push_str("    withResolvedRuntimeBridge(\n");
    output.push_str("      sessionHandle: sessionHandle,\n");
    output.push_str("      onMissing: { hostStatusNotFound }\n");
    output.push_str("    ) { bridge, runtimeHost in\n");
    output.push_str(&format!("      bridge.{method_name}(\n"));
    output.push_str("        runtimeHost: runtimeHost");

    for argument in arguments {
        output.push_str(",\n");
        output.push_str("        ");
        output.push_str(argument);
    }

    output.push_str("\n");
    output.push_str("      )\n");
    output.push_str("    }\n");
    output.push_str("  }\n");
}

fn apple_runtime_bridge_method_name(module: &HostAbiModule, request: &HostAbiFunction) -> String {
    format!(
        "{}{}",
        apple_swift_parameter_label(module.name),
        apple_pascal_case(request.name)
    )
}

/// Return the decoded local name for one request parameter.
fn apple_swift_decoded_request_name(request: &HostRequest, parameter: &HostAbiParameter) -> String {
    let input_parameters = request.input_parameters();

    if input_parameters.len() == 1 && matches!(parameter.ty, HostAbiType::Named(_)) {
        return "decodedRequest".to_string();
    }

    format!("decoded{}", apple_pascal_case(parameter.name))
}

/// Return the runtime-host call arguments for one request.
fn apple_swift_request_arguments(input_parameters: &[HostAbiParameter]) -> Vec<String> {
    let single_named_input = input_parameters.len() == 1
        && input_parameters
            .first()
            .is_some_and(|parameter| matches!(parameter.ty, HostAbiType::Named(_)));

    input_parameters
        .iter()
        .map(|parameter| {
            let decoded_name = if single_named_input {
                "decodedRequest".to_string()
            } else {
                format!("decoded{}", apple_pascal_case(parameter.name))
            };

            if single_named_input {
                decoded_name
            } else {
                format!(
                    "{}: {}",
                    apple_swift_parameter_label(parameter.name),
                    decoded_name
                )
            }
        })
        .collect()
}

/// Return the Apple module path segment for one module.
fn apple_module_segment(module: &HostAbiModule) -> String {
    apple_pascal_case(module.name)
}

/// Return the Apple Swift protocol name for one module.
#[allow(dead_code)]
fn apple_swift_protocol_name(module: &HostAbiModule) -> String {
    format!("{}Abi", apple_module_segment(module))
}

/// Return the Apple callback-bundle field name for one request.
fn apple_callback_bundle_field_name<'a>(
    _module: &'a HostAbiModule,
    request: &'a HostAbiFunction,
) -> &'a str {
    request.name
}

/// Render one Swift runtime ingress call argument.
fn apple_swift_runtime_argument(
    module: &HostAbiModule,
    parameter: &HostAbiParameter,
    native_arguments: &[(&'static str, String)],
) -> String {
    if let Some((_, native_argument)) = native_arguments
        .iter()
        .find(|(parameter_name, _)| *parameter_name == parameter.name)
    {
        return native_argument.clone();
    }

    match &parameter.ty {
        HostAbiType::HostSessionHandle => {
            format!("{}.rawValue", apple_swift_parameter_label(parameter.name))
        }
        HostAbiType::HostRequestId => {
            format!("{}.rawValue", apple_swift_parameter_label(parameter.name))
        }
        HostAbiType::Named(name) if apple_named_type_is_enum(module, name) => {
            format!(
                "encodeBridge{name}({})",
                apple_swift_parameter_label(parameter.name)
            )
        }
        _ => apple_swift_parameter_label(parameter.name),
    }
}

/// Render one recursive Swift ingress call with native wrappers.
fn render_swift_ingress_call(
    output: &mut String,
    module: &HostAbiModule,
    ingress: &HostIngress,
    parameter_index: usize,
    native_arguments: &mut Vec<(&'static str, String)>,
    indent: usize,
) {
    if parameter_index == ingress.parameters().len() {
        render_swift_ingress_terminal_call(output, module, ingress, native_arguments, indent);
        return;
    }

    let parameter = &ingress.parameters()[parameter_index];
    let Some((helper_name, native_name)) = apple_swift_native_wrapper(module, parameter) else {
        render_swift_ingress_call(
            output,
            module,
            ingress,
            parameter_index + 1,
            native_arguments,
            indent,
        );
        return;
    };

    let prefix = " ".repeat(indent);
    output.push_str(&format!(
        "{prefix}return {helper_name}({}) {{ {native_name} in\n",
        apple_swift_parameter_label(parameter.name)
    ));

    native_arguments.push((parameter.name, native_name));
    render_swift_ingress_call(
        output,
        module,
        ingress,
        parameter_index + 1,
        native_arguments,
        indent + 2,
    );
    native_arguments.pop();

    output.push_str(&format!("{prefix}}}\n"));
}

/// Render one terminal Swift ingress call after every wrapper is in scope.
fn render_swift_ingress_terminal_call(
    output: &mut String,
    module: &HostAbiModule,
    ingress: &HostIngress,
    native_arguments: &[(&'static str, String)],
    indent: usize,
) {
    let prefix = " ".repeat(indent);

    output.push_str(&format!(
        "{prefix}let status = destack_runtime_host_ios_{}(\n",
        ingress.name()
    ));

    for (index, parameter) in ingress.parameters().iter().enumerate() {
        let trailing = if index + 1 == ingress.parameters().len() {
            ""
        } else {
            ","
        };
        let argument = apple_swift_runtime_argument(module, parameter, native_arguments);
        output.push_str(&format!("{prefix}  {argument}{trailing}\n"));
    }

    output.push_str(&format!("{prefix})\n\n"));
    output.push_str(&format!("{prefix}return RuntimeAbiStatus(\n"));
    output.push_str(&format!("{prefix}  code: status.code,\n"));
    output.push_str(&format!("{prefix}  errorID: status.error_id\n"));
    output.push_str(&format!("{prefix})\n"));
}

/// Return the wrapper helper and native variable for one ingress parameter.
fn apple_swift_native_wrapper(
    module: &HostAbiModule,
    parameter: &HostAbiParameter,
) -> Option<(String, String)> {
    let helper_name = match &parameter.ty {
        HostAbiType::StringRef => "withNativeStringRef".to_string(),
        HostAbiType::StringSlice => "withNativeStringSlice".to_string(),
        HostAbiType::Named(name) if !apple_named_type_is_enum(module, name) => {
            apple_swift_encode_helper_name(parameter)
        }
        HostAbiType::NativeSlice(_) => apple_swift_encode_helper_name(parameter),
        _ => return None,
    };

    Some((
        helper_name,
        apple_swift_native_parameter_name(parameter.name),
    ))
}

/// Return one native local name for one wrapped ingress parameter.
fn apple_swift_native_parameter_name(name: &str) -> String {
    let parameter_name = apple_swift_parameter_label(name);
    let mut characters = parameter_name.chars();
    let first_character = characters
        .next()
        .unwrap_or_else(|| panic!("missing ingress parameter name for {name}"));

    format!(
        "native{}{}",
        first_character.to_ascii_uppercase(),
        characters.as_str()
    )
}

