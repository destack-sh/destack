/// Configure one qualified Swift bridge with one session handle and one bindings lane.
fn configure_swift_session_ingress_bridge_with_qualifiers(
    bridge: &mut SwiftBridgeSpec,
    implemented_protocol: &'static str,
    bindings_type: &'static str,
    qualifier: &'static str,
    initializer_documentation: &'static str,
) {
    let session_property = if qualifier.is_empty() {
        "let sessionHandle: HostSessionHandle".to_string()
    } else {
        format!("{qualifier} let sessionHandle: HostSessionHandle")
    };
    let bindings_property = if qualifier.is_empty() {
        format!("private let bindings: {bindings_type}")
    } else {
        format!("{qualifier} private let bindings: {bindings_type}")
    };

    let _ = implemented_protocol;
    bridge
        .stored_properties
        .extend([session_property, bindings_property]);
    bridge.initializer_parameters = vec![
        SwiftBridgeParameter {
            external_label: Some("sessionHandle".to_string()),
            local_name: "sessionHandle".to_string(),
            ty: "HostSessionHandle".to_string(),
        },
        SwiftBridgeParameter {
            external_label: Some("bindings".to_string()),
            local_name: "bindings".to_string(),
            ty: bindings_type.to_string(),
        },
    ];
    bridge.initializer_assignments = vec![
        "self.sessionHandle = sessionHandle".to_string(),
        "self.bindings = bindings".to_string(),
    ];
    bridge.initializer_documentation = Some(initializer_documentation.to_string());
}

