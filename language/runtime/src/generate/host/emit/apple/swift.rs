/// Return one derived Swift ingress method name.
fn apple_swift_method_name(name: &str) -> String {
    apple_swift_parameter_label(name)
}

/// Return one derived Swift encode helper name.
fn apple_swift_encode_helper_name(parameter: &HostAbiParameter) -> String {
    match &parameter.ty {
        HostAbiType::Named(name) => format!("withNative{name}"),
        HostAbiType::NativeSlice(element) => {
            let HostAbiType::Named(name) = element.as_ref() else {
                panic!(
                    "missing named slice ingress parameter for {}",
                    parameter.name
                );
            };

            format!("withNative{name}Slice")
        }
        _ => panic!("missing named ingress parameter for {}", parameter.name),
    }
}

/// Return whether one Apple decode path can throw.
fn apple_type_decode_can_throw(module: &HostAbiModule, ty: &HostAbiType) -> bool {
    match ty {
        HostAbiType::StringRef | HostAbiType::StringSlice => true,
        HostAbiType::Named(name) if apple_named_type_is_enum(module, name) => true,
        HostAbiType::Named(name) => apple_named_struct_fields(module, name)
            .iter()
            .any(|field| apple_type_decode_can_throw(module, &field.ty)),
        HostAbiType::NativeArray(inner)
        | HostAbiType::NativeSlice(inner)
        | HostAbiType::OutputPointer(inner) => apple_type_decode_can_throw(module, inner),
        _ => false,
    }
}

/// Return the primitive-slice suffix for one native slice element.
fn apple_primitive_slice_suffix(ty: &HostAbiType) -> Option<&'static str> {
    match ty {
        HostAbiType::U8 => Some("U8"),
        HostAbiType::I8 => Some("I8"),
        HostAbiType::I16 => Some("I16"),
        _ => None,
    }
}

/// Render one Apple Swift callback parameter type.
fn render_apple_swift_callback_type(ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::U8 => "UInt8".to_string(),
        HostAbiType::U16 => "UInt16".to_string(),
        HostAbiType::I8 => "Int8".to_string(),
        HostAbiType::I16 => "Int16".to_string(),
        HostAbiType::U32 => "UInt32".to_string(),
        HostAbiType::I32 => "Int32".to_string(),
        HostAbiType::U64 => "UInt64".to_string(),
        HostAbiType::HostRequestId => "HostRequestID".to_string(),
        HostAbiType::Bool => "Bool".to_string(),
        HostAbiType::F64 => "Double".to_string(),
        HostAbiType::StringRef => "DestackRustStringRef".to_string(),
        HostAbiType::StringSlice => "DestackRustStringSlice".to_string(),
        HostAbiType::HostSessionHandle => "UInt64".to_string(),
        HostAbiType::HostStatus => "UInt32".to_string(),
        HostAbiType::RuntimeStatus => "DestackRustRuntimeStatus".to_string(),
        HostAbiType::NativeArray(element) => {
            format!("{}Array", render_apple_swift_callback_type(element))
        }
        HostAbiType::NativeSlice(element) => {
            if let Some(slice_suffix) = apple_primitive_slice_suffix(element) {
                format!("DestackRust{slice_suffix}Slice")
            } else {
                format!("{}Slice", render_apple_swift_callback_type(element))
            }
        }
        HostAbiType::OutputPointer(inner) => {
            format!(
                "UnsafeMutablePointer<{}>?",
                render_apple_swift_callback_type(inner)
            )
        }
        HostAbiType::Named(name) => format!("DestackRust{}", render_external_abi_name(name)),
    }
}

/// Render one Apple Swift callback result type.
fn render_apple_swift_callback_result_type(ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::HostStatus => "UInt32".to_string(),
        _ => render_apple_swift_callback_type(ty),
    }
}

/// Render one projected Apple Swift native parameter type.
fn render_apple_swift_native_type(module: &HostAbiModule, ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::U8 => "UInt8".to_string(),
        HostAbiType::U16 => "UInt16".to_string(),
        HostAbiType::I8 => "Int8".to_string(),
        HostAbiType::I16 => "Int16".to_string(),
        HostAbiType::U32 => "UInt32".to_string(),
        HostAbiType::I32 => "Int32".to_string(),
        HostAbiType::U64 => "UInt64".to_string(),
        HostAbiType::HostRequestId => "HostRequestID".to_string(),
        HostAbiType::Bool => "Bool".to_string(),
        HostAbiType::F64 => "Double".to_string(),
        HostAbiType::StringRef => "String".to_string(),
        HostAbiType::StringSlice => "[String]".to_string(),
        HostAbiType::HostSessionHandle => "HostSessionHandle".to_string(),
        HostAbiType::HostStatus => "HostAbiStatus".to_string(),
        HostAbiType::RuntimeStatus => "RuntimeAbiStatus".to_string(),
        HostAbiType::NativeArray(element) => {
            format!("[{}]", render_apple_swift_native_type(module, element))
        }
        HostAbiType::NativeSlice(element) => {
            format!("[{}]", render_apple_swift_native_type(module, element))
        }
        HostAbiType::OutputPointer(inner) => {
            format!(
                "UnsafeMutablePointer<{}>?",
                render_apple_swift_native_type(module, inner)
            )
        }
        HostAbiType::Named(name) => apple_swift_named_type(name),
    }
}

/// Return the Apple Swift native type for one named ABI type.
fn apple_swift_named_type(name: &str) -> String {
    format!("Runtime{name}")
}

/// Return one authored Apple named type by name.
fn apple_named_type(module: &HostAbiModule, name: &str) -> HostAbiNamedType {
    if let Some(named_type) = module
        .types
        .iter()
        .find(|named_type| named_type.name == name)
    {
        return named_type.clone();
    }

    panic!("missing Apple named type {name}");
}

/// Return whether one authored Apple named type is one enum.
fn apple_named_type_is_enum(module: &HostAbiModule, name: &str) -> bool {
    matches!(
        apple_named_type(module, name).definition,
        HostAbiNamedTypeDefinition::Enum { .. }
    )
}

/// Return the struct fields for one authored Apple named type.
fn apple_named_struct_fields(module: &HostAbiModule, name: &str) -> Vec<HostAbiField> {
    let HostAbiNamedTypeDefinition::Struct { fields } = apple_named_type(module, name).definition
    else {
        panic!("expected Apple named struct for {name}");
    };

    fields
}

/// Return the exported ABI type name for one authored Rust host ABI type.
fn render_external_abi_name(name: &str) -> &str {
    name.strip_prefix("Host").unwrap_or(name)
}

/// Return one generated Apple named type label.
fn apple_swift_parameter_label(name: &str) -> String {
    let mut segments = name.split('_');
    let Some(first) = segments.next() else {
        return String::new();
    };

    let mut label = first.to_string();
    for segment in segments {
        if segment == "id" {
            label.push_str("ID");
            continue;
        }
        if segment == "url" {
            label.push_str("URL");
            continue;
        }

        let mut characters = segment.chars();
        let Some(first_character) = characters.next() else {
            continue;
        };

        label.push(first_character.to_ascii_uppercase());
        label.extend(characters);
    }

    label
}
