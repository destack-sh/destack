fn apple_swift_current_bridge_arena_name(module: &HostAbiModule) -> String {
    format!("current{}BridgeArena", apple_pascal_case(module.name))
}

/// Render one generated Swift bridge arena.
fn render_swift_bridge_arena(output: &mut String, module: &HostAbiModule) {
    let arena_name = apple_swift_bridge_arena_name(module);
    let current_arena_name = apple_swift_current_bridge_arena_name(module);

    push_swift_doc_comment(
        output,
        "One temporary native allocation arena for one bridge callback.",
        0,
    );
    output.push_str(&format!("final class {arena_name} {{\n"));
    output.push_str("  /// The raw deallocation actions recorded for this callback.\n");
    output.push_str("  private var deallocations: [() -> Void] = []\n\n");
    output.push_str(
        "  /// Remove every recorded allocation before one new callback payload is encoded.\n",
    );
    output.push_str("  func reset() {\n");
    output.push_str("    for deallocate in deallocations.reversed() {\n");
    output.push_str("      deallocate()\n");
    output.push_str("    }\n\n");
    output.push_str("    deallocations.removeAll(keepingCapacity: true)\n");
    output.push_str("  }\n\n");
    output.push_str("  /// Release every recorded native allocation.\n");
    output.push_str("  deinit {\n");
    output.push_str("    for deallocate in deallocations.reversed() {\n");
    output.push_str("      deallocate()\n");
    output.push_str("    }\n");
    output.push_str("  }\n\n");
    output.push_str("  /// Allocate one copied UTF-8 buffer for one Swift string.\n");
    output.push_str("  func makeStringRef(\n");
    output.push_str("    _ value: String\n");
    output.push_str("  ) -> DestackRustStringRef {\n");
    output.push_str("    let bytes = Array(value.utf8)\n");
    output.push_str("    if bytes.isEmpty {\n");
    output.push_str("      return DestackRustStringRef(data: nil, len: 0)\n");
    output.push_str("    }\n\n");
    output.push_str(
        "    let storage = UnsafeMutablePointer<UInt8>.allocate(capacity: bytes.count)\n",
    );
    output.push_str("    storage.initialize(from: bytes, count: bytes.count)\n");
    output.push_str("    deallocations.append {\n");
    output.push_str("      storage.deinitialize(count: bytes.count)\n");
    output.push_str("      storage.deallocate()\n");
    output.push_str("    }\n\n");
    output.push_str("    return DestackRustStringRef(\n");
    output.push_str("      data: UnsafePointer(storage),\n");
    output.push_str("      len: UInt32(bytes.count)\n");
    output.push_str("    )\n");
    output.push_str("  }\n\n");
    output.push_str("  /// Allocate one copied string-slice payload.\n");
    output.push_str("  func makeStringSlice(\n");
    output.push_str("    _ values: [String]\n");
    output.push_str("  ) -> DestackRustStringSlice {\n");
    output.push_str("    let data = makeArray(count: values.count) { buffer in\n");
    output.push_str("      for (index, value) in values.enumerated() {\n");
    output.push_str("        buffer[index] = makeStringRef(value)\n");
    output.push_str("      }\n");
    output.push_str("    }\n\n");
    output.push_str("    return DestackRustStringSlice(\n");
    output.push_str("      data: data,\n");
    output.push_str("      len: UInt32(values.count)\n");
    output.push_str("    )\n");
    output.push_str("  }\n\n");
    output
        .push_str("  /// Allocate one copied native array and fill it with one builder closure.\n");
    output.push_str("  func makeArray<Element>(\n");
    output.push_str("    count: Int,\n");
    output.push_str("    fill: (UnsafeMutableBufferPointer<Element>) -> Void\n");
    output.push_str("  ) -> UnsafeMutablePointer<Element>? {\n");
    output.push_str("    if count == 0 {\n");
    output.push_str("      return nil\n");
    output.push_str("    }\n\n");
    output.push_str("    let storage = UnsafeMutablePointer<Element>.allocate(capacity: count)\n");
    output.push_str("    let buffer = UnsafeMutableBufferPointer(start: storage, count: count)\n");
    output.push_str("    fill(buffer)\n");
    output.push_str("    deallocations.append {\n");
    output.push_str("      storage.deinitialize(count: count)\n");
    output.push_str("      storage.deallocate()\n");
    output.push_str("    }\n\n");
    output.push_str("    return storage\n");
    output.push_str("  }\n");
    output.push_str("}\n\n");

    let key = format!("dev.destack.runtime.apple.{}-bridge-arena", module.name);
    push_swift_doc_comment(
        output,
        "Return the thread-local bridge arena for one callback thread.",
        0,
    );
    output.push_str(&format!("func {current_arena_name}() -> {arena_name} {{\n"));
    output.push_str("  let dictionary = Thread.current.threadDictionary\n");
    output.push_str(&format!("  let key = \"{key}\"\n\n"));
    output.push_str(&format!(
        "  if let arena = dictionary[key] as? {arena_name} {{\n"
    ));
    output.push_str("    arena.reset()\n\n");
    output.push_str("    return arena\n");
    output.push_str("  }\n\n");
    output.push_str(&format!("  let arena = {arena_name}()\n"));
    output.push_str("  dictionary[key] = arena\n\n");
    output.push_str("  return arena\n");
    output.push_str("}\n");
}

/// Render one generic Swift enum decode helper.
fn render_swift_enum_decode_helper(output: &mut String, named_type: &HostAbiNamedType) {
    let HostAbiNamedTypeDefinition::Enum { repr, .. } = &named_type.definition else {
        panic!("expected Apple enum helper for {}", named_type.name);
    };

    let runtime_name = apple_swift_named_type(named_type.name);
    let raw_value = match repr {
        HostAbiEnumRepresentation::U32 | HostAbiEnumRepresentation::I32 => {
            ".init(value)".to_string()
        }
    };

    push_swift_doc_comment(
        output,
        &format!(
            "Build one Swift {} from one bridge raw value.",
            render_external_abi_name(named_type.name)
        ),
        0,
    );
    output.push_str(&format!(
        "func decodeBridge{}(\n  _ value: {}\n) throws -> {} {{\n",
        named_type.name,
        render_apple_swift_callback_type(&HostAbiType::Named(named_type.name)),
        runtime_name
    ));
    output.push_str(&format!(
        "  guard let value = {runtime_name}(rawValue: {raw_value}) else {{\n"
    ));
    output.push_str("    throw BridgeStringError.invalidStringSlice\n");
    output.push_str("  }\n\n");
    output.push_str("  return value\n");
    output.push_str("}\n");
}

/// Render one generic Swift struct decode helper.
fn render_swift_struct_decode_helper(
    output: &mut String,
    module: &HostAbiModule,
    named_type: &HostAbiNamedType,
) {
    let HostAbiNamedTypeDefinition::Struct { fields } = &named_type.definition else {
        panic!("expected Apple struct helper for {}", named_type.name);
    };
    let runtime_name = apple_swift_named_type(named_type.name);
    let can_throw = apple_type_decode_can_throw(module, &HostAbiType::Named(named_type.name));
    let throws_suffix = if can_throw { " throws" } else { "" };

    push_swift_doc_comment(
        output,
        &format!(
            "Build one Swift {} from one bridge payload.",
            render_external_abi_name(named_type.name)
        ),
        0,
    );
    output.push_str(&format!(
        "func decodeBridge{}(\n  _ value: {}\n){} -> {} {{\n",
        named_type.name,
        render_apple_swift_callback_type(&HostAbiType::Named(named_type.name)),
        throws_suffix,
        runtime_name
    ));
    output.push_str(&format!("  {runtime_name}(\n"));
    let mut field_lines = Vec::new();

    let mut index = 0;
    while index < fields.len() {
        let field = &fields[index];
        if let Some(optional_field_name) = field.name.strip_prefix("has_") {
            if let Some(value_field) = fields.get(index + 1) {
                if value_field.name == optional_field_name {
                    field_lines.push(format!(
                        "    {}:\n      value.{}\n      ? {}\n      : nil",
                        apple_swift_parameter_label(value_field.name),
                        field.name,
                        render_swift_decode_value_expr(
                            module,
                            &format!("value.{}", value_field.name),
                            &value_field.ty,
                        )
                    ));
                    index += 2;
                    continue;
                }
            }
        }

        field_lines.push(format!(
            "    {}:\n      {}",
            apple_swift_parameter_label(field.name),
            render_swift_decode_value_expr(module, &format!("value.{}", field.name), &field.ty)
        ));
        index += 1;
    }

    for (index, field_line) in field_lines.iter().enumerate() {
        let trailing = if index + 1 == field_lines.len() {
            ""
        } else {
            ","
        };
        output.push_str(field_line);
        output.push_str(trailing);
        output.push('\n');
    }

    output.push_str("  )\n");
    output.push_str("}\n");
}

/// Render one generic Swift named-slice decode helper.
fn render_swift_named_slice_decode_helper(output: &mut String, module: &HostAbiModule, name: &str) {
    let named_type = apple_named_type(module, name);
    let decode_can_throw =
        apple_type_decode_can_throw(module, &HostAbiType::Named(named_type.name));
    let decode_prefix = if decode_can_throw { "try " } else { "" };
    let map_prefix = if decode_can_throw { "try " } else { "" };

    push_swift_doc_comment(
        output,
        &format!(
            "Build one Swift {} slice from one bridge payload.",
            render_external_abi_name(name)
        ),
        0,
    );
    output.push_str(&format!(
        "func decodeBridge{}Slice(\n  _ value: {}\n) throws -> [{}] {{\n",
        name,
        format!("DestackRust{}Slice", render_external_abi_name(name)),
        apple_swift_named_type(name),
    ));
    output.push_str("  if value.len == 0 {\n");
    output.push_str("    return []\n");
    output.push_str("  }\n\n");
    output.push_str("  guard let data = value.data else {\n");
    output.push_str("    throw BridgeStringError.invalidStringSlice\n");
    output.push_str("  }\n\n");
    output.push_str("  let buffer = UnsafeBufferPointer(\n");
    output.push_str("    start: data,\n");
    output.push_str("    count: Int(value.len)\n");
    output.push_str("  )\n\n");
    output.push_str("  return ");
    output.push_str(map_prefix);
    output.push_str("buffer.map { ");
    output.push_str(decode_prefix);
    output.push_str(&format!("decodeBridge{name}($0)"));
    output.push_str(" }\n");
    output.push_str("}\n");
}

/// Render one Swift decode expression for one ABI field.
fn render_swift_decode_value_expr(
    module: &HostAbiModule,
    source: &str,
    ty: &HostAbiType,
) -> String {
    match ty {
        HostAbiType::U8 | HostAbiType::U16 | HostAbiType::I8 | HostAbiType::I16 => {
            source.to_string()
        }
        HostAbiType::U32
        | HostAbiType::U64
        | HostAbiType::Bool
        | HostAbiType::F64
        | HostAbiType::HostStatus
        | HostAbiType::RuntimeStatus => source.to_string(),
        HostAbiType::I32 => format!("Int({source})"),
        HostAbiType::HostRequestId => format!("HostRequestID(rawValue: {source})"),
        HostAbiType::StringRef => format!("try tryDecodeNativeString({source})"),
        HostAbiType::StringSlice => format!("try tryDecodeNativeStringSlice({source})"),
        HostAbiType::Named(name) => {
            let prefix = if apple_type_decode_can_throw(module, ty) {
                "try "
            } else {
                ""
            };
            format!("{prefix}decodeBridge{name}({source})")
        }
        HostAbiType::NativeSlice(inner) => {
            if let HostAbiType::Named(name) = inner.as_ref() {
                format!("try decodeBridge{name}Slice({source})")
            } else if let Some(slice_suffix) = apple_primitive_slice_suffix(inner) {
                format!("decodeBridge{slice_suffix}Slice({source})")
            } else {
                panic!("unsupported Apple decode expression for {:?}", ty);
            }
        }
        other => panic!("unsupported Apple decode expression for {:?}", other),
    }
}

