/// Render one generic Swift struct encode helper.
fn render_swift_struct_encode_helper(
    output: &mut String,
    module: &HostAbiModule,
    named_type: &HostAbiNamedType,
) {
    let HostAbiNamedTypeDefinition::Struct { fields } = &named_type.definition else {
        panic!(
            "expected Apple struct encode helper for {}",
            named_type.name
        );
    };

    let runtime_name = apple_swift_named_type(named_type.name);
    let callback_type = render_apple_swift_callback_type(&HostAbiType::Named(named_type.name));
    let arena_name = apple_swift_bridge_arena_name(module);
    let current_arena_name = apple_swift_current_bridge_arena_name(module);

    push_swift_doc_comment(
        output,
        &format!(
            "Encode one Swift {} as one bridge payload.",
            render_external_abi_name(named_type.name)
        ),
        0,
    );
    output.push_str(&format!(
        "func encodeBridge{}(\n  _ value: {},\n  arena: {}\n) -> {} {{\n",
        named_type.name, runtime_name, arena_name, callback_type
    ));
    output.push_str(&format!("  {}(\n", callback_type));
    let mut field_lines = Vec::new();

    let mut index = 0;
    while index < fields.len() {
        let field = &fields[index];
        if let Some(optional_field_name) = field.name.strip_prefix("has_") {
            if let Some(value_field) = fields.get(index + 1) {
                if value_field.name == optional_field_name {
                    let runtime_field =
                        format!("value.{}", apple_swift_parameter_label(value_field.name));
                    field_lines.push(format!("    {}: {} != nil", field.name, runtime_field));
                    field_lines.push(format!(
                        "    {}:\n{}",
                        value_field.name,
                        indent_swift_lines(
                            &render_swift_optional_encode_value_expr(
                                module,
                                &runtime_field,
                                &value_field.ty,
                                "arena"
                            ),
                            6
                        )
                    ));
                    index += 2;
                    continue;
                }
            }
        }

        field_lines.push(format!(
            "    {}:\n      {}",
            field.name,
            render_swift_encode_value_expr(
                module,
                &format!("value.{}", apple_swift_parameter_label(field.name)),
                &field.ty,
                "arena"
            )
        ));
        index += 1;
    }

    for (index, field_line) in field_lines.iter().enumerate() {
        let trailing = if index + 1 == field_lines.len() {
            ""
        } else {
            ","
        };
        output.push_str(field_line);
        output.push_str(trailing);
        output.push('\n');
    }

    output.push_str("  )\n");
    output.push_str("}\n\n");
    output.push_str(&format!(
        "func encodeBridge{}(\n  _ value: {}\n) -> {} {{\n",
        named_type.name, runtime_name, callback_type
    ));
    output.push_str(&format!("  let arena = {}()\n\n", current_arena_name));
    output.push_str(&format!(
        "  return encodeBridge{}(value, arena: arena)\n",
        named_type.name
    ));
    output.push_str("}\n");
}

