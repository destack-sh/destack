/// Return the runtime-host request argument label for one Swift request parameter.
fn apple_runtime_host_request_argument_label(
    _module: &HostAbiModule,
    request: &HostAbiFunction,
    parameter: &HostAbiParameter,
) -> Option<String> {
    let input_parameters = request
        .parameters
        .iter()
        .filter(|parameter| {
            !matches!(
                parameter.ty,
                HostAbiType::HostSessionHandle | HostAbiType::OutputPointer(_)
            )
        })
        .collect::<Vec<_>>();

    let parameter_index = input_parameters
        .iter()
        .position(|candidate| candidate.name == parameter.name)
        .expect("Swift host call parameter must exist in request inputs");

    let is_primary_unlabeled_single = input_parameters.len() == 1
        && matches!(
            parameter.name,
            "query" | "draft" | "request" | "options" | "url" | "path" | "text" | "paths"
        );

    let is_primary_unlabeled_multi =
        parameter_index == 0 && matches!(parameter.name, "query_text" | "text" | "paths");

    if is_primary_unlabeled_single || is_primary_unlabeled_multi {
        None
    } else {
        Some(apple_swift_parameter_label(parameter.name))
    }
}

