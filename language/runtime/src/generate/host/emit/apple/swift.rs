/// Return one derived Swift encode helper name.
fn apple_swift_encode_helper_name(parameter: &HostAbiParameter) -> String {
    match &parameter.ty {
        HostAbiType::Named(name) => format!("withNative{name}"),
        HostAbiType::NativeSlice(element) => {
            if apple_native_slice_uses_string_transport(element) {
                return "withNativeStringSlice".to_string();
            }

            let HostAbiType::Named(name) = element.as_ref() else {
                panic!(
                    "missing named slice ingress parameter for {}",
                    parameter.name
                );
            };

            format!("withNative{name}Slice")
        }
        _ => panic!("missing named ingress parameter for {}", parameter.name),
    }
}

/// Return whether one Apple decode path can throw.
fn apple_type_decode_can_throw(module: &HostAbiModule, ty: &HostAbiType) -> bool {
    match ty {
        HostAbiType::StringRef | HostAbiType::OsPath | HostAbiType::StringSlice => true,
        HostAbiType::Named(name) if apple_named_type_is_enum(module, name) => true,
        HostAbiType::Named(name) => apple_named_struct_fields(module, name)
            .iter()
            .any(|field| apple_type_decode_can_throw(module, &field.ty)),
        HostAbiType::Optional(inner) => apple_type_decode_can_throw(module, inner),
        HostAbiType::NativeArray(inner)
        | HostAbiType::NativeSlice(inner)
        | HostAbiType::OutputPointer(inner) => apple_type_decode_can_throw(module, inner),
        _ => false,
    }
}

/// Return the primitive-slice suffix for one native slice element.
fn apple_primitive_slice_suffix(ty: &HostAbiType) -> Option<&'static str> {
    match ty {
        HostAbiType::U8 => Some("U8"),
        HostAbiType::I8 => Some("I8"),
        HostAbiType::I16 => Some("I16"),
        _ => None,
    }
}

/// Return whether one native slice uses the shared string transport.
fn apple_native_slice_uses_string_transport(ty: &HostAbiType) -> bool {
    matches!(ty, HostAbiType::StringRef | HostAbiType::OsPath)
}

/// Render one Apple Swift callback parameter type.
fn render_apple_swift_callback_type(ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::U8 => "UInt8".to_string(),
        HostAbiType::U16 => "UInt16".to_string(),
        HostAbiType::I8 => "Int8".to_string(),
        HostAbiType::I16 => "Int16".to_string(),
        HostAbiType::U32 => "UInt32".to_string(),
        HostAbiType::I32 => "Int32".to_string(),
        HostAbiType::U64 => "UInt64".to_string(),
        HostAbiType::HostRequestId => "HostRequestID".to_string(),
        HostAbiType::Bool => "Bool".to_string(),
        HostAbiType::F64 => "Double".to_string(),
        HostAbiType::StringRef => "DestackRustStringRef".to_string(),
        HostAbiType::OsPath => "DestackRustStringRef".to_string(),
        HostAbiType::StringSlice => "DestackRustStringSlice".to_string(),
        HostAbiType::HostSessionHandle => "UInt64".to_string(),
        HostAbiType::HostStatus => "UInt32".to_string(),
        HostAbiType::RuntimeStatus => "DestackRustRuntimeStatus".to_string(),
        HostAbiType::NativeArray(element) => {
            format!("{}Array", render_apple_swift_callback_type(element))
        }
        HostAbiType::NativeSlice(element) => {
            if apple_native_slice_uses_string_transport(element) {
                "DestackRustStringSlice".to_string()
            } else if let Some(slice_suffix) = apple_primitive_slice_suffix(element) {
                format!("DestackRust{slice_suffix}Slice")
            } else {
                format!("{}Slice", render_apple_swift_callback_type(element))
            }
        }
        HostAbiType::OutputPointer(inner) => {
            format!(
                "UnsafeMutablePointer<{}>?",
                render_apple_swift_callback_type(inner)
            )
        }
        HostAbiType::Optional(inner) => render_apple_swift_optional_callback_type(inner),
        HostAbiType::Named(name) => format!("DestackRust{}", render_external_abi_name(name)),
    }
}

