use super::docs::push_swift_doc_comment;
use super::name::apple_pascal_case;
use crate::host::model::{HostCallParameter, HostCallParameterType, host_call_parameters};
use destack_runtime::host::abi::describe::{HostAbiFunction, HostAbiModule, HostAbiType};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum HostRole {
    Requests,
    Events,
}

impl HostRole {
    /// Return the generated interface suffix.
    const fn suffix(self) -> &'static str {
        match self {
            Self::Requests => "Requests",
            Self::Events => "Events",
        }
    }
}

const HOST_STATUS_TYPE: HostAbiType = HostAbiType::HostStatus;

/// Render the generated Apple host module wrappers.
pub(super) fn render_swift_host_modules(modules: &[HostAbiModule]) -> String {
    let mut output = String::new();

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("import Foundation\n\n");

    for (index, module) in modules.iter().enumerate() {
        render_swift_host_module(&mut output, module);

        if index + 1 != modules.len() {
            output.push('\n');
        }
    }

    output
}

/// Render one generated Apple host interface file.
pub(super) fn render_swift_host_protocol(module: &HostAbiModule, role: HostRole) -> String {
    let mut output = String::new();
    let contract_name = host_protocol_name(module, role);

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("import Foundation\n\n");

    push_swift_doc_comment(
        &mut output,
        &format!(
            "The {} {} surface attached to one Apple runtime host.",
            module.name.replace('_', "-"),
            host_role_label(role),
        ),
        0,
    );

    if matches!(role, HostRole::Requests | HostRole::Events) {
        output.push_str("@MainActor\n");
    }

    output.push_str(&format!("public protocol {contract_name}"));

    if matches!(role, HostRole::Requests) {
        output.push_str(": AnyObject");
    }

    output.push_str(" {\n");

    for method in host_methods(module, role) {
        render_swift_host_protocol_method(&mut output, module, method, role);
        output.push('\n');
    }

    output.push_str("}\n\n");

    match role {
        HostRole::Requests => {
            render_swift_host_unsupported_requests(&mut output, module);
        }
        HostRole::Events => {
            render_swift_host_noop_events(&mut output, module);
        }
    }

    output
}

fn has_host_requests(module: &HostAbiModule) -> bool {
    !module.requests.is_empty()
}

fn has_host_events(module: &HostAbiModule) -> bool {
    !module.ingress.is_empty()
}

fn host_protocol_name(module: &HostAbiModule, role: HostRole) -> String {
    format!("{}{}", apple_pascal_case(module.name), role.suffix())
}

fn render_swift_host_module(output: &mut String, module: &HostAbiModule) {
    let class_name = format!("{}Host", apple_pascal_case(module.name));

    push_swift_doc_comment(
        output,
        &format!(
            "The {} host surface attached to one Apple runtime host.",
            module.name.replace('_', "-"),
        ),
        0,
    );
    output.push_str("@MainActor\n");
    output.push_str(&format!("public final class {class_name}"));

    match (has_host_requests(module), has_host_events(module)) {
        (true, true) => {
            let requests_name = host_protocol_name(module, HostRole::Requests);
            let events_name = host_protocol_name(module, HostRole::Events);

            output.push_str(&format!(": {requests_name}, {events_name} {{\n"));
            output.push_str(&format!("  private var requests: any {requests_name}\n"));
            output.push_str(&format!("  private let events: any {events_name}\n\n"));
            push_swift_doc_comment(output, "Create one host surface.", 2);
            output.push_str("  public init(\n");
            output.push_str(&format!("    requests: any {requests_name},\n"));
            output.push_str(&format!("    events: any {events_name}\n"));
            output.push_str("  ) {\n");
            output.push_str("    self.requests = requests\n");
            output.push_str("    self.events = events\n");
            output.push_str("  }\n\n");

            render_swift_host_update_requests_method(output, &requests_name);
            output.push('\n');
            render_swift_host_wrapper_methods(output, module, HostRole::Requests, "requests");
            if has_host_events(module) {
                output.push('\n');
            }
            render_swift_host_wrapper_methods(output, module, HostRole::Events, "events");
        }
        (true, false) => {
            let requests_name = host_protocol_name(module, HostRole::Requests);

            output.push_str(&format!(": {requests_name} {{\n"));
            output.push_str(&format!("  private var requests: any {requests_name}\n\n"));
            push_swift_doc_comment(output, "Create one host surface.", 2);
            output.push_str(&format!(
                "  public init(requests: any {requests_name}) {{\n"
            ));
            output.push_str("    self.requests = requests\n");
            output.push_str("  }\n\n");

            render_swift_host_update_requests_method(output, &requests_name);
            output.push('\n');
            render_swift_host_wrapper_methods(output, module, HostRole::Requests, "requests");
        }
        (false, true) => {
            let events_name = host_protocol_name(module, HostRole::Events);

            output.push_str(&format!(": {events_name} {{\n"));
            output.push_str(&format!("  private let events: any {events_name}\n\n"));
            push_swift_doc_comment(output, "Create one host surface.", 2);
            output.push_str(&format!("  public init(events: any {events_name}) {{\n"));
            output.push_str("    self.events = events\n");
            output.push_str("  }\n\n");

            render_swift_host_wrapper_methods(output, module, HostRole::Events, "events");
        }
        (false, false) => panic!("missing host surfaces for module {}", module.name),
    }

    output.push_str("}\n");
}

fn render_swift_host_update_requests_method(output: &mut String, requests_name: &str) {
    push_swift_doc_comment(output, "Replace the request surface for this host.", 2);
    output.push_str("  func updateRequests(\n");
    output.push_str(&format!("    _ requests: any {requests_name}\n"));
    output.push_str("  ) {\n");
    output.push_str("    self.requests = requests\n");
    output.push_str("  }\n");
}

fn render_swift_host_protocol_method(
    output: &mut String,
    module: &HostAbiModule,
    method: HostMethod<'_>,
    role: HostRole,
) {
    push_swift_doc_comment(output, method.documentation(), 2);
    render_swift_host_method_signature(output, module, method, role, "  func");
    output.push('\n');
}

fn render_swift_host_wrapper_methods(
    output: &mut String,
    module: &HostAbiModule,
    role: HostRole,
    receiver: &str,
) {
    let methods = host_methods(module, role);

    for (index, method) in methods.iter().copied().enumerate() {
        push_swift_doc_comment(output, method.documentation(), 2);
        render_swift_host_method_signature(output, module, method, role, "  public func");
        output.push_str(" {\n");

        let call = render_swift_host_call(method, receiver);
        if method.return_type(module, role).is_some() {
            output.push_str("    return ");
            output.push_str(&call);
            output.push('\n');
        } else {
            output.push_str("    ");
            output.push_str(&call);
            output.push('\n');
        }

        output.push_str("  }");

        if index + 1 != methods.len() {
            output.push_str("\n\n");
        } else {
            output.push('\n');
        }
    }
}

fn render_swift_host_unsupported_requests(output: &mut String, module: &HostAbiModule) {
    let contract_name = host_protocol_name(module, HostRole::Requests);
    let unsupported_name = format!("Unsupported{contract_name}");

    push_swift_doc_comment(
        output,
        &format!(
            "The explicit unsupported {} request surface for one Apple runtime host.",
            module.name.replace('_', "-"),
        ),
        0,
    );
    output.push_str("@MainActor\n");
    output.push_str(&format!(
        "public final class {unsupported_name}: {contract_name} {{\n"
    ));
    push_swift_doc_comment(output, "Create one unsupported request surface.", 2);
    output.push_str("  public init() {}\n\n");

    let methods = host_methods(module, HostRole::Requests);
    for (index, method) in methods.iter().copied().enumerate() {
        push_swift_doc_comment(output, method.documentation(), 2);
        render_swift_host_method_signature(
            output,
            module,
            method,
            HostRole::Requests,
            "  public func",
        );
        output.push_str(" {\n");

        if let Some(expression) = render_swift_unsupported_request_value(module, method) {
            output.push_str("    return ");
            output.push_str(&expression);
            output.push('\n');
        }

        output.push_str("  }");

        if index + 1 != methods.len() {
            output.push_str("\n\n");
        } else {
            output.push('\n');
        }
    }

    output.push_str("}\n");
}

fn render_swift_host_noop_events(output: &mut String, module: &HostAbiModule) {
    let contract_name = host_protocol_name(module, HostRole::Events);
    let noop_name = format!("Noop{contract_name}");

    push_swift_doc_comment(
        output,
        &format!(
            "The explicit no-op {} event surface for one Apple runtime host.",
            module.name.replace('_', "-"),
        ),
        0,
    );
    output.push_str(&format!(
        "public final class {noop_name}: {contract_name} {{\n"
    ));
    push_swift_doc_comment(output, "Create one no-op event surface.", 2);
    output.push_str("  public init() {}\n\n");

    let methods = host_methods(module, HostRole::Events);
    for (index, method) in methods.iter().copied().enumerate() {
        push_swift_doc_comment(output, method.documentation(), 2);
        render_swift_host_method_signature(
            output,
            module,
            method,
            HostRole::Events,
            "  public func",
        );
        output.push_str(" {\n");
        output.push_str("  }");

        if index + 1 != methods.len() {
            output.push_str("\n\n");
        } else {
            output.push('\n');
        }
    }

    output.push_str("}\n");
}

fn render_swift_host_method_signature(
    output: &mut String,
    module: &HostAbiModule,
    method: HostMethod<'_>,
    role: HostRole,
    prefix: &str,
) {
    output.push_str(prefix);
    output.push(' ');
    output.push_str(&method.name());
    output.push('(');

    let parameters = method.parameters();
    if parameters.is_empty() {
        output.push(')');
    } else {
        output.push('\n');

        for (index, parameter) in parameters.iter().copied().enumerate() {
            let parameter_name = parameter.name();
            let local_name = apple_swift_parameter_label(parameter_name);
            let label = if index == 0 {
                "_".to_string()
            } else {
                local_name.clone()
            };

            output.push_str("    ");
            output.push_str(&label);

            if label != local_name {
                output.push(' ');
                output.push_str(&local_name);
            }

            output.push_str(": ");
            output.push_str(&parameter.render_type(module, role));

            if index + 1 != parameters.len() {
                output.push(',');
            }

            output.push('\n');
        }

        output.push_str("  )");
    }

    if let Some(return_type) = method.return_type(module, role) {
        output.push_str(&format!(" -> {return_type}"));
    }
}

fn render_swift_host_call(method: HostMethod<'_>, receiver: &str) -> String {
    let mut output = String::new();
    output.push_str(receiver);
    output.push('.');
    output.push_str(&method.name());
    output.push('(');

    let parameters = method.parameters();
    for (index, parameter) in parameters.iter().copied().enumerate() {
        let name = apple_swift_parameter_label(parameter.name());

        if index > 0 {
            output.push_str(", ");
        }

        if index == 0 {
            output.push_str(&name);
        } else {
            output.push_str(&format!("{name}: {name}"));
        }
    }

    output.push(')');
    output
}

fn render_swift_host_type(module: &HostAbiModule, ty: &HostAbiType, role: HostRole) -> String {
    match ty {
        HostAbiType::Named(name) => render_swift_named_type(module, name),
        HostAbiType::Optional(inner) => {
            format!("{}?", render_swift_host_type(module, inner, role))
        }
        HostAbiType::NativeSlice(inner) => {
            format!("[{}]", render_swift_host_type(module, inner, role))
        }
        HostAbiType::StringRef => "String".to_string(),
        HostAbiType::OsPath => "String".to_string(),
        HostAbiType::StringSlice => "[String]".to_string(),
        HostAbiType::HostRequestId => "HostRequestID".to_string(),
        HostAbiType::Bool => "Bool".to_string(),
        HostAbiType::U8 => "UInt8".to_string(),
        HostAbiType::U16 => "UInt16".to_string(),
        HostAbiType::I8 => "Int8".to_string(),
        HostAbiType::I16 => "Int16".to_string(),
        HostAbiType::U32 => {
            let _ = role;
            "UInt32".to_string()
        }
        HostAbiType::I32 => "Int32".to_string(),
        HostAbiType::U64 => "UInt64".to_string(),
        HostAbiType::F64 => "Double".to_string(),
        HostAbiType::HostStatus => "UInt32".to_string(),
        HostAbiType::RuntimeStatus => "RuntimeIngressStatus".to_string(),
        HostAbiType::HostSessionHandle
        | HostAbiType::OutputPointer(_)
        | HostAbiType::NativeArray(_) => {
            panic!("unsupported Apple runtime-host type")
        }
    }
}

fn render_swift_named_type(module: &HostAbiModule, name: &str) -> String {
    let _ = module;
    format!("Runtime{name}")
}

fn render_swift_unsupported_request_value(
    module: &HostAbiModule,
    method: HostMethod<'_>,
) -> Option<String> {
    let ty = method.result_type();
    let return_type = method.return_type(module, HostRole::Requests)?;

    Some(match ty {
        HostAbiType::Bool => "false".to_string(),
        HostAbiType::StringRef => "\"\"".to_string(),
        HostAbiType::StringSlice | HostAbiType::NativeSlice(_) => "[]".to_string(),
        HostAbiType::HostStatus => "hostStatusNotSupported".to_string(),
        HostAbiType::Named(_) => format!("{return_type}(status: hostStatusNotSupported)"),
        _ => format!("{return_type}(status: hostStatusNotSupported)"),
    })
}

fn host_methods<'a>(module: &'a HostAbiModule, role: HostRole) -> Vec<HostMethod<'a>> {
    match role {
        HostRole::Requests => module.requests.iter().map(HostMethod::Request).collect(),
        HostRole::Events => module.ingress.iter().map(HostMethod::Ingress).collect(),
    }
}

fn host_role_label(role: HostRole) -> &'static str {
    match role {
        HostRole::Requests => "request",
        HostRole::Events => "event",
    }
}

#[derive(Clone, Copy)]
enum HostMethod<'a> {
    Request(&'a HostAbiFunction),
    Ingress(&'a HostAbiFunction),
}

impl<'a> HostMethod<'a> {
    fn name(self) -> String {
        match self {
            Self::Request(request) => apple_swift_parameter_label(request.name),
            Self::Ingress(ingress) => apple_swift_parameter_label(ingress.name),
        }
    }

    fn documentation(self) -> &'static str {
        match self {
            Self::Request(request) => request.documentation,
            Self::Ingress(ingress) => ingress.documentation,
        }
    }

    fn parameters(self) -> Vec<HostParameter<'a>> {
        match self {
            Self::Request(request) => host_call_parameters(&request.parameters)
                .into_iter()
                .map(HostParameter::Call)
                .collect(),
            Self::Ingress(ingress) => ingress
                .parameters
                .iter()
                .filter(|parameter| !matches!(parameter.ty, HostAbiType::HostSessionHandle))
                .map(HostParameter::Abi)
                .collect(),
        }
    }

    fn result_type(self) -> &'a HostAbiType {
        match self {
            Self::Request(request) => request
                .parameters
                .iter()
                .find_map(|parameter| match &parameter.ty {
                    HostAbiType::OutputPointer(inner) => Some(inner.as_ref()),
                    _ => None,
                })
                .unwrap_or(&request.result),
            Self::Ingress(_) => &HOST_STATUS_TYPE,
        }
    }

    fn return_type(self, module: &HostAbiModule, role: HostRole) -> Option<String> {
        match self {
            Self::Request(_) => Some(render_swift_host_type(module, self.result_type(), role)),
            Self::Ingress(_) => None,
        }
    }
}

#[derive(Clone, Copy)]
enum HostParameter<'a> {
    Abi(&'a destack_runtime::host::abi::describe::HostAbiParameter),
    Call(HostCallParameter<'a>),
}

impl<'a> HostParameter<'a> {
    fn name(self) -> &'a str {
        match self {
            Self::Abi(parameter) => parameter.name,
            Self::Call(parameter) => parameter.name(),
        }
    }

    fn render_type(self, module: &HostAbiModule, role: HostRole) -> String {
        match self {
            Self::Abi(parameter) => render_swift_host_type(module, &parameter.ty, role),
            Self::Call(parameter) => match parameter.ty() {
                HostCallParameterType::Abi(ty) => render_swift_host_type(module, ty, role),
            },
        }
    }
}

fn apple_swift_parameter_label(name: &str) -> String {
    let mut segments = name.split('_');
    let Some(first) = segments.next() else {
        return String::new();
    };

    let mut label = first.to_string();
    for segment in segments {
        if segment == "id" {
            label.push_str("ID");
            continue;
        }
        if segment == "url" {
            label.push_str("URL");
            continue;
        }

        let mut characters = segment.chars();
        let Some(first_character) = characters.next() else {
            continue;
        };

        label.push(first_character.to_ascii_uppercase());
        label.extend(characters);
    }

    label
}
