use std::collections::BTreeSet;

use super::docs::push_kotlin_doc_comment;
use super::kotlin::android_kotlin_parameter_name;
use super::name::android_pascal_case;
use crate::host::model::{HostCallParameter, HostCallParameterType, host_call_parameters};
use destack_runtime::host::abi::describe::{HostAbiFunction, HostAbiModule, HostAbiType};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum HostRole {
    Requests,
    Events,
}

impl HostRole {
    /// Return the generated interface suffix.
    const fn suffix(self) -> &'static str {
        match self {
            Self::Requests => "Requests",
            Self::Events => "Events",
        }
    }
}

const HOST_STATUS_TYPE: HostAbiType = HostAbiType::HostStatus;

/// Render the generated Android host module wrappers.
pub(super) fn render_kotlin_host_modules(modules: &[HostAbiModule]) -> String {
    let mut output = String::new();
    let mut imports = BTreeSet::new();

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("package dev.destack.runtime.android.core\n\n");

    for module in modules {
        if has_host_requests(module) {
            imports.insert(format!(
                "dev.destack.runtime.android.module.{}.{}",
                module.name,
                host_interface_name(module, HostRole::Requests),
            ));
        }

        if has_host_events(module) {
            imports.insert(format!(
                "dev.destack.runtime.android.module.{}.{}",
                module.name,
                host_interface_name(module, HostRole::Events),
            ));
        }

        collect_kotlin_host_module_imports(&mut imports, module);
    }

    for import in imports {
        output.push_str(&format!("import {import}\n"));
    }

    if !modules.is_empty() {
        output.push('\n');
    }

    for (index, module) in modules.iter().enumerate() {
        render_kotlin_host_module(&mut output, module);

        if index + 1 != modules.len() {
            output.push('\n');
        }
    }

    output
}

fn collect_kotlin_host_module_imports(imports: &mut BTreeSet<String>, module: &HostAbiModule) {
    for role in [HostRole::Requests, HostRole::Events] {
        if !matches!(role, HostRole::Requests) && !has_host_events(module) {
            continue;
        }

        if matches!(role, HostRole::Requests) && !has_host_requests(module) {
            continue;
        }

        for method in host_methods(module, role) {
            collect_kotlin_host_module_type_import(imports, module, method.result_type());

            for parameter in method.parameters() {
                collect_kotlin_host_surface_import(imports, module, parameter.ty());
            }
        }
    }
}

fn collect_kotlin_host_surface_import(
    imports: &mut BTreeSet<String>,
    module: &HostAbiModule,
    ty: HostSurfaceType<'_>,
) {
    let HostSurfaceType::Abi(ty) = ty;
    collect_kotlin_host_module_type_import(imports, module, ty);
}

fn collect_kotlin_host_module_type_import(
    imports: &mut BTreeSet<String>,
    module: &HostAbiModule,
    ty: &HostAbiType,
) {
    match ty {
        HostAbiType::Named(name) => {
            imports.insert(format!(
                "dev.destack.runtime.android.module.{}.{}",
                module.name,
                render_android_named_type(module, name)
            ));
        }
        HostAbiType::Optional(inner) => {
            collect_kotlin_host_module_type_import(imports, module, inner);
        }
        HostAbiType::NativeSlice(inner) | HostAbiType::OutputPointer(inner) => {
            collect_kotlin_host_module_type_import(imports, module, inner);
        }
        HostAbiType::U8
        | HostAbiType::U16
        | HostAbiType::I8
        | HostAbiType::I16
        | HostAbiType::U32
        | HostAbiType::I32
        | HostAbiType::U64
        | HostAbiType::F64
        | HostAbiType::Bool
        | HostAbiType::StringRef
        | HostAbiType::StringSlice
        | HostAbiType::OsPath
        | HostAbiType::HostRequestId
        | HostAbiType::HostStatus
        | HostAbiType::RuntimeStatus
        | HostAbiType::HostSessionHandle
        | HostAbiType::NativeArray(_) => {}
    }
}

/// Render one generated Android host interface file.
pub(super) fn render_kotlin_host_interface(module: &HostAbiModule, role: HostRole) -> String {
    let mut output = String::new();
    let mut imports = Vec::new();
    let method_count = host_methods(module, role).len();
    let interface_keyword = if method_count == 1 {
        "fun interface"
    } else {
        "interface"
    };
    let contract_name = host_interface_name(module, role);

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str(&format!(
        "package dev.destack.runtime.android.module.{}\n\n",
        module.name
    ));

    if host_interface_uses_type(module, role, HostAbiType::HostRequestId) {
        imports.push("dev.destack.runtime.android.core.HostRequestId".to_string());
    }

    if matches!(role, HostRole::Requests) {
        imports.push("dev.destack.runtime.android.core.hostStatusNotSupported".to_string());
    }

    for import in imports {
        output.push_str(&format!("import {import}\n"));
    }

    if host_interface_uses_type(module, role, HostAbiType::HostRequestId)
        || matches!(role, HostRole::Requests)
    {
        output.push('\n');
    }

    push_kotlin_doc_comment(
        &mut output,
        &format!(
            "The {} {} surface attached to one Android runtime host.",
            module.name.replace('_', "-"),
            host_role_label(role),
        ),
        0,
    );
    output.push_str(&format!("public {interface_keyword} {contract_name} {{\n"));

    for method in host_methods(module, role) {
        render_kotlin_host_method(&mut output, module, method, role, false);
        output.push('\n');
    }

    output.push_str("}\n");

    match role {
        HostRole::Requests => {
            output.push('\n');
            render_kotlin_host_unsupported_requests(&mut output, module);
        }
        HostRole::Events => {
            output.push('\n');
            render_kotlin_host_noop_events(&mut output, module);
        }
    }

    output
}

fn has_host_requests(module: &HostAbiModule) -> bool {
    !module.requests.is_empty()
}

fn has_host_events(module: &HostAbiModule) -> bool {
    !module.ingress.is_empty()
}

fn host_interface_name(module: &HostAbiModule, role: HostRole) -> String {
    format!("{}{}", android_pascal_case(module.name), role.suffix())
}

fn render_kotlin_host_module(output: &mut String, module: &HostAbiModule) {
    let class_name = format!("{}Host", android_pascal_case(module.name));

    push_kotlin_doc_comment(
        output,
        &format!(
            "The {} host surface attached to one Android runtime host.",
            module.name.replace('_', "-"),
        ),
        0,
    );

    match (has_host_requests(module), has_host_events(module)) {
        (true, true) => {
            let requests_name = host_interface_name(module, HostRole::Requests);
            let events_name = host_interface_name(module, HostRole::Events);

            output.push_str(&format!("public class {class_name}(\n"));
            output.push_str(&format!("    requests: {requests_name},\n"));
            output.push_str(&format!("    private val events: {events_name},\n"));
            output.push_str(&format!(") : {requests_name}, {events_name} {{\n"));
            output.push_str(&format!(
                "    private var requests: {requests_name} = requests\n\n"
            ));
            render_kotlin_host_update_requests_method(output, &requests_name);
            output.push('\n');
            render_kotlin_host_wrapper_methods(output, module, HostRole::Events, "events");
            output.push('\n');
            render_kotlin_host_wrapper_methods(output, module, HostRole::Requests, "requests");
            output.push_str("}\n");
        }
        (true, false) => {
            let requests_name = host_interface_name(module, HostRole::Requests);

            output.push_str(&format!("public class {class_name}(\n"));
            output.push_str(&format!("    requests: {requests_name},\n"));
            output.push_str(&format!(") : {requests_name} {{\n"));
            output.push_str(&format!(
                "    private var requests: {requests_name} = requests\n\n"
            ));
            render_kotlin_host_update_requests_method(output, &requests_name);
            output.push('\n');
            render_kotlin_host_wrapper_methods(output, module, HostRole::Requests, "requests");
            output.push_str("}\n");
        }
        (false, true) => {
            let events_name = host_interface_name(module, HostRole::Events);

            output.push_str(&format!("public class {class_name}(\n"));
            output.push_str(&format!("    private val events: {events_name},\n"));
            output.push_str(&format!(") : {events_name} {{\n"));
            render_kotlin_host_wrapper_methods(output, module, HostRole::Events, "events");
            output.push_str("}\n");
        }
        (false, false) => panic!("missing host surfaces for module {}", module.name),
    }
}

fn render_kotlin_host_update_requests_method(output: &mut String, requests_name: &str) {
    push_kotlin_doc_comment(output, "Replace the request surface for this host.", 4);
    output.push_str("    internal fun updateRequests(\n");
    output.push_str(&format!("        requests: {requests_name},\n"));
    output.push_str("    ) {\n");
    output.push_str("        this.requests = requests\n");
    output.push_str("    }\n");
}

fn render_kotlin_host_wrapper_methods(
    output: &mut String,
    module: &HostAbiModule,
    role: HostRole,
    receiver: &str,
) {
    let methods = host_methods(module, role);

    for (index, method) in methods.iter().copied().enumerate() {
        render_kotlin_host_method(output, module, method, role, true);
        output.pop();
        output.push_str(" {\n");

        let call = render_kotlin_host_call(method, receiver);
        if method.return_type(module, role).is_some() {
            output.push_str("        return ");
            output.push_str(&call);
            output.push('\n');
        } else {
            output.push_str("        ");
            output.push_str(&call);
            output.push('\n');
        }

        output.push_str("    }");

        if index + 1 != methods.len() {
            output.push_str("\n\n");
        } else {
            output.push('\n');
        }
    }
}

fn render_kotlin_host_method(
    output: &mut String,
    module: &HostAbiModule,
    method: HostMethod<'_>,
    role: HostRole,
    is_override: bool,
) {
    push_kotlin_doc_comment(output, method.documentation(), 4);
    output.push_str("    ");

    if is_override {
        output.push_str("override ");
    } else {
        output.push_str("public ");
    }

    output.push_str("fun ");
    output.push_str(&method.name());
    output.push_str("(\n");

    for parameter in method.parameters() {
        let parameter_name = parameter.name();

        output.push_str("        ");
        output.push_str(&android_kotlin_parameter_name(parameter_name));
        output.push_str(": ");
        output.push_str(&parameter.render_type(module, role));
        output.push_str(",\n");
    }

    output.push_str("    )");

    if let Some(return_type) = method.return_type(module, role) {
        output.push_str(&format!(": {return_type}"));
    }

    output.push('\n');
}

fn render_kotlin_host_unsupported_requests(output: &mut String, module: &HostAbiModule) {
    let contract_name = host_interface_name(module, HostRole::Requests);
    let unsupported_name = format!("Unsupported{contract_name}");

    push_kotlin_doc_comment(
        output,
        &format!(
            "The explicit unsupported {} request surface for one Android runtime host.",
            module.name.replace('_', "-"),
        ),
        0,
    );
    output.push_str(&format!(
        "public object {unsupported_name} : {contract_name} {{\n"
    ));

    for method in host_methods(module, HostRole::Requests) {
        render_kotlin_host_method(output, module, method, HostRole::Requests, true);
        output.pop();
        output.push_str(" {\n");

        if let Some(expression) = render_kotlin_unsupported_request_value(module, method) {
            output.push_str("        return ");
            output.push_str(&expression);
            output.push('\n');
        }

        output.push_str("    }\n\n");
    }

    output.push_str("}\n");
}

fn render_kotlin_host_noop_events(output: &mut String, module: &HostAbiModule) {
    let contract_name = host_interface_name(module, HostRole::Events);
    let noop_name = format!("Noop{contract_name}");

    push_kotlin_doc_comment(
        output,
        &format!(
            "The explicit no-op {} event surface for one Android runtime host.",
            module.name.replace('_', "-"),
        ),
        0,
    );
    output.push_str(&format!("public object {noop_name} : {contract_name} {{\n"));

    for method in host_methods(module, HostRole::Events) {
        render_kotlin_host_method(output, module, method, HostRole::Events, true);
        output.pop();
        output.push_str(" {\n");
        output.push_str("    }\n\n");
    }

    output.push_str("}\n");
}

fn render_kotlin_host_type(module: &HostAbiModule, ty: &HostAbiType, role: HostRole) -> String {
    match ty {
        HostAbiType::Named(name) => render_android_named_type(module, name),
        HostAbiType::Optional(inner) => {
            format!("{}?", render_kotlin_host_type(module, inner, role))
        }
        HostAbiType::NativeSlice(inner) => {
            format!("List<{}>", render_kotlin_host_type(module, inner, role))
        }
        HostAbiType::StringRef => "String".to_string(),
        HostAbiType::OsPath => "String".to_string(),
        HostAbiType::StringSlice => "List<String>".to_string(),
        HostAbiType::HostRequestId => "HostRequestId".to_string(),
        HostAbiType::Bool => "Boolean".to_string(),
        HostAbiType::U8 | HostAbiType::U16 | HostAbiType::I8 | HostAbiType::I16 => {
            "Int".to_string()
        }
        HostAbiType::U32 => {
            if matches!(role, HostRole::Requests) {
                "Int".to_string()
            } else {
                "UInt".to_string()
            }
        }
        HostAbiType::I32 => "Int".to_string(),
        HostAbiType::U64 => "Long".to_string(),
        HostAbiType::F64 => "Double".to_string(),
        HostAbiType::HostStatus => "Int".to_string(),
        HostAbiType::RuntimeStatus => "RuntimeIngressStatus".to_string(),
        HostAbiType::HostSessionHandle
        | HostAbiType::OutputPointer(_)
        | HostAbiType::NativeArray(_) => {
            panic!("unsupported Android runtime-host type")
        }
    }
}

fn render_android_named_type(module: &HostAbiModule, name: &str) -> String {
    let _ = module;
    format!("Runtime{name}")
}

fn render_kotlin_unsupported_request_value(
    module: &HostAbiModule,
    method: HostMethod<'_>,
) -> Option<String> {
    let Some(return_type) = method.return_type(module, HostRole::Requests) else {
        return None;
    };

    let ty = method.result_type();

    Some(match ty {
        HostAbiType::Bool => "false".to_string(),
        HostAbiType::StringRef => "\"\"".to_string(),
        HostAbiType::StringSlice | HostAbiType::NativeSlice(_) => "emptyList()".to_string(),
        HostAbiType::HostStatus => "hostStatusNotSupported".to_string(),
        HostAbiType::Named(_) => format!("{return_type}(status = hostStatusNotSupported)"),
        _ => format!("{return_type}(status = hostStatusNotSupported)"),
    })
}

fn render_kotlin_host_call(method: HostMethod<'_>, receiver: &str) -> String {
    let mut output = String::new();
    output.push_str(receiver);
    output.push('.');
    output.push_str(&method.name());
    output.push('(');

    let parameters = method.parameters();
    for (index, parameter) in parameters.iter().copied().enumerate() {
        let name = android_kotlin_parameter_name(parameter.name());

        if index > 0 {
            output.push_str(", ");
        }

        output.push_str(&name);
    }

    output.push(')');
    output
}

fn host_methods<'a>(module: &'a HostAbiModule, role: HostRole) -> Vec<HostMethod<'a>> {
    match role {
        HostRole::Requests => module.requests.iter().map(HostMethod::Request).collect(),
        HostRole::Events => module.ingress.iter().map(HostMethod::Ingress).collect(),
    }
}

fn host_interface_uses_type(module: &HostAbiModule, role: HostRole, ty: HostAbiType) -> bool {
    host_methods(module, role).into_iter().any(|method| {
        method.result_type() == &ty
            || method.parameters().into_iter().any(|parameter| {
                matches!(parameter.ty(), HostSurfaceType::Abi(parameter_ty) if parameter_ty == &ty)
            })
    })
}

fn host_role_label(role: HostRole) -> &'static str {
    match role {
        HostRole::Requests => "request",
        HostRole::Events => "event",
    }
}

#[derive(Clone, Copy)]
enum HostMethod<'a> {
    Request(&'a HostAbiFunction),
    Ingress(&'a HostAbiFunction),
}

impl<'a> HostMethod<'a> {
    fn name(self) -> String {
        match self {
            Self::Request(request) => android_kotlin_parameter_name(request.name),
            Self::Ingress(ingress) => android_kotlin_parameter_name(ingress.name),
        }
    }

    fn documentation(self) -> &'static str {
        match self {
            Self::Request(request) => request.documentation,
            Self::Ingress(ingress) => ingress.documentation,
        }
    }

    fn parameters(self) -> Vec<HostParameter<'a>> {
        match self {
            Self::Request(request) => host_call_parameters(&request.parameters)
                .into_iter()
                .map(HostParameter::Call)
                .collect(),
            Self::Ingress(ingress) => ingress
                .parameters
                .iter()
                .filter(|parameter| !matches!(parameter.ty, HostAbiType::HostSessionHandle))
                .map(HostParameter::Abi)
                .collect(),
        }
    }

    fn result_type(self) -> &'a HostAbiType {
        match self {
            Self::Request(request) => request
                .parameters
                .iter()
                .find_map(|parameter| match &parameter.ty {
                    HostAbiType::OutputPointer(inner) => Some(inner.as_ref()),
                    _ => None,
                })
                .unwrap_or(&request.result),
            Self::Ingress(_) => &HOST_STATUS_TYPE,
        }
    }

    fn return_type(self, module: &HostAbiModule, role: HostRole) -> Option<String> {
        match self {
            Self::Request(_) => Some(render_kotlin_host_type(module, self.result_type(), role)),
            Self::Ingress(_) => None,
        }
    }
}

#[derive(Clone, Copy)]
enum HostParameter<'a> {
    Abi(&'a destack_runtime::host::abi::describe::HostAbiParameter),
    Call(HostCallParameter<'a>),
}

impl<'a> HostParameter<'a> {
    fn name(self) -> &'a str {
        match self {
            Self::Abi(parameter) => parameter.name,
            Self::Call(parameter) => parameter.name(),
        }
    }

    fn ty(self) -> HostSurfaceType<'a> {
        match self {
            Self::Abi(parameter) => HostSurfaceType::Abi(&parameter.ty),
            Self::Call(parameter) => match parameter.ty() {
                HostCallParameterType::Abi(ty) => HostSurfaceType::Abi(ty),
            },
        }
    }
}

enum HostSurfaceType<'a> {
    Abi(&'a HostAbiType),
}

impl HostParameter<'_> {
    fn render_type(self, module: &HostAbiModule, role: HostRole) -> String {
        let HostSurfaceType::Abi(ty) = self.ty();
        render_kotlin_host_type(module, ty, role)
    }
}
