/// Configure one session-bound Kotlin ingress bridge.
fn configure_kotlin_session_ingress_bridge(
    bridge: &mut KotlinBridgeSpec,
    implemented_interface: &'static str,
    bindings_type: &'static str,
    imports: &[&'static str],
) {
    bridge
        .imports
        .extend(imports.iter().map(|import| (*import).to_string()));
    bridge.constructor_fields.extend([
        KotlinBridgeField {
            qualifier: "private val",
            name: "sessionHandle",
            ty: "HostSessionHandle".to_string(),
        },
        KotlinBridgeField {
            qualifier: "private val",
            name: "bindings",
            ty: bindings_type.to_string(),
        },
    ]);
    let _ = implemented_interface;
}

