/// Render one Android Kotlin projected native type.
fn render_android_kotlin_native_type(ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::U8 | HostAbiType::U16 | HostAbiType::I8 | HostAbiType::I16 => {
            "Int".to_string()
        }
        HostAbiType::U32 => "UInt".to_string(),
        HostAbiType::I32 => "Int".to_string(),
        HostAbiType::U64 => "Long".to_string(),
        HostAbiType::HostRequestId => "HostRequestId".to_string(),
        HostAbiType::Bool => "Boolean".to_string(),
        HostAbiType::F64 => "Double".to_string(),
        HostAbiType::StringRef => "String".to_string(),
        HostAbiType::StringSlice => "List<String>".to_string(),
        HostAbiType::HostSessionHandle => "HostSessionHandle".to_string(),
        HostAbiType::HostStatus => "Int".to_string(),
        HostAbiType::RuntimeStatus => "RuntimeAbiStatus".to_string(),
        HostAbiType::NativeArray(_) => {
            panic!("unsupported Android Kotlin array projection")
        }
        HostAbiType::NativeSlice(element) => {
            format!("List<{}>", render_android_kotlin_native_type(element))
        }
        HostAbiType::OutputPointer(_) => {
            panic!("unsupported Android Kotlin output-pointer projection")
        }
        HostAbiType::Named(name) => format!("Runtime{name}"),
    }
}

/// Return one Kotlin parameter label for one snake-case parameter.
pub(super) fn android_kotlin_parameter_name(name: &str) -> String {
    let mut segments = name.split('_');
    let Some(first) = segments.next() else {
        return String::new();
    };

    let mut label = first.to_string();
    for segment in segments {
        if segment == "id" {
            label.push_str("Id");
            continue;
        }
        if segment == "url" {
            label.push_str("Url");
            continue;
        }

        let mut characters = segment.chars();
        let Some(first_character) = characters.next() else {
            continue;
        };

        label.push(first_character.to_ascii_uppercase());
        label.extend(characters);
    }

    label
}
