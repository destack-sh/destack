/// Build one generated callback method that directly forwards into one request helper.
fn build_simple_runtime_host_callback_method(
    module: &HostAbiModule,
    request: &HostAbiFunction,
    on_main_thread: bool,
    on_missing: String,
) -> KotlinBridgeMethod {
    let name = android_runtime_bridge_method_name(module, request);
    let parameters = request
        .parameters
        .iter()
        .filter(|parameter| {
            !matches!(
                parameter.ty,
                HostAbiType::HostSessionHandle | HostAbiType::OutputPointer(_)
            )
        })
        .map(|parameter| KotlinBridgeParameter {
            name: android_kotlin_parameter_name(parameter.name),
            ty: render_android_kotlin_bridge_parameter_type(module, request, parameter),
        })
        .collect::<Vec<_>>();

    let mut call_arguments = vec![("runtimeHost".to_string(), "runtimeHost".to_string())];
    call_arguments.extend(
        parameters
            .iter()
            .map(|parameter| (parameter.name.clone(), parameter.name.clone())),
    );

    build_resolve_runtime_host_kotlin_method(
        request.documentation,
        &name,
        parameters,
        &render_android_kotlin_bridge_request_return_type(module, request),
        on_main_thread,
        &on_missing,
        Vec::new(),
        build_local_kotlin_call(&name, call_arguments),
    )
}

