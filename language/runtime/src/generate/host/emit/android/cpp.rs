/// Render one generated Android C++ runtime header.
pub(super) fn render_cpp_runtime_header(module: &HostAbiModule) -> String {
    let mut output = String::new();
    let guard = format!(
        "DESTACK_RUNTIME_ANDROID_BRIDGE_{}_RUNTIME_H",
        module.name.to_ascii_uppercase()
    );

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str(&format!("#ifndef {guard}\n"));
    output.push_str(&format!("#define {guard}\n\n"));
    output.push_str("#include \"../types.h\"\n\n");

    for request in &module.requests {
        push_cpp_doc_comment(
            &mut output,
            &format!(
                "Forward the `{}` {} request through one attached bridge session.",
                request.name, module.name
            ),
            0,
        );
        output.push_str("uint32_t ");
        output.push_str(&android_cpp_runtime_request_name(module, request));
        output.push_str("(\n");
        render_cpp_signature_parameters(&mut output, &request.parameters);
        output.push_str(");\n\n");
    }

    push_cpp_doc_comment(
        &mut output,
        &format!("Build one Android host {} callback bundle.", module.name),
        0,
    );
    output.push_str(&android_cpp_callback_struct_name(module));
    output.push(' ');
    output.push_str(&android_cpp_callback_bundle_name(module));
    output.push_str("();\n\n");

    if module.ingress.first().is_some() {
        push_cpp_doc_comment(
            &mut output,
            &format!("Register the {} runtime ingress JNI methods.", module.name),
            0,
        );
        output.push_str(&format!(
            "bool register_{}_runtime_natives(JNIEnv *env);\n\n",
            module.name
        ));
    }

    if let Some(ingress) = module.ingress.first() {
        push_cpp_doc_comment(
            &mut output,
            &format!(
                "Send the `{}` {} ingress payload into the runtime ingress path.",
                android_cpp_ingress_stem(ingress),
                module.name
            ),
            0,
        );
        output.push_str("RuntimeStatus ");
        output.push_str(&android_cpp_send_name(ingress));
        output.push_str("(\n");
        render_cpp_signature_parameters(&mut output, &ingress.parameters);
        output.push_str(");\n\n");
    }

    output.push_str("#endif\n");
    output
}

/// Render one generated Android C++ methods header.
pub(super) fn render_cpp_methods_header(module: &HostAbiModule) -> String {
    let mut output = String::new();
    let guard = format!(
        "DESTACK_RUNTIME_ANDROID_BRIDGE_{}_METHODS_H",
        module.name.to_ascii_uppercase()
    );

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str(&format!("#ifndef {guard}\n"));
    output.push_str(&format!("#define {guard}\n\n"));
    output.push_str("#include \"../types.h\"\n\n");
    push_cpp_doc_comment(
        &mut output,
        &format!(
            "Resolve the {} bridge methods from one runtime bridge instance.",
            module.name
        ),
        0,
    );
    output.push_str(&format!(
        "bool resolve_{}_methods(JNIEnv *env, jobject bridge);\n",
        module.name
    ));

    for request in &module.requests {
        push_cpp_doc_comment(
            &mut output,
            &format!(
                "Call the {}-{} entrypoint on one registered bridge.",
                module.name,
                request.name.replace('_', "-")
            ),
            0,
        );
        output.push_str("uint32_t ");
        output.push_str(&android_cpp_methods_request_name(module, request));
        output.push_str("(\n");
        output.push_str("    JNIEnv *env,\n");
        for (index, parameter) in request.parameters.iter().enumerate() {
            let trailing = if index + 1 == request.parameters.len() {
                ""
            } else {
                ","
            };
            let declaration =
                render_cpp_parameter_declaration(&render_cpp_type(&parameter.ty), parameter.name);
            output.push_str(&format!("    {declaration}{trailing}\n"));
        }
        output.push_str(");\n\n");
    }

    output.push_str("#endif\n");
    output
}

/// Render one generated Android C++ methods source.
pub(super) fn render_cpp_methods_source(module: &HostAbiModule) -> String {
    render_generic_cpp_methods_source(module)
}

pub(super) fn render_cpp_ingress_bridge_source(module: &HostAbiModule) -> Option<String> {
    Some(render_generic_cpp_runtime_jni_wrapper_source(
        module,
        single_ingress(module),
    ))
}

fn android_cpp_uses_jni_strings(module: &HostAbiModule) -> bool {
    module.ingress.first().is_some_and(|ingress| {
        ingress
            .parameters
            .iter()
            .any(|parameter| android_cpp_type_uses_jni_strings(module, &parameter.ty))
    })
}

/// Render one generated Android C++ runtime source.
pub(super) fn render_cpp_runtime_source(module: &HostAbiModule) -> String {
    let mut output = String::new();

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("#include \"../types.h\"\n");
    output.push_str("#include \"../jni.h\"\n");
    output.push_str("#include \"../loader.h\"\n");
    output.push_str("#include \"callbacks.generated.h\"\n");
    output.push_str("#include \"runtime.generated.h\"\n\n");
    output.push_str("#include <deque>\n");
    output.push_str("#include <string>\n");
    output.push_str("#include <vector>\n\n");
    output.push_str("namespace {\n\n");

    push_cpp_doc_comment(
        &mut output,
        "Convert one host status code into one runtime status.",
        0,
    );
    output.push_str("RuntimeStatus runtime_status_from_code(uint32_t code) {\n");
    output.push_str("    RuntimeStatus status = {\n");
    output.push_str("        .code = code,\n");
    output.push_str("        .error_id = 0,\n");
    output.push_str("    };\n\n");
    output.push_str("    return status;\n");
    output.push_str("}\n");

    if android_cpp_uses_jni_strings(module) {
        output.push('\n');
        push_cpp_doc_comment(
            &mut output,
            "Borrow one runtime string reference from one JNI string.",
            0,
        );
        output.push_str(
            "NativeStringRef native_string_ref_from_jstring(JNIEnv *env, jstring value) {\n",
        );
        output.push_str("    if (value == nullptr) {\n");
        output.push_str("        return {\n");
        output.push_str("            .data = nullptr,\n");
        output.push_str("            .len = 0,\n");
        output.push_str("        };\n");
        output.push_str("    }\n\n");
        output.push_str("    const char *chars = env->GetStringUTFChars(value, nullptr);\n");
        output.push_str("    jsize length = env->GetStringUTFLength(value);\n\n");
        output.push_str("    return {\n");
        output.push_str("        .data = reinterpret_cast<const uint8_t *>(chars),\n");
        output.push_str("        .len = static_cast<uint32_t>(length),\n");
        output.push_str("    };\n");
        output.push_str("}\n\n");

        push_cpp_doc_comment(
            &mut output,
            "Release one runtime string reference borrowed from one JNI string.",
            0,
        );
        output.push_str(
            "void release_native_string_ref(JNIEnv *env, jstring value, NativeStringRef ref) {\n",
        );
        output.push_str("    if (value == nullptr || ref.data == nullptr) {\n");
        output.push_str("        return;\n");
        output.push_str("    }\n\n");
        output.push_str("    env->ReleaseStringUTFChars(\n");
        output.push_str("        value,\n");
        output.push_str("        reinterpret_cast<const char *>(ref.data)\n");
        output.push_str("    );\n");
        output.push_str("}\n");
    }

    output.push_str("\n}\n\n");

    for request in module
        .requests
        .iter()
        .filter(|request| android_cpp_generates_request_forwarder(module, request))
    {
        render_cpp_request_forwarder(&mut output, module, request);
        output.push('\n');
    }

    render_cpp_callback_bundle(&mut output, module);

    if let Some(ingress) = module.ingress.first() {
        output.push('\n');
        render_cpp_send_helper(&mut output, ingress);
    }

    output
}

/// Render one generated Android C++ request forwarder.
fn render_cpp_request_forwarder(
    output: &mut String,
    module: &HostAbiModule,
    request: &HostAbiFunction,
) {
    push_cpp_doc_comment(
        output,
        &format!(
            "Forward the `{}` {} request through one attached bridge session.",
            request.name, module.name
        ),
        0,
    );
    output.push_str("uint32_t ");
    output.push_str(&android_cpp_runtime_request_name(module, request));
    output.push_str("(\n");
    render_cpp_signature_parameters(output, &request.parameters);
    output.push_str(") {\n");
    output.push_str("    JNIEnv *env = nullptr;\n");
    output.push_str("    bool did_attach_thread = false;\n\n");
    output.push_str("    if (!resolve_jni_env(&env, &did_attach_thread)) {\n");
    output.push_str("        return HOST_STATUS_FAILED;\n");
    output.push_str("    }\n\n");
    output.push_str("    uint32_t status = ");
    output.push_str(&android_cpp_methods_request_name(module, request));
    output.push_str("(env");
    for parameter in &request.parameters {
        output.push_str(", ");
        output.push_str(parameter.name);
    }
    output.push_str(");\n\n");
    output.push_str("    detach_jni_thread(did_attach_thread);\n\n");
    output.push_str("    return status;\n");
    output.push_str("}\n");
}

/// Render one generated Android C++ runtime send helper.
fn render_cpp_send_helper(output: &mut String, ingress: &HostAbiFunction) {
    push_cpp_doc_comment(output, ingress.documentation, 0);
    output.push_str("RuntimeStatus ");
    output.push_str(&android_cpp_send_name(ingress));
    output.push_str("(\n");
    render_cpp_signature_parameters(output, &ingress.parameters);
    output.push_str(") {\n");
    output.push_str("    RuntimeBindings bindings = {};\n");
    output.push_str(
        "    RuntimeStatus status = runtime_status_from_code(resolve_runtime_bindings(&bindings));\n",
    );
    output.push_str("    if (status.code != HOST_STATUS_OK) {\n");
    output.push_str("        return status;\n");
    output.push_str("    }\n\n");
    output.push_str("    return bindings.");
    output.push_str(ingress.name);
    output.push('(');
    for (index, parameter) in ingress.parameters.iter().enumerate() {
        if index != 0 {
            output.push_str(", ");
        }
        output.push_str(parameter.name);
    }
    output.push_str(");\n");
    output.push_str("}\n");
}

/// Render one generated Android C++ callback bundle factory.
fn render_cpp_callback_bundle(output: &mut String, module: &HostAbiModule) {
    push_cpp_doc_comment(
        output,
        &format!("Build one Android host {} callback bundle.", module.name),
        0,
    );
    output.push_str(&android_cpp_callback_struct_name(module));
    output.push(' ');
    output.push_str(&android_cpp_callback_bundle_name(module));
    output.push_str("() {\n");
    output.push_str("    return ");
    output.push_str(&android_cpp_callback_struct_name(module));
    output.push_str(" {\n");

    for request in &module.requests {
        let field_name = android_cpp_callback_field_name(request);
        output.push_str(&format!(
            "        .{} = {},\n",
            field_name,
            android_cpp_runtime_request_name(module, request)
        ));
    }

    output.push_str("    };\n");
    output.push_str("}\n");
}

/// Render one C++ signature parameter list.
fn render_cpp_signature_parameters(
    output: &mut String,
    parameters: &[destack_runtime::host::abi::describe::HostAbiParameter],
) {
    for (index, parameter) in parameters.iter().enumerate() {
        let trailing = if index + 1 == parameters.len() {
            ""
        } else {
            ","
        };
        let parameter_declaration =
            render_cpp_parameter_declaration(&render_cpp_type(&parameter.ty), parameter.name);

        output.push_str(&format!("    {parameter_declaration}{trailing}\n"));
    }
}

/// Render one C++ parameter declaration.
pub(super) fn render_cpp_parameter_declaration(ty: &str, name: &str) -> String {
    if ty.ends_with('*') {
        return format!("{ty}{name}");
    }

    format!("{ty} {name}")
}

/// Return the generated Android C++ runtime request function name.
pub(super) fn android_cpp_runtime_request_name(
    module: &HostAbiModule,
    request: &HostAbiFunction,
) -> String {
    format!("call_{}_{}_for_session", module.name, request.name)
}

/// Return the generated Android C++ callback struct name.
fn android_cpp_callback_struct_name(module: &HostAbiModule) -> String {
    format!("AndroidHost{}Callbacks", android_pascal_case(module.name))
}

/// Return the generated Android C++ callback bundle function name.
fn android_cpp_callback_bundle_name(module: &HostAbiModule) -> String {
    format!("make_{}_callbacks", module.name)
}

/// Return the Android C++ callback field name for one request.
pub(super) fn android_cpp_callback_field_name(request: &HostAbiFunction) -> String {
    match request.name {
        "delete" => "delete_".to_string(),
        other => other.to_string(),
    }
}

/// Return the generated Android C++ methods call name.
pub(super) fn android_cpp_methods_request_name(
    module: &HostAbiModule,
    request: &HostAbiFunction,
) -> String {
    format!("call_{}_{}", module.name, request.name)
}

/// Return the generated Android C++ send helper name.
pub(super) fn android_cpp_send_name(ingress: &HostAbiFunction) -> String {
    format!("send_{}", android_cpp_ingress_stem(ingress))
}

/// Return the Android C++ ingress stem.
pub(super) fn android_cpp_ingress_stem(ingress: &HostAbiFunction) -> String {
    ingress.name.to_string()
}

/// Return whether one Android C++ request forwarder should be generated.
fn android_cpp_generates_request_forwarder(
    _module: &HostAbiModule,
    _request: &HostAbiFunction,
) -> bool {
    true
}

/// Render one Android C++ projected native type.
pub(super) fn render_cpp_type(ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::U8 => "uint8_t".to_string(),
        HostAbiType::U16 => "uint16_t".to_string(),
        HostAbiType::I8 => "int8_t".to_string(),
        HostAbiType::I16 => "int16_t".to_string(),
        HostAbiType::U32 => "uint32_t".to_string(),
        HostAbiType::I32 => "int32_t".to_string(),
        HostAbiType::U64 => "uint64_t".to_string(),
        HostAbiType::HostRequestId => "uint64_t".to_string(),
        HostAbiType::Bool => "bool".to_string(),
        HostAbiType::F64 => "double".to_string(),
        HostAbiType::StringRef => "NativeStringRef".to_string(),
        HostAbiType::OsPath => "NativeStringRef".to_string(),
        HostAbiType::StringSlice => "NativeStringSlice".to_string(),
        HostAbiType::HostSessionHandle => "uint64_t".to_string(),
        HostAbiType::HostStatus => "uint32_t".to_string(),
        HostAbiType::RuntimeStatus => "RuntimeStatus".to_string(),
        HostAbiType::NativeArray(inner) => format!("NativeArray<{}>", render_cpp_type(inner)),
        HostAbiType::NativeSlice(inner) => {
            if let HostAbiType::Named(name) = inner.as_ref() {
                format!("{name}Slice")
            } else if let Some(slice_type) = android_cpp_string_slice_type(inner) {
                slice_type.to_string()
            } else if let Some(slice_type) = android_cpp_primitive_slice_type(inner) {
                slice_type.to_string()
            } else {
                panic!("unsupported Android C++ native-slice projection");
            }
        }
        HostAbiType::OutputPointer(inner) => format!("{} *", render_cpp_type(inner)),
        HostAbiType::Optional(inner) => android_cpp_optional_type_name(inner),
        HostAbiType::Named(name) => (*name).to_string(),
    }
}

/// Return the generated Android C++ optional wrapper type name for one payload.
pub(super) fn android_cpp_optional_type_name(ty: &HostAbiType) -> String {
    format!("Optional{}", android_cpp_type_segment(ty))
}

/// Return the generated Android C++ type segment for one payload.
pub(super) fn android_cpp_type_segment(ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::U8 => "U8".to_string(),
        HostAbiType::U16 => "U16".to_string(),
        HostAbiType::I8 => "I8".to_string(),
        HostAbiType::I16 => "I16".to_string(),
        HostAbiType::U32 => "U32".to_string(),
        HostAbiType::I32 => "I32".to_string(),
        HostAbiType::U64 => "U64".to_string(),
        HostAbiType::HostRequestId => "HostRequestId".to_string(),
        HostAbiType::Bool => "Bool".to_string(),
        HostAbiType::F64 => "F64".to_string(),
        HostAbiType::StringRef => "StringRef".to_string(),
        HostAbiType::OsPath => "OsPath".to_string(),
        HostAbiType::StringSlice => "StringSlice".to_string(),
        HostAbiType::HostSessionHandle => "HostSessionHandle".to_string(),
        HostAbiType::HostStatus => "HostStatus".to_string(),
        HostAbiType::RuntimeStatus => "RuntimeStatus".to_string(),
        HostAbiType::NativeArray(inner) => {
            format!("{}Array", android_cpp_type_segment(inner))
        }
        HostAbiType::NativeSlice(inner) => {
            format!("{}Slice", android_cpp_type_segment(inner))
        }
        HostAbiType::OutputPointer(inner) => {
            format!("Pointer{}", android_cpp_type_segment(inner))
        }
        HostAbiType::Optional(inner) => {
            format!("Optional{}", android_cpp_type_segment(inner))
        }
        HostAbiType::Named(name) => (*name).to_string(),
    }
}
