use super::docs::{push_indented_rust_doc_comment, push_rust_doc_comment};
use crate::host::model::{CallbackLane, HostArtifact, HostCatalog, HostPlatform};
use crate::platform::model::WorkspaceLayout;

/// Render the generated Rust iOS binding files.
pub(crate) fn render_ios_binding_files(
    layout: &WorkspaceLayout,
    catalog: &HostCatalog,
) -> Vec<HostArtifact> {
    vec![
        HostArtifact {
            path: layout
                .language_root
                .join("runtime/src/host/apple/abi/bindings.generated.rs"),
            contents: render_bindings_file(
                HostPlatform::Ios,
                catalog.binding_lanes(HostPlatform::Ios),
            ),
        },
        HostArtifact {
            path: layout
                .language_root
                .join("runtime/src/host/apple/abi/bridge.generated.rs"),
            contents: render_bridge_file(
                HostPlatform::Ios,
                catalog.bridge_lanes(HostPlatform::Ios),
            ),
        },
    ]
}

/// Render the generated Rust Android binding files.
pub(crate) fn render_android_binding_files(
    layout: &WorkspaceLayout,
    catalog: &HostCatalog,
) -> Vec<HostArtifact> {
    vec![
        HostArtifact {
            path: layout
                .language_root
                .join("runtime/src/host/android/abi/bindings.generated.rs"),
            contents: render_bindings_file(
                HostPlatform::Android,
                catalog.binding_lanes(HostPlatform::Android),
            ),
        },
        HostArtifact {
            path: layout
                .language_root
                .join("runtime/src/host/android/abi/bridge.generated.rs"),
            contents: render_bridge_file(
                HostPlatform::Android,
                catalog.bridge_lanes(HostPlatform::Android),
            ),
        },
    ]
}

/// Render one generated platform bindings file.
fn render_bindings_file(platform: HostPlatform, lanes: &[CallbackLane]) -> String {
    let mut output = String::new();
    let module_segment = rust_platform_host_segment(platform);
    let abi_segment = platform.segment();

    output.push_str("// generated by generate-bindings: do not edit\n\n");

    if matches!(platform, HostPlatform::Android) {
        output.push_str("#![allow(unreachable_pub)]\n\n");
    }

    for lane in lanes {
        output.push_str(&format!(
            "use crate::host::{module_segment}::abi::{}::{}::{};\n",
            lane.module_name, lane.submodule_name, lane.callback_type
        ));
    }

    output.push_str(&format!(
        "use crate::host::{module_segment}::abi::registry::resolve_{abi_segment}_bindings;\n"
    ));

    match platform {
        HostPlatform::Ios => {
            output.push_str("use crate::host::HOST_STATUS_NOT_SUPPORTED;\n");
            output.push_str("use crate::host::HostSessionHandle;\n\n");
        }
        HostPlatform::Android => {
            output.push_str("use crate::host::{HostSessionHandle, HostStatus};\n\n");
        }
    }

    push_rust_doc_comment(
        &mut output,
        &format!(
            "{} host bindings container for callback-backed lanes.",
            platform.label()
        ),
    );
    output.push_str("#[derive(Clone, Copy, Debug, Default)]\n");
    output.push_str("#[repr(C)]\n");
    output.push_str(&format!(
        "pub(crate) struct {}HostBindings {{\n",
        platform.rust_name()
    ));

    for lane in lanes {
        push_indented_rust_doc_comment(
            &mut output,
            "    ",
            &format!("{} host callbacks.", lane.subject),
        );
        output.push_str(&format!(
            "    pub {}: {},\n",
            lane.field_name, lane.callback_type
        ));
    }

    output.push_str("}\n\n");

    push_rust_doc_comment(
        &mut output,
        &format!(
            "Resolve one callback from one {} host bindings lane.",
            platform.label()
        ),
    );
    output.push_str(&format!(
        "pub(crate) fn resolve_{}_binding_callback<T: Copy>(\n",
        abi_segment
    ));
    output.push_str("    session_handle: HostSessionHandle,\n");
    output.push_str(&format!(
        "    resolve: impl FnOnce(&{}HostBindings) -> Option<T>,\n",
        platform.rust_name()
    ));
    output.push_str(") -> Result<T, u32> {\n");
    output.push_str(&format!(
        "    let bindings = resolve_{}_bindings(session_handle)?;\n\n",
        abi_segment
    ));
    match platform {
        HostPlatform::Ios => {
            output.push_str("    resolve(&bindings).ok_or(HOST_STATUS_NOT_SUPPORTED)\n");
        }
        HostPlatform::Android => {
            output.push_str("    resolve(&bindings).ok_or(HostStatus::NotSupported.code())\n");
        }
    }
    output.push_str("}\n\n");

    push_rust_doc_comment(
        &mut output,
        &format!("Resolve and invoke one {} host callback.", platform.label()),
    );
    output.push_str(&format!(
        "pub(crate) fn invoke_{}_binding_callback<T: Copy>(\n",
        abi_segment
    ));
    output.push_str("    session_handle: HostSessionHandle,\n");
    output.push_str(&format!(
        "    resolve: impl FnOnce(&{}HostBindings) -> Option<T>,\n",
        platform.rust_name()
    ));
    output.push_str("    invoke: impl FnOnce(T) -> u32,\n");
    output.push_str(") -> u32 {\n");
    output.push_str(&format!(
        "    let callback = match resolve_{}_binding_callback(session_handle, resolve) {{\n",
        abi_segment
    ));
    output.push_str("        Ok(callback) => callback,\n");
    output.push_str("        Err(status) => return status,\n");
    output.push_str("    };\n\n");
    output.push_str("    invoke(callback)\n");
    output.push_str("}\n");

    output
}

/// Return the Rust host module segment for one platform.
fn rust_platform_host_segment(platform: HostPlatform) -> &'static str {
    match platform {
        HostPlatform::Android => "android",
        HostPlatform::Ios => "apple",
    }
}

/// Render one generated runtime-bridge file.
fn render_bridge_file(platform: HostPlatform, lanes: &[CallbackLane]) -> String {
    let mut output = String::new();
    let module_segment = rust_platform_host_segment(platform);
    let abi_segment = platform.segment();

    output.push_str("// generated by generate-bindings: do not edit\n\n");

    match platform {
        HostPlatform::Ios => {
            output.push_str("#![cfg_attr(not(target_os = \"ios\"), allow(dead_code))]\n\n");
        }
        HostPlatform::Android => {
            output.push_str("#![cfg_attr(not(target_os = \"android\"), allow(dead_code))]\n\n");
        }
    }

    for lane in lanes {
        output.push_str(&format!(
            "use crate::host::{module_segment}::abi::{}::{}::{};\n",
            lane.module_name, lane.submodule_name, lane.callback_type
        ));
    }

    output.push_str(&format!(
        "use crate::host::{module_segment}::abi::binding::{}HostBindings;\n",
        platform.rust_name()
    ));
    output.push_str(&format!(
        "use crate::host::{module_segment}::abi::registry::{{register_{abi_segment}_bindings, unregister_{abi_segment}_bindings}};\n"
    ));
    match platform {
        HostPlatform::Ios => {
            output.push_str("use crate::host::{HostSessionHandle, HostSessionId};\n\n");
        }
        HostPlatform::Android => {
            output.push_str("use crate::host::HostSessionHandle;\n\n");
        }
    }

    push_rust_doc_comment(
        &mut output,
        &format!(
            "{} runtime-bridge bindings for the mobile host lanes.",
            platform.label()
        ),
    );
    if matches!(platform, HostPlatform::Android) {
        push_rust_doc_comment(
            &mut output,
            "This layout must stay in lockstep with `AndroidRuntimeBridgeBindings` in `bridge/types.h`.",
        );
    }
    output.push_str("#[derive(Clone, Copy, Debug, Default)]\n");
    output.push_str("#[repr(C)]\n");
    output.push_str(&format!(
        "pub(crate) struct {}RuntimeBridgeBindings {{\n",
        platform.rust_name()
    ));

    for lane in lanes {
        push_indented_rust_doc_comment(
            &mut output,
            "    ",
            &format!("The {} host callbacks.", lane.subject),
        );
        output.push_str(&format!(
            "    pub(crate) {}: {},\n",
            lane.field_name, lane.callback_type
        ));
    }

    output.push_str("}\n\n");

    push_rust_doc_comment(
        &mut output,
        &format!(
            "Register one {} runtime-bridge callback table through one runtime seam entrypoint.",
            platform.label()
        ),
    );
    output.push_str(&format!(
        "pub(crate) unsafe fn destack_host_{}_register_runtime_bridge_bindings(\n",
        abi_segment
    ));
    output.push_str("    session_handle: HostSessionHandle,\n");
    output.push_str(&format!(
        "    bindings: {}RuntimeBridgeBindings,\n",
        platform.rust_name()
    ));
    output.push_str(") -> u32 {\n");
    output.push_str(&format!(
        "    let bindings = {}HostBindings {{\n",
        platform.rust_name()
    ));

    for lane in lanes {
        output.push_str(&format!(
            "        {}: bindings.{},\n",
            lane.field_name, lane.field_name
        ));
    }

    output.push_str(&format!(
        "        ..{}HostBindings::default()\n",
        platform.rust_name()
    ));
    output.push_str("    };\n\n");
    output.push_str(&format!(
        "    register_{}_bindings(session_handle, bindings)\n",
        abi_segment
    ));
    output.push_str("}\n\n");

    push_rust_doc_comment(
        &mut output,
        &format!(
            "Remove one {} runtime-bridge callback table through one runtime seam entrypoint.",
            platform.label()
        ),
    );
    output.push_str(&format!(
        "pub(crate) unsafe fn destack_host_{}_unregister_runtime_bridge_bindings(\n",
        abi_segment
    ));
    output.push_str("    session_handle: HostSessionHandle,\n");
    output.push_str(") {\n");
    match platform {
        HostPlatform::Ios => {
            output.push_str("    let session_id = HostSessionId::from_handle(session_handle);\n\n");
            output.push_str("    unregister_ios_bindings(session_id);\n");
        }
        HostPlatform::Android => {
            output.push_str("    unregister_android_bindings(session_handle);\n");
        }
    }
    output.push_str("}\n");

    output
}
