use std::collections::BTreeSet;

use crate::host::model::{HostArtifact, HostCatalog, HostModule, HostPlatform};
use crate::platform::model::WorkspaceLayout;
use destack_runtime::host::abi::describe::{HostAbiFunction, HostAbiType};

/// Render the generated Rust ABI crate files.
pub(crate) fn render_runtime_abi_files(
    layout: &WorkspaceLayout,
    catalog: &HostCatalog,
) -> Vec<HostArtifact> {
    let mut files = Vec::new();

    files.extend(render_platform_runtime_abi_files(
        layout,
        catalog,
        HostPlatform::Android,
    ));
    files.extend(render_platform_runtime_abi_files(
        layout,
        catalog,
        HostPlatform::Ios,
    ));

    files
}

/// Render the generated Rust ABI crate files for one platform.
fn render_platform_runtime_abi_files(
    layout: &WorkspaceLayout,
    catalog: &HostCatalog,
    platform: HostPlatform,
) -> Vec<HostArtifact> {
    let mut files = Vec::new();
    let platform_segment = platform.segment();

    // platform root
    files.push(HostArtifact::new(
        layout
            .language_root
            .join(format!("runtime/abi/src/{platform_segment}/mod.rs")),
        render_runtime_abi_platform_mod_file(catalog, platform),
    ));

    // shared bridge bindings
    files.push(HostArtifact::new(
        layout.language_root.join(format!(
            "runtime/abi/src/{platform_segment}/bridge.generated.rs"
        )),
        render_runtime_abi_bridge_file(platform),
    ));

    // per module wrappers
    for module in catalog.modules_for_platform(platform) {
        if !runtime_abi_module_is_generated(module) {
            continue;
        }

        files.push(HostArtifact::new(
            layout.language_root.join(format!(
                "runtime/abi/src/{platform_segment}/{}.generated.rs",
                module.name()
            )),
            render_runtime_abi_module_file(catalog, module, platform),
        ));
    }

    files
}

/// Return whether one platform module uses the generated ABI crate path.
fn runtime_abi_module_is_generated(module: &HostModule) -> bool {
    !module.requests().is_empty() || module.has_ingress()
}

/// Render the generated ABI crate module file for one platform root.
fn render_runtime_abi_platform_mod_file(catalog: &HostCatalog, platform: HostPlatform) -> String {
    let mut output = String::new();
    let mut modules = catalog
        .modules_for_platform(platform)
        .into_iter()
        .filter(|module| runtime_abi_module_is_generated(module))
        .map(|module| (module.name(), true))
        .collect::<Vec<_>>();

    modules.push(("bridge", true));
    modules.push(("lifecycle", false));
    modules.push(("system", false));
    modules.sort_by_key(|(module_name, _)| *module_name);

    output.push_str("// generated by generate-bindings: do not edit\n\n");

    // module declarations
    for (module_name, is_generated) in &modules {
        let path = if *is_generated {
            format!("{module_name}.generated.rs")
        } else {
            format!("{module_name}.rs")
        };

        output.push_str(&format!("#[path = \"{path}\"]\n"));
        output.push_str(&format!("mod {module_name};\n"));
    }

    output.push('\n');

    // public exports
    for (module_name, _) in &modules {
        output.push_str(&format!("pub use {module_name}::*;\n"));
    }

    output
}

/// Render the generated ABI crate bridge file for one platform.
fn render_runtime_abi_bridge_file(platform: HostPlatform) -> String {
    let mut output = String::new();
    let platform_prefix = platform.prefix();
    let bindings_type = format!("{}RuntimeBridgeBindings", platform.rust_name());
    let runtime_segment = runtime_abi_runtime_segment(platform);

    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str(&format!(
        "use crate::host::{runtime_segment}::abi::bridge::{bindings_type};\n"
    ));
    output.push_str(&format!(
        "use crate::host::{runtime_segment}::abi::bridge::destack_host_{platform_prefix}_register_runtime_bridge_bindings as runtime_register_runtime_bridge_bindings;\n"
    ));
    output.push_str(&format!(
        "use crate::host::{runtime_segment}::abi::bridge::destack_host_{platform_prefix}_unregister_runtime_bridge_bindings as runtime_unregister_runtime_bridge_bindings;\n\n"
    ));

    output.push_str(&format!(
        "/// Register one {} runtime-bridge callback table through the ABI crate.\n",
        platform.label()
    ));
    output.push_str("#[unsafe(no_mangle)]\n");
    output.push_str(&format!(
        "pub unsafe extern \"C\" fn destack_host_{platform_prefix}_register_runtime_bridge_bindings(\n"
    ));
    output.push_str("    session_handle: u64,\n");
    output.push_str(&format!("    bindings: {bindings_type},\n"));
    output.push_str(") -> u32 {\n");
    output.push_str(
        "    unsafe { runtime_register_runtime_bridge_bindings(session_handle, bindings) }\n",
    );
    output.push_str("}\n\n");

    output.push_str(&format!(
        "/// Remove one {} runtime-bridge callback table through the ABI crate.\n",
        platform.label()
    ));
    output.push_str("#[unsafe(no_mangle)]\n");
    output.push_str(&format!(
        "pub unsafe extern \"C\" fn destack_host_{platform_prefix}_unregister_runtime_bridge_bindings(\n"
    ));
    output.push_str("    session_handle: u64,\n");
    output.push_str(") {\n");
    output.push_str("    unsafe { runtime_unregister_runtime_bridge_bindings(session_handle) }\n");
    output.push_str("}\n");

    output
}

/// Render the generated ABI crate module file for one platform module.
fn render_runtime_abi_module_file(
    _catalog: &HostCatalog,
    module: &HostModule,
    platform: HostPlatform,
) -> String {
    let mut output = String::new();
    let mut imports = BTreeSet::new();
    // type imports
    for request in module.requests() {
        collect_runtime_abi_function_imports(&mut imports, module, platform, request.abi());
    }

    if module.has_ingress() {
        let ingress = module
            .single_ingress()
            .expect("missing authored ingress for module runtime ingress");

        collect_runtime_abi_ingress_imports(&mut imports, module, platform, ingress.abi());
    }

    // runtime aliases
    for request in module.requests() {
        let export_name = runtime_abi_request_export_name(module, platform, request.abi());
        let alias_name = runtime_abi_request_alias(module, request.abi());
        let runtime_segment = runtime_abi_runtime_segment(platform);

        imports.insert(format!(
            "use crate::host::{runtime_segment}::abi::{}::{export_name} as {alias_name};",
            module.name()
        ));
    }

    if module.has_ingress() {
        let ingress = module
            .single_ingress()
            .expect("missing authored ingress for module runtime ingress");
        let export_name = runtime_abi_ingress_export_name(platform, ingress.abi());
        let alias_name = runtime_abi_ingress_alias(ingress.abi());
        let runtime_segment = runtime_abi_runtime_segment(platform);

        imports.insert(format!(
            "use crate::host::{runtime_segment}::abi::ingress::{export_name} as {alias_name};"
        ));
    }

    output.push_str("// generated by generate-bindings: do not edit\n\n");

    for import in imports {
        output.push_str(&import);
        output.push('\n');
    }

    if !module.requests().is_empty() || module.has_ingress() {
        output.push('\n');
    }

    // request wrappers
    for request in module.requests() {
        render_runtime_abi_forward_function(
            &mut output,
            module,
            request.abi(),
            platform,
            "request",
            runtime_abi_request_export_name(module, platform, request.abi()),
        );
        output.push('\n');
    }

    // ingress wrappers
    if module.has_ingress() {
        let ingress = module
            .single_ingress()
            .expect("missing authored ingress for module runtime ingress");

        render_runtime_abi_ingress_forward_function(
            &mut output,
            module,
            ingress.abi(),
            platform,
            runtime_abi_ingress_export_name(platform, ingress.abi()),
        );
    }

    output
}

/// Collect the import set for one ABI crate ingress function.
fn collect_runtime_abi_ingress_imports(
    imports: &mut BTreeSet<String>,
    module: &HostModule,
    platform: HostPlatform,
    ingress: &HostAbiFunction,
) {
    if module_uses_runtime_abi_simple_ingress(ingress) {
        collect_runtime_abi_simple_ingress_imports(imports, module, platform, ingress);
        return;
    }

    collect_runtime_abi_function_imports(imports, module, platform, ingress);
}

/// Collect the import set for one ABI crate function.
fn collect_runtime_abi_function_imports(
    imports: &mut BTreeSet<String>,
    module: &HostModule,
    platform: HostPlatform,
    function: &HostAbiFunction,
) {
    // parameter types
    for parameter in &function.parameters {
        collect_runtime_abi_type_imports(imports, module, platform, &parameter.ty);
    }

    // result type
    collect_runtime_abi_type_imports(imports, module, platform, &function.result);
}

/// Collect the import set for one straightforward ABI crate ingress.
fn collect_runtime_abi_simple_ingress_imports(
    imports: &mut BTreeSet<String>,
    module: &HostModule,
    platform: HostPlatform,
    ingress: &HostAbiFunction,
) {
    imports.insert("use crate::diagnostic::RuntimeStatus;".to_string());

    for parameter in ingress.parameters.iter().skip(1) {
        match &parameter.ty {
            HostAbiType::StringRef => {
                imports.insert("use crate::platform::abi::NativeStringRef;".to_string());
            }
            HostAbiType::StringSlice => {
                imports.insert("use crate::platform::abi::NativeStringSlice;".to_string());
            }
            HostAbiType::NativeSlice(inner) => {
                imports.insert("use crate::platform::abi::NativeSlice;".to_string());
                imports.insert(format!(
                    "use crate::platform::os::{};",
                    runtime_abi_simple_ingress_slice_element_type(inner.as_ref())
                ));
            }
            HostAbiType::Named(name) => {
                if let Some(host_type_name) =
                    runtime_abi_simple_ingress_host_type_name(platform, &HostAbiType::Named(name))
                {
                    imports.insert(runtime_abi_platform_header_import(
                        module,
                        platform,
                        &host_type_name,
                    ));
                } else if let Some(host_type_name) =
                    runtime_abi_simple_ingress_abi_host_type(&HostAbiType::Named(name))
                {
                    imports.insert(format!(
                        "use crate::host::abi::{}::{host_type_name};",
                        module.name()
                    ));
                } else {
                    imports.insert(format!(
                        "use crate::platform::os::{};",
                        runtime_abi_simple_ingress_value_type(&HostAbiType::Named(name))
                    ));
                }
            }
            _ => {}
        }
    }
}

/// Collect the import set for one ABI crate type.
fn collect_runtime_abi_type_imports(
    imports: &mut BTreeSet<String>,
    module: &HostModule,
    platform: HostPlatform,
    ty: &HostAbiType,
) {
    match ty {
        HostAbiType::StringRef => {
            imports.insert("use crate::platform::abi::NativeStringRef;".to_string());
        }
        HostAbiType::StringSlice => {
            imports.insert("use crate::platform::abi::NativeStringSlice;".to_string());
        }
        HostAbiType::RuntimeStatus => {
            imports.insert("use crate::diagnostic::RuntimeStatus;".to_string());
        }
        HostAbiType::Optional(inner) => {
            collect_runtime_abi_type_imports(imports, module, platform, inner);
        }
        HostAbiType::NativeArray(inner) => {
            imports.insert("use crate::platform::NativeArray;".to_string());
            collect_runtime_abi_type_imports(imports, module, platform, inner);
        }
        HostAbiType::NativeSlice(inner) => {
            imports.insert("use crate::platform::abi::NativeSlice;".to_string());
            collect_runtime_abi_type_imports(imports, module, platform, inner);
        }
        HostAbiType::OutputPointer(inner) => {
            collect_runtime_abi_type_imports(imports, module, platform, inner);
        }
        HostAbiType::Named(name) => {
            imports.insert(runtime_abi_named_type_import(module, platform, name));
        }
        HostAbiType::OsPath => {
            imports.insert("use crate::platform::fs::OsPath;".to_string());
        }
        HostAbiType::U8
        | HostAbiType::U16
        | HostAbiType::I8
        | HostAbiType::I16
        | HostAbiType::U32
        | HostAbiType::I32
        | HostAbiType::U64
        | HostAbiType::HostRequestId
        | HostAbiType::Bool
        | HostAbiType::F64
        | HostAbiType::HostSessionHandle
        | HostAbiType::HostStatus => {}
    }
}

/// Return whether one ingress uses the straightforward lowered ABI path.
fn module_uses_runtime_abi_simple_ingress(ingress: &HostAbiFunction) -> bool {
    if !matches!(ingress.result, HostAbiType::RuntimeStatus) {
        return false;
    }

    ingress
        .parameters
        .iter()
        .all(|parameter| runtime_abi_simple_ingress_parameter_supported(&parameter.ty))
}

/// Return whether one ingress parameter uses the straightforward lowered ABI path.
fn runtime_abi_simple_ingress_parameter_supported(ty: &HostAbiType) -> bool {
    match ty {
        HostAbiType::U8
        | HostAbiType::U16
        | HostAbiType::I8
        | HostAbiType::I16
        | HostAbiType::U32
        | HostAbiType::I32
        | HostAbiType::U64
        | HostAbiType::HostRequestId
        | HostAbiType::Bool
        | HostAbiType::F64
        | HostAbiType::StringRef
        | HostAbiType::StringSlice
        | HostAbiType::OsPath
        | HostAbiType::HostSessionHandle => true,
        HostAbiType::NativeSlice(inner) => matches!(inner.as_ref(), HostAbiType::Named(_)),
        HostAbiType::Named(_) => true,
        HostAbiType::Optional(_) => false,
        HostAbiType::HostStatus
        | HostAbiType::RuntimeStatus
        | HostAbiType::NativeArray(_)
        | HostAbiType::OutputPointer(_) => false,
    }
}

/// Return the Rust parameter type for one straightforward ingress wrapper.
fn runtime_abi_simple_ingress_parameter_type(ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::U8 => "u8".to_string(),
        HostAbiType::U16 => "u16".to_string(),
        HostAbiType::I8 => "i8".to_string(),
        HostAbiType::I16 => "i16".to_string(),
        HostAbiType::U32 => "u32".to_string(),
        HostAbiType::I32 => "i32".to_string(),
        HostAbiType::U64 | HostAbiType::HostRequestId | HostAbiType::HostSessionHandle => {
            "u64".to_string()
        }
        HostAbiType::Bool => "bool".to_string(),
        HostAbiType::F64 => "f64".to_string(),
        HostAbiType::StringRef => "NativeStringRef".to_string(),
        HostAbiType::OsPath => "OsPath".to_string(),
        HostAbiType::StringSlice => "NativeStringSlice".to_string(),
        HostAbiType::NativeSlice(inner) => {
            format!(
                "NativeSlice<{}>",
                runtime_abi_simple_ingress_slice_element_type(inner.as_ref())
            )
        }
        HostAbiType::Named(name) => {
            runtime_abi_simple_ingress_abi_host_type(&HostAbiType::Named(name))
                .unwrap_or_else(|| runtime_abi_simple_ingress_value_type(&HostAbiType::Named(name)))
        }
        other => panic!("unsupported straightforward ingress parameter type: {other:?}"),
    }
}

/// Return the slice element type for one straightforward ingress wrapper.
fn runtime_abi_simple_ingress_slice_element_type(ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::Named(_) => runtime_abi_simple_ingress_value_type(ty),
        other => panic!("unsupported straightforward ingress slice element type: {other:?}"),
    }
}

/// Return the platform-header host type name for one straightforward ingress type.
fn runtime_abi_simple_ingress_host_type_name(
    platform: HostPlatform,
    ty: &HostAbiType,
) -> Option<String> {
    match (platform, ty) {
        (HostPlatform::Android, HostAbiType::Named(name)) if name.starts_with("AndroidHost") => {
            Some((*name).to_string())
        }
        (HostPlatform::Ios, HostAbiType::Named(name)) if name.starts_with("IosHost") => {
            Some((*name).to_string())
        }
        _ => None,
    }
}

/// Return the authored host ABI type name for one straightforward ingress type.
fn runtime_abi_simple_ingress_abi_host_type(ty: &HostAbiType) -> Option<String> {
    match ty {
        HostAbiType::Named(name) => Some((*name).to_string()),
        _ => None,
    }
}

/// Return the runtime value type for one straightforward ingress ABI type.
fn runtime_abi_simple_ingress_value_type(ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::Named(name) => format!("{name}Value"),
        other => panic!("unsupported straightforward ingress value type: {other:?}"),
    }
}

/// Return the import line for one ABI crate named type.
fn runtime_abi_named_type_import(
    module: &HostModule,
    _platform: HostPlatform,
    type_name: &str,
) -> String {
    format!("use crate::host::abi::{}::{type_name};", module.name())
}

/// Return the import line for one platform header type.
fn runtime_abi_platform_header_import(
    module: &HostModule,
    platform: HostPlatform,
    type_name: &str,
) -> String {
    let runtime_segment = runtime_abi_runtime_segment(platform);

    format!(
        "use crate::host::{runtime_segment}::abi::{}::{type_name};",
        module.name()
    )
}

/// Render one ABI crate forwarder function.
fn render_runtime_abi_forward_function(
    output: &mut String,
    module: &HostModule,
    function: &HostAbiFunction,
    _platform: HostPlatform,
    kind: &str,
    export_name: String,
) {
    let alias_name = if kind == "request" {
        runtime_abi_request_alias(module, function)
    } else {
        runtime_abi_ingress_alias(function)
    };

    output.push_str(&format!(
        "/// Forward the `{}` {} {} through the ABI crate.\n",
        function.name,
        module.name(),
        kind
    ));
    output.push_str("#[unsafe(no_mangle)]\n");
    output.push_str(&format!("pub unsafe extern \"C\" fn {export_name}(\n"));

    for parameter in &function.parameters {
        output.push_str(&format!(
            "    {}: {},\n",
            parameter.name,
            runtime_abi_rust_type(&parameter.ty)
        ));
    }

    output.push_str(&format!(
        ") -> {} {{\n",
        runtime_abi_rust_type(&function.result)
    ));
    output.push_str("    unsafe {\n");
    output.push_str(&format!("        {alias_name}(\n"));

    for parameter in &function.parameters {
        output.push_str(&format!("            {},\n", parameter.name));
    }

    output.push_str("        )\n");
    output.push_str("    }\n");
    output.push_str("}\n");
}

/// Render one ABI crate ingress forwarder function.
fn render_runtime_abi_ingress_forward_function(
    output: &mut String,
    module: &HostModule,
    ingress: &HostAbiFunction,
    platform: HostPlatform,
    export_name: String,
) {
    if module_uses_runtime_abi_simple_ingress(ingress) {
        render_runtime_abi_simple_ingress_forward_function(output, ingress, export_name);
        return;
    }

    render_runtime_abi_forward_function(output, module, ingress, platform, "ingress", export_name);
}

/// Render one straightforward ABI crate ingress forwarder function.
fn render_runtime_abi_simple_ingress_forward_function(
    output: &mut String,
    ingress: &HostAbiFunction,
    export_name: String,
) {
    let alias_name = runtime_abi_ingress_alias(ingress);

    output.push_str(&format!(
        "/// Forward the `{}` ingress through the ABI crate.\n",
        ingress.name
    ));
    output.push_str("#[unsafe(no_mangle)]\n");
    output.push_str(&format!("pub unsafe extern \"C\" fn {export_name}(\n"));
    output.push_str("    runtime_id: u64,\n");

    for parameter in ingress.parameters.iter().skip(1) {
        output.push_str(&format!(
            "    {}: {},\n",
            parameter.name,
            runtime_abi_simple_ingress_parameter_type(&parameter.ty)
        ));
    }

    output.push_str(") -> RuntimeStatus {\n");
    output.push_str(&format!("    unsafe {{ {alias_name}(\n"));
    output.push_str("        runtime_id,\n");

    for parameter in ingress.parameters.iter().skip(1) {
        output.push_str(&format!("        {},\n", parameter.name));
    }

    output.push_str("    ) }\n");
    output.push_str("}\n");
}

/// Return the exported ABI crate request name.
fn runtime_abi_request_export_name(
    module: &HostModule,
    platform: HostPlatform,
    function: &HostAbiFunction,
) -> String {
    format!(
        "destack_host_{}_{}_{}",
        platform.prefix(),
        module.name(),
        function.name
    )
}

/// Return the exported ABI crate ingress name.
fn runtime_abi_ingress_export_name(platform: HostPlatform, function: &HostAbiFunction) -> String {
    format!("destack_host_{}_{}", platform.prefix(), function.name)
}

/// Return the local alias for one imported runtime ABI request.
fn runtime_abi_request_alias(module: &HostModule, function: &HostAbiFunction) -> String {
    format!("runtime_{}_{}", module.name(), function.name)
}

/// Return the local alias for one imported runtime ABI ingress.
fn runtime_abi_ingress_alias(function: &HostAbiFunction) -> String {
    format!("runtime_{}", function.name)
}

/// Return the runtime crate platform module segment for one ABI crate platform.
fn runtime_abi_runtime_segment(platform: HostPlatform) -> &'static str {
    match platform {
        HostPlatform::Android => "android",
        HostPlatform::Ios => "apple",
    }
}

/// Render one Rust type for the ABI crate wrapper.
fn runtime_abi_rust_type(ty: &HostAbiType) -> String {
    match ty {
        HostAbiType::U8 => "u8".to_string(),
        HostAbiType::U16 => "u16".to_string(),
        HostAbiType::I8 => "i8".to_string(),
        HostAbiType::I16 => "i16".to_string(),
        HostAbiType::U32 => "u32".to_string(),
        HostAbiType::I32 => "i32".to_string(),
        HostAbiType::U64 => "u64".to_string(),
        HostAbiType::HostRequestId => "u64".to_string(),
        HostAbiType::Bool => "bool".to_string(),
        HostAbiType::F64 => "f64".to_string(),
        HostAbiType::StringRef => "NativeStringRef".to_string(),
        HostAbiType::OsPath => "OsPath".to_string(),
        HostAbiType::StringSlice => "NativeStringSlice".to_string(),
        HostAbiType::HostSessionHandle => "u64".to_string(),
        HostAbiType::HostStatus => "u32".to_string(),
        HostAbiType::RuntimeStatus => "RuntimeStatus".to_string(),
        HostAbiType::Optional(inner) => format!(
            "crate::host::abi::core::HostAbiOptional<{}>",
            runtime_abi_rust_type(inner)
        ),
        HostAbiType::NativeArray(inner) => {
            format!("NativeArray<{}>", runtime_abi_rust_type(inner))
        }
        HostAbiType::NativeSlice(inner) => {
            format!("NativeSlice<{}>", runtime_abi_rust_type(inner))
        }
        HostAbiType::OutputPointer(inner) => {
            format!("*mut {}", runtime_abi_rust_type(inner))
        }
        HostAbiType::Named(name) => (*name).to_string(),
    }
}
