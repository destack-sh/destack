use std::collections::BTreeSet;

use super::codegen::ModuleCodegen;

/// Render the generated platform binding lists.
pub(crate) fn render_platform_bindings_index(domains: &BTreeSet<String>) -> String {
    let mut output = String::new();
    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("use crate::runtime::binding::{NativeBindingSet, VmBindingSet};\n");

    if !domains.is_empty() {
        let imports = domains
            .iter()
            .map(|domain| ModuleCodegen::sanitize_module_name(domain))
            .collect::<Vec<_>>()
            .join(", ");
        output.push_str(&format!("use crate::platform::{{{imports}}};\n\n"));
    } else {
        output.push_str("\n");
    }

    output.push_str("/// Native binding sets for all platform domains.\n");
    output.push_str("pub const PLATFORM_NATIVE_BINDINGS: &[NativeBindingSet] = &[\n");
    for domain in domains {
        let codegen = ModuleCodegen::new(domain);
        let module = ModuleCodegen::sanitize_module_name(domain);
        let set_name = codegen.native_set_name();
        output.push_str(&format!("    {module}::{set_name},\n"));
    }
    output.push_str("];\n\n");

    output.push_str("/// VM binding sets for all platform domains.\n");
    output.push_str("pub const PLATFORM_VM_BINDINGS: &[VmBindingSet] = &[\n");
    for domain in domains {
        let codegen = ModuleCodegen::new(domain);
        let module = ModuleCodegen::sanitize_module_name(domain);
        let set_name = codegen.vm_set_name();
        output.push_str(&format!("    {module}::{set_name},\n"));
    }
    output.push_str("];\n");

    output
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::render_platform_bindings_index;

    /// Emit platform index rows in deterministic sorted domain order.
    #[test]
    fn test_render_platform_bindings_index_is_sorted() {
        let domains =
            BTreeSet::from(["tty".to_string(), "audio".to_string(), "crypto".to_string()]);

        let output = render_platform_bindings_index(&domains);
        let audio_index = output
            .find("audio::AUDIO_NATIVE_BINDINGS")
            .expect("audio row");
        let crypto_index = output
            .find("crypto::CRYPTO_NATIVE_BINDINGS")
            .expect("crypto row");
        let tty_index = output.find("tty::TTY_NATIVE_BINDINGS").expect("tty row");

        assert!(audio_index < crypto_index);
        assert!(crypto_index < tty_index);
    }
}
