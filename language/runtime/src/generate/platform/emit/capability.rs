use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

/// Prefix used by the intrinsic platform-capability declaration.
const PLATFORM_CAPABILITY_TYPE_PREFIX: &str = "export type PlatformCapability =";

/// Generate runtime capability kinds from the primitive binding union.
pub(crate) fn generate_platform_capability_kind() {
    let intrinsic_binding_path = intrinsic_binding_path();
    let source = fs::read_to_string(&intrinsic_binding_path).unwrap_or_else(|error| {
        panic!("failed to read intrinsic binding source {intrinsic_binding_path:?}: {error}")
    });
    let capability_names = parse_platform_capability_names(&source);
    let generated = render_platform_capability_source(&capability_names);
    let output_path = runtime_capability_generated_path();

    write_generated_file(&output_path, &generated);
}

/// Resolve the language workspace root for generator inputs.
fn language_root() -> PathBuf {
    let runtime_root = Path::new(env!("CARGO_MANIFEST_DIR"));
    runtime_root
        .parent()
        .unwrap_or_else(|| panic!("missing language root for {runtime_root:?}"))
        .to_path_buf()
}

/// Resolve the primitive binding declaration path.
fn intrinsic_binding_path() -> PathBuf {
    language_root().join("library/core/primitive/binding.ds")
}

/// Resolve the generated runtime capability kind output path.
fn runtime_capability_generated_path() -> PathBuf {
    language_root().join("runtime/src/runtime/capability/capability.generated.rs")
}

/// Write one generated file to disk.
fn write_generated_file(path: &Path, contents: &str) {
    // parent directory
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).expect("failed to create output directory");
    }

    fs::write(path, contents).expect("failed to write generated file");
}

/// Parse canonical capability names from the intrinsic type union.
fn parse_platform_capability_names(source: &str) -> Vec<String> {
    let mut in_union = false;
    let mut capabilities = Vec::new();

    for line in source.lines() {
        let trimmed = line.trim();

        // locate the platform capability union declaration
        if !in_union {
            if !trimmed.starts_with(PLATFORM_CAPABILITY_TYPE_PREFIX) {
                continue;
            }

            in_union = true;
        }

        // collect capability literals from this line
        capabilities.extend(string_literals_from_line(trimmed));

        // stop once the type declaration terminator is reached
        if trimmed.contains(';') {
            break;
        }
    }

    if !in_union {
        panic!("missing intrinsic PlatformCapability union declaration");
    }

    if capabilities.is_empty() {
        panic!("intrinsic PlatformCapability union is empty");
    }

    let mut seen_capabilities = BTreeSet::new();
    for capability in &capabilities {
        if !seen_capabilities.insert(capability.clone()) {
            panic!("duplicate intrinsic capability literal: {capability}");
        }
    }

    capabilities
}

/// Extract all string literal payloads from one source line.
fn string_literals_from_line(line: &str) -> Vec<String> {
    let mut values = Vec::new();
    let mut current = String::new();
    let mut is_in_string = false;

    for character in line.chars() {
        if character == '"' {
            if is_in_string {
                values.push(current.clone());
                current.clear();
            }
            is_in_string = !is_in_string;
            continue;
        }

        if is_in_string {
            current.push(character);
        }
    }

    values
}

/// Render generated runtime capability kind source.
fn render_platform_capability_source(capability_names: &[String]) -> String {
    let mut variant_to_name = BTreeMap::new();
    let mut capability_variants = Vec::with_capacity(capability_names.len());

    // build deterministic variant names and reject collisions
    for capability_name in capability_names {
        let variant_name = variant_name_for_capability(capability_name);
        if let Some(existing_name) = variant_to_name.insert(variant_name.clone(), capability_name) {
            panic!(
                "capability variant collision for {variant_name}: {existing_name} vs {capability_name}"
            );
        }

        capability_variants.push((capability_name.clone(), variant_name));
    }

    let mut output = String::new();
    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("use super::PlatformCapabilityId;\n\n");
    output.push_str("/// Canonical runtime platform capability kind.\n");
    output.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n");
    output.push_str("pub enum PlatformCapability {\n");
    for (capability_name, variant_name) in &capability_variants {
        output.push_str(&format!("    /// `{capability_name}`.\n"));
        output.push_str(&format!("    {variant_name},\n"));
    }
    output.push_str("}\n\n");
    output.push_str("impl PlatformCapability {\n");
    output.push_str("    /// All canonical platform capability kinds.\n");
    output.push_str("    pub const ALL: &'static [Self] = &[\n");
    for (_capability_name, variant_name) in &capability_variants {
        output.push_str(&format!("        Self::{variant_name},\n"));
    }
    output.push_str("    ];\n\n");
    output.push_str("    /// Return the canonical capability name.\n");
    output.push_str("    pub const fn name(self) -> &'static str {\n");
    output.push_str("        match self {\n");
    for (capability_name, variant_name) in &capability_variants {
        output.push_str(&format!(
            "            Self::{variant_name} => \"{capability_name}\",\n"
        ));
    }
    output.push_str("        }\n");
    output.push_str("    }\n\n");
    output.push_str("    /// Return the stable capability identifier.\n");
    output.push_str("    pub const fn id(self) -> PlatformCapabilityId {\n");
    output.push_str("        PlatformCapabilityId::from_name(self.name())\n");
    output.push_str("    }\n\n");
    output.push_str("    /// Resolve one capability kind from one canonical capability name.\n");
    output.push_str("    pub fn from_name(name: &str) -> Option<Self> {\n");
    output.push_str("        match name {\n");
    for (capability_name, variant_name) in &capability_variants {
        output.push_str(&format!(
            "            \"{capability_name}\" => Some(Self::{variant_name}),\n"
        ));
    }
    output.push_str("            _ => None,\n");
    output.push_str("        }\n");
    output.push_str("    }\n");
    output.push_str("}\n");

    output
}

/// Build one enum variant name from one capability string.
fn variant_name_for_capability(capability_name: &str) -> String {
    let mut variant_name = String::new();

    for segment in capability_name.split('.') {
        let segment_name = pascal_case_segment(segment);
        variant_name.push_str(&segment_name);
    }

    if variant_name.is_empty() {
        panic!("invalid empty capability name");
    }

    if variant_name
        .chars()
        .next()
        .is_some_and(|character| character.is_ascii_digit())
    {
        variant_name.insert(0, 'N');
    }

    variant_name
}

/// Convert one capability segment to one pascal-case fragment.
fn pascal_case_segment(segment: &str) -> String {
    let mut output = String::new();
    let mut uppercase_next = true;

    for character in segment.chars() {
        // reset casing across delimiters
        if !character.is_ascii_alphanumeric() {
            uppercase_next = true;
            continue;
        }

        // uppercase only the next segment boundary character
        if uppercase_next {
            output.push(character.to_ascii_uppercase());
            uppercase_next = false;
            continue;
        }

        output.push(character);
    }

    output
}

#[cfg(test)]
mod tests {
    use super::{
        parse_platform_capability_names, render_platform_capability_source,
        variant_name_for_capability,
    };

    /// Parse all capability literals from the intrinsic union.
    #[test]
    fn test_parse_platform_capability_names_collects_union_literals() {
        let source = r#"
            export type PlatformCapability =
              | "fs.read"
              | "net.connect"
              | "gpu.render.multiDraw"
            ;
        "#;

        let names = parse_platform_capability_names(source);

        assert_eq!(
            names,
            vec![
                "fs.read".to_string(),
                "net.connect".to_string(),
                "gpu.render.multiDraw".to_string()
            ]
        );
    }

    /// Reject duplicate capability literals in the intrinsic union.
    #[test]
    #[should_panic(expected = "duplicate intrinsic capability literal: fs.read")]
    fn test_parse_platform_capability_names_rejects_duplicates() {
        let source = r#"
            export type PlatformCapability =
              | "fs.read"
              | "fs.read"
            ;
        "#;

        let _ = parse_platform_capability_names(source);
    }

    /// Convert capability names to stable enum variant names.
    #[test]
    fn test_variant_name_for_capability() {
        assert_eq!(variant_name_for_capability("fs.read"), "FsRead");
        assert_eq!(
            variant_name_for_capability("gpu.render.multiDraw"),
            "GpuRenderMultiDraw"
        );
        assert_eq!(variant_name_for_capability("3d.render"), "N3dRender");
    }

    /// Render one stable capability enum source file.
    #[test]
    fn test_render_platform_capability_source() {
        let source =
            render_platform_capability_source(&["fs.read".to_string(), "net.connect".to_string()]);

        assert!(source.contains("pub enum PlatformCapability"));
        assert!(source.contains("FsRead"));
        assert!(source.contains("NetConnect"));
    }
}
