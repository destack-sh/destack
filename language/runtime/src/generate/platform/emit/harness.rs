use std::collections::BTreeSet;

use super::docs::GeneratedDocumentation;
use super::{BindingSymbol, RenderSpec};
use crate::platform::model::{BindingEntry, BindingType};

/// Render one generated test harness for a platform module.
pub(crate) fn render_test_harness(spec: &RenderSpec<'_>) -> String {
    let mut output = String::new();
    let mut writer = HarnessWriter::new(spec, &mut output);

    writer.write_header();
    writer.write_impl();
    writer.write_harness_value();

    output
}

/// Stateful writer for one generated test harness module.
struct HarnessWriter<'spec, 'output> {
    /// Render specification derived from bindings.
    spec: &'spec RenderSpec<'spec>,
    /// Output buffer for generated content.
    output: &'output mut String,
}

impl<'spec, 'output> HarnessWriter<'spec, 'output> {
    /// Create one writer for a generated test harness.
    fn new(spec: &'spec RenderSpec<'spec>, output: &'output mut String) -> Self {
        Self { spec, output }
    }

    /// Return the Rust code generator for this module.
    fn codegen(&self) -> super::codegen::ModuleCodegen<'spec> {
        self.spec.codegen()
    }

    /// Return the generated harness context type name.
    fn context_name(&self) -> String {
        let module = self.codegen().to_pascal_case(self.spec.module);
        format!("{module}HarnessContext")
    }

    /// Return true when one binding type needs one harness wrapper.
    fn binding_type_needs_harness_value(&self, binding_type: &BindingType) -> bool {
        let codegen = self.codegen();
        let native_type = codegen.native_type_for_binding(binding_type);
        let vm_type = codegen.vm_type_for_binding(binding_type);

        native_type != vm_type
    }

    /// Render one harness parameter type.
    fn render_harness_parameter_type(&self, binding_type: &BindingType) -> String {
        let codegen = self.codegen();
        let native_type = codegen.native_type_for_binding(binding_type);
        let vm_type = codegen.vm_type_for_binding(binding_type);

        if native_type == vm_type {
            return native_type;
        }

        format!("HarnessValue<{native_type}, {vm_type}>")
    }

    /// Render one harness return type.
    fn render_harness_return_type(&self, binding_type: &BindingType) -> String {
        if matches!(binding_type, BindingType::Void) {
            return "()".to_string();
        }

        self.render_harness_parameter_type(binding_type)
    }

    /// Indent one generated documentation block for an impl item.
    fn write_indented_docs(&mut self, docs: &str) {
        for line in docs.lines() {
            self.output.push_str("    ");
            self.output.push_str(line);
            self.output.push('\n');
        }
    }

    /// Write the shared header for one generated harness file.
    fn write_header(&mut self) {
        let context_name = self.context_name();

        self.output
            .push_str("// generated by generate-bindings: test harness, do not edit\n\n");
        self.output.push_str("#![allow(dead_code)]\n");
        self.output.push_str("#![allow(unused_imports)]\n");
        self.output
            .push_str("#![allow(clippy::type_complexity)]\n\n");

        self.output
            .push_str("use crate::diagnostic::{RuntimeError, RuntimeResult};\n");
        self.output.push_str(&format!(
            "use crate::platform::{}::tests::{context_name};\n",
            self.spec.module
        ));
        self.output
            .push_str("use crate::platform::{{NativeAbiCodec, VmAbiCodec}};\n");

        let mut local_types = self.spec.types.named_types.clone();
        local_types.extend(self.spec.types.native_named_types.iter().cloned());
        if self.spec.module == "error" {
            local_types.remove("PlatformError");
        }

        if !local_types.is_empty() {
            let imports = local_types.iter().cloned().collect::<Vec<_>>().join(", ");
            self.output.push_str(&format!(
                "use crate::platform::{}::{{{imports}, native as {}_native, vm as {}_vm}};\n",
                self.spec.module, self.spec.module, self.spec.module
            ));
        } else {
            self.output.push_str(&format!(
                "use crate::platform::{}::{{native as {}_native, vm as {}_vm}};\n",
                self.spec.module, self.spec.module, self.spec.module
            ));
        }

        let native_abi_imports = ["NativeSlice", "NativeStringRef", "NativeStringSlice"].join(", ");
        self.output.push_str(&format!(
            "use crate::platform::abi::{{{native_abi_imports}}};\n"
        ));

        let mut platform_imports = BTreeSet::from([
            "NativeArray".to_string(),
            "PlatformError as HarnessPlatformError".to_string(),
            "VmArray".to_string(),
            "VmSlice".to_string(),
            "fs".to_string(),
            "resource".to_string(),
        ]);
        platform_imports.extend(self.spec.types.type_domains.iter().cloned());

        let platform_imports = platform_imports.into_iter().collect::<Vec<_>>().join(", ");
        self.output
            .push_str(&format!("use crate::platform::{{{platform_imports}}};\n"));
        self.output.push_str("use destack_vm as vm;\n\n");
    }

    /// Write the generated impl block and binding wrappers.
    fn write_impl(&mut self) {
        let context_name = self.context_name();

        self.output
            .push_str(&format!("impl<'call> {context_name}<'call> {{\n"));

        // generated vm context
        self.output
            .push_str("    /// Return the generated VM context if available.\n");
        self.output.push_str("    #[allow(clippy::mut_from_ref)]\n");
        self.output.push_str(
            "    fn generated_vm_context_mut(&self) -> Option<&mut vm::BindingContext<'_>> {\n",
        );
        self.output.push_str("        self.vm_context\n");
        self.output
            .push_str("            .map(|context| unsafe { &mut *(context as *mut vm::BindingContext<'_>) })\n");
        self.output.push_str("    }\n\n");

        // native wrapper
        self.output.push_str(
            "    /// Return one standardized value payload for native and VM variants.\n",
        );
        self.output
            .push_str("    pub(crate) fn harness_value<Native, Vm>(&self, native: Native) -> HarnessValue<Native, Vm> {\n");
        self.output
            .push_str("        HarnessValue::Native(native)\n");
        self.output.push_str("    }\n\n");

        // vm wrapper
        self.output.push_str(
            "    /// Return one standardized value payload for VM and native variants.\n",
        );
        self.output
            .push_str("    pub(crate) fn harness_value_vm<Native, Vm>(&self, vm: Vm) -> HarnessValue<Native, Vm> {\n");
        self.output.push_str("        HarnessValue::Vm(vm)\n");
        self.output.push_str("    }\n");
        self.output.push('\n');

        // value encoder
        self.output
            .push_str("    /// Encode one value into one native or VM harness payload.\n");
        self.output
            .push_str("    pub(crate) fn harness_value_from<Native, Vm>(\n");
        self.output.push_str("        &mut self,\n");
        self.output.push_str("        value: Native::Value,\n");
        self.output
            .push_str("    ) -> RuntimeResult<HarnessValue<Native, Vm>>\n");
        self.output.push_str("    where\n");
        self.output.push_str("        Native: NativeAbiCodec,\n");
        self.output
            .push_str("        Vm: VmAbiCodec<Value = Native::Value>,\n");
        self.output.push_str("    {\n");
        self.output
            .push_str("        match self.generated_vm_context_mut() {\n");
        self.output.push_str("            Some(context) => {\n");
        self.output
            .push_str("                let context = &mut context.write();\n");
        self.output
            .push_str("                let value = Vm::from_value(context, value)?;\n");
        self.output
            .push_str("                Ok(HarnessValue::Vm(value))\n");
        self.output.push_str("            }\n");
        self.output.push_str("            None => {\n");
        self.output.push_str(
            "                let value = Native::from_value(self.call_context, value);\n",
        );
        self.output
            .push_str("                Ok(HarnessValue::Native(value))\n");
        self.output.push_str("            }\n");
        self.output.push_str("        }\n");
        self.output.push_str("    }\n");
        self.output.push('\n');

        // value decoder
        self.output
            .push_str("    /// Decode one native or VM harness payload into one value.\n");
        self.output
            .push_str("    pub(crate) fn harness_value_into<Native, Vm>(\n");
        self.output.push_str("        &mut self,\n");
        self.output
            .push_str("        value: HarnessValue<Native, Vm>,\n");
        self.output
            .push_str("    ) -> RuntimeResult<Native::Value>\n");
        self.output.push_str("    where\n");
        self.output.push_str("        Native: NativeAbiCodec,\n");
        self.output
            .push_str("        Vm: VmAbiCodec<Value = Native::Value>,\n");
        self.output.push_str("    {\n");
        self.output.push_str("        match value {\n");
        self.output.push_str(
            "            HarnessValue::Native(value) => unsafe { Native::into_value(value) },\n",
        );
        self.output
            .push_str("            HarnessValue::Vm(value) => {\n");
        self.output.push_str(
            "                let context = self.generated_vm_context_mut().ok_or_else(|| {\n",
        );
        self.output.push_str("                    RuntimeError::from(HarnessPlatformError::invalid_argument_value(\n");
        self.output
            .push_str("                        \"context\",\n");
        self.output
            .push_str("                        \"expected vm context\",\n");
        self.output.push_str("                    ))\n");
        self.output.push_str("                    .boxed()\n");
        self.output.push_str("                })?;\n");
        self.output
            .push_str("                let context = &context.read();\n");
        self.output
            .push_str("                value.into_value(context)\n");
        self.output.push_str("            }\n");
        self.output.push_str("        }\n");
        self.output.push_str("    }\n");

        for binding in &self.spec.consts {
            self.output.push('\n');
            self.write_binding_function(binding);
        }

        self.output.push_str("}\n");
    }

    /// Write one generated harness binding wrapper.
    fn write_binding_function(&mut self, binding: &BindingSymbol<'_>) {
        let docs = GeneratedDocumentation::render(
            binding.entry.documentation.as_deref(),
            "Call one generated platform test harness binding.",
        );
        self.write_indented_docs(&docs);

        let function_name = &binding.implementation_fn_name;
        let return_type = self.render_harness_return_type(&binding.entry.return_binding);
        let parameters = self.render_harness_parameters(binding.entry);

        self.output
            .push_str(&format!("    pub(crate) fn {function_name}(\n"));
        self.output.push_str("        &mut self");

        for parameter in parameters {
            self.output.push_str(",\n        ");
            self.output.push_str(&parameter);
        }

        self.output
            .push_str(&format!(",\n    ) -> RuntimeResult<{return_type}> {{\n"));
        self.output
            .push_str("        match self.generated_vm_context_mut() {\n");
        self.write_vm_branch(binding);
        self.write_native_branch(binding);
        self.output.push_str("        }\n");
        self.output.push_str("    }\n");
    }

    /// Render the parameter list for one harness binding wrapper.
    fn render_harness_parameters(&self, entry: &BindingEntry) -> Vec<String> {
        let codegen = self.codegen();
        let mut parameters = Vec::new();

        for (index, parameter) in entry.parameters.iter().enumerate() {
            let name = codegen.sanitize_param_name(&parameter.name, index);
            let parameter_type = self.render_harness_parameter_type(&parameter.binding_type);
            parameters.push(format!("{name}: {parameter_type}"));
        }

        parameters
    }

    /// Write the VM branch for one harness binding wrapper.
    fn write_vm_branch(&mut self, binding: &BindingSymbol<'_>) {
        let codegen = self.codegen();
        let function_name = &binding.implementation_fn_name;
        let argument_names = binding
            .entry
            .parameters
            .iter()
            .enumerate()
            .map(|(index, parameter)| codegen.sanitize_param_name(&parameter.name, index))
            .collect::<Vec<_>>();

        self.output.push_str("            Some(context) => {\n");

        // parameter conversions
        for (parameter, argument_name) in binding.entry.parameters.iter().zip(argument_names.iter())
        {
            if !self.binding_type_needs_harness_value(&parameter.binding_type) {
                continue;
            }

            self.output.push_str(&format!(
                "                let {argument_name} = {argument_name}.into_vm(\"{argument_name}\")?;\n"
            ));
        }

        let call_arguments = if argument_names.is_empty() {
            "self.call_context, context".to_string()
        } else {
            format!("self.call_context, context, {}", argument_names.join(", "))
        };

        // return handling
        if matches!(binding.entry.return_binding, BindingType::Void) {
            self.output.push_str(&format!(
                "                {}_vm::{function_name}({call_arguments})\n",
                self.spec.module
            ));
        } else {
            self.output.push_str(&format!(
                "                let out = {}_vm::{function_name}({call_arguments})?;\n",
                self.spec.module
            ));

            if self.binding_type_needs_harness_value(&binding.entry.return_binding) {
                self.output
                    .push_str("                Ok(HarnessValue::Vm(out))\n");
            } else {
                self.output.push_str("                Ok(out)\n");
            }
        }

        self.output.push_str("            }\n");
    }

    /// Write the native branch for one harness binding wrapper.
    fn write_native_branch(&mut self, binding: &BindingSymbol<'_>) {
        let codegen = self.codegen();
        let function_name = &binding.implementation_fn_name;
        let argument_names = binding
            .entry
            .parameters
            .iter()
            .enumerate()
            .map(|(index, parameter)| codegen.sanitize_param_name(&parameter.name, index))
            .collect::<Vec<_>>();

        self.output.push_str("            None => ");

        if matches!(binding.entry.return_binding, BindingType::Void) {
            self.output.push_str("unsafe {\n");

            // parameter conversions
            for (parameter, argument_name) in
                binding.entry.parameters.iter().zip(argument_names.iter())
            {
                if !self.binding_type_needs_harness_value(&parameter.binding_type) {
                    continue;
                }

                self.output.push_str(&format!(
                    "                let {argument_name} = {argument_name}.into_native(\"{argument_name}\")?;\n"
                ));
            }

            let call_arguments = if argument_names.is_empty() {
                "self.call_context".to_string()
            } else {
                format!("self.call_context, {}", argument_names.join(", "))
            };

            self.output.push_str(&format!(
                "                {}_native::{function_name}({call_arguments})\n",
                self.spec.module
            ));
            self.output.push_str("            },\n");
            return;
        }

        self.output.push_str("{\n");

        // parameter conversions
        for (parameter, argument_name) in binding.entry.parameters.iter().zip(argument_names.iter())
        {
            if !self.binding_type_needs_harness_value(&parameter.binding_type) {
                continue;
            }

            self.output.push_str(&format!(
                "                let {argument_name} = {argument_name}.into_native(\"{argument_name}\")?;\n"
            ));
        }

        let native_return_type = codegen.native_type_for_binding(&binding.entry.return_binding);
        self.output.push_str(&format!(
            "                let mut out = std::mem::MaybeUninit::<{native_return_type}>::uninit();\n"
        ));

        let call_arguments = if argument_names.is_empty() {
            "self.call_context, out.as_mut_ptr()".to_string()
        } else {
            format!(
                "self.call_context, out.as_mut_ptr(), {}",
                argument_names.join(", ")
            )
        };

        self.output.push_str("                unsafe {\n");
        self.output.push_str(&format!(
            "                    {}_native::{function_name}({call_arguments})?;\n",
            self.spec.module
        ));
        self.output.push_str("                }\n");
        self.output
            .push_str("                let out = unsafe { out.assume_init() };\n");

        if self.binding_type_needs_harness_value(&binding.entry.return_binding) {
            self.output
                .push_str("                Ok(HarnessValue::Native(out))\n");
        } else {
            self.output.push_str("                Ok(out)\n");
        }

        self.output.push_str("            },\n");
    }

    /// Write the shared harness value wrapper.
    fn write_harness_value(&mut self) {
        self.output.push('\n');
        self.output.push_str(
            "/// Wrapper that carries one native or VM value for generated harness bindings.\n",
        );
        self.output
            .push_str("pub(crate) enum HarnessValue<Native, Vm> {\n");
        self.output.push_str("    /// Native value variant.\n");
        self.output.push_str("    Native(Native),\n");
        self.output.push_str("    /// VM value variant.\n");
        self.output.push_str("    Vm(Vm),\n");
        self.output.push_str("}\n\n");

        self.output
            .push_str("impl<Native: Clone, Vm: Clone> Clone for HarnessValue<Native, Vm> {\n");
        self.output.push_str("    fn clone(&self) -> Self {\n");
        self.output.push_str("        match self {\n");
        self.output.push_str(
            "            HarnessValue::Native(value) => HarnessValue::Native(value.clone()),\n",
        );
        self.output
            .push_str("            HarnessValue::Vm(value) => HarnessValue::Vm(value.clone()),\n");
        self.output.push_str("        }\n");
        self.output.push_str("    }\n");
        self.output.push_str("}\n\n");

        self.output
            .push_str("impl<Native, Vm> HarnessValue<Native, Vm> {\n");
        self.output
            .push_str("    /// Convert one wrapper into one native value.\n");
        self.output
            .push_str("    fn into_native(self, label: &str) -> RuntimeResult<Native> {\n");
        self.output.push_str("        match self {\n");
        self.output
            .push_str("            HarnessValue::Native(value) => Ok(value),\n");
        self.output
            .push_str("            HarnessValue::Vm(_) => Err(RuntimeError::from(\n");
        self.output
            .push_str("                HarnessPlatformError::invalid_argument_value(\n");
        self.output.push_str("                    label,\n");
        self.output
            .push_str("                    \"expected native harness value\",\n");
        self.output.push_str("                ),\n");
        self.output.push_str("            )\n");
        self.output.push_str("            .boxed()),\n");
        self.output.push_str("        }\n");
        self.output.push_str("    }\n\n");

        self.output
            .push_str("    /// Convert one wrapper into one VM value.\n");
        self.output
            .push_str("    fn into_vm(self, label: &str) -> RuntimeResult<Vm> {\n");
        self.output.push_str("        match self {\n");
        self.output
            .push_str("            HarnessValue::Vm(value) => Ok(value),\n");
        self.output
            .push_str("            HarnessValue::Native(_) => Err(RuntimeError::from(\n");
        self.output.push_str(
            "                HarnessPlatformError::invalid_argument_value(label, \"expected VM harness value\"),\n",
        );
        self.output.push_str("            )\n");
        self.output.push_str("            .boxed()),\n");
        self.output.push_str("        }\n");
        self.output.push_str("    }\n");
        self.output.push_str("}\n");
    }
}

