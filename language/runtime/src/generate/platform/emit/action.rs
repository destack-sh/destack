use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

/// Prefix used by the host action declaration.
const HOST_ACTION_TYPE_PREFIX: &str = "export type HostAction =";

/// Generate runtime host actions from the binding action union.
pub(crate) fn generate_host_actions() {
    let binding_metadata_path = binding_metadata_path();
    let source = fs::read_to_string(&binding_metadata_path).unwrap_or_else(|error| {
        panic!("failed to read binding metadata source {binding_metadata_path:?}: {error}")
    });
    let action_names = parse_host_action_names(&source);
    let generated = render_host_action_source(&action_names);
    let output_path = runtime_action_generated_path();

    write_generated_file(&output_path, &generated);
}

/// Resolve the language workspace root for generator inputs.
fn language_root() -> PathBuf {
    let runtime_root = Path::new(env!("CARGO_MANIFEST_DIR"));
    runtime_root
        .parent()
        .unwrap_or_else(|| panic!("missing language root for {runtime_root:?}"))
        .to_path_buf()
}

/// Resolve the binding declaration path.
fn binding_metadata_path() -> PathBuf {
    language_root().join("library/platform/core/action.ds")
}

/// Resolve the generated runtime action output path.
fn runtime_action_generated_path() -> PathBuf {
    language_root().join("runtime/src/runtime/action/action.generated.rs")
}

/// Write one generated file to disk.
fn write_generated_file(path: &Path, contents: &str) {
    // parent directory
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).expect("failed to create output directory");
    }

    fs::write(path, contents).expect("failed to write generated file");
}

/// Parse canonical action names from the binding metadata union.
fn parse_host_action_names(source: &str) -> Vec<String> {
    let mut in_union = false;
    let mut actions = Vec::new();

    for line in source.lines() {
        let trimmed = line.trim();

        // locate the host action union declaration
        if !in_union {
            if !trimmed.starts_with(HOST_ACTION_TYPE_PREFIX) {
                continue;
            }

            in_union = true;
        }

        // collect action literals from this line
        actions.extend(string_literals_from_line(trimmed));

        // stop once the type declaration terminator is reached
        if trimmed.contains(';') {
            break;
        }
    }

    if !in_union {
        panic!("missing HostAction union declaration");
    }

    if actions.is_empty() {
        panic!("HostAction union is empty");
    }

    let mut seen_actions = BTreeSet::new();
    for action in &actions {
        if !seen_actions.insert(action.clone()) {
            panic!("duplicate host action literal: {action}");
        }
    }

    actions
}

/// Extract all string literal payloads from one source line.
fn string_literals_from_line(line: &str) -> Vec<String> {
    let mut values = Vec::new();
    let mut current = String::new();
    let mut is_in_string = false;

    for character in line.chars() {
        if character == '"' {
            if is_in_string {
                values.push(current.clone());
                current.clear();
            }
            is_in_string = !is_in_string;
            continue;
        }

        if is_in_string {
            current.push(character);
        }
    }

    values
}

/// Render generated runtime action source.
fn render_host_action_source(action_names: &[String]) -> String {
    let mut variant_to_name = BTreeMap::new();
    let mut action_variants = Vec::with_capacity(action_names.len());

    // build deterministic variant names and reject collisions
    for action_name in action_names {
        let variant_name = variant_name_for_action(action_name);
        if let Some(existing_name) = variant_to_name.insert(variant_name.clone(), action_name) {
            panic!("action variant collision for {variant_name}: {existing_name} vs {action_name}");
        }

        action_variants.push((action_name.clone(), variant_name));
    }

    let mut output = String::new();
    output.push_str("// generated by generate-bindings: do not edit\n\n");
    output.push_str("use super::HostActionId;\n\n");
    output.push_str("/// Canonical runtime host action.\n");
    output.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n");
    output.push_str("pub enum HostAction {\n");
    for (action_name, variant_name) in &action_variants {
        output.push_str(&format!("    /// `{action_name}`.\n"));
        output.push_str(&format!("    {variant_name},\n"));
    }
    output.push_str("}\n\n");
    output.push_str("impl HostAction {\n");
    output.push_str("    /// All canonical host actions.\n");
    output.push_str("    pub const ALL: &'static [Self] = &[\n");
    for (_action_name, variant_name) in &action_variants {
        output.push_str(&format!("        Self::{variant_name},\n"));
    }
    output.push_str("    ];\n\n");
    output.push_str("    /// Return the canonical action name.\n");
    output.push_str("    pub const fn name(self) -> &'static str {\n");
    output.push_str("        match self {\n");
    for (action_name, variant_name) in &action_variants {
        output.push_str(&format!(
            "            Self::{variant_name} => \"{action_name}\",\n"
        ));
    }
    output.push_str("        }\n");
    output.push_str("    }\n\n");
    output.push_str("    /// Return the stable action identifier.\n");
    output.push_str("    pub const fn id(self) -> HostActionId {\n");
    output.push_str("        HostActionId::from_name(self.name())\n");
    output.push_str("    }\n\n");
    output.push_str("    /// Resolve one action from one canonical action name.\n");
    output.push_str("    pub fn from_name(name: &str) -> Option<Self> {\n");
    output.push_str("        match name {\n");
    for (action_name, variant_name) in &action_variants {
        output.push_str(&format!(
            "            \"{action_name}\" => Some(Self::{variant_name}),\n"
        ));
    }
    output.push_str("            _ => None,\n");
    output.push_str("        }\n");
    output.push_str("    }\n");
    output.push_str("}\n");

    output
}

/// Build one enum variant name from one action string.
fn variant_name_for_action(action_name: &str) -> String {
    let mut variant_name = String::new();

    for segment in action_name.split('.') {
        let segment_name = pascal_case_segment(segment);
        variant_name.push_str(&segment_name);
    }

    if variant_name.is_empty() {
        panic!("invalid empty action name");
    }

    if variant_name
        .chars()
        .next()
        .is_some_and(|character| character.is_ascii_digit())
    {
        variant_name.insert(0, 'N');
    }

    variant_name
}

/// Convert one action segment to one pascal-case fragment.
fn pascal_case_segment(segment: &str) -> String {
    let mut output = String::new();
    let mut uppercase_next = true;

    for character in segment.chars() {
        // reset casing across delimiters
        if !character.is_ascii_alphanumeric() {
            uppercase_next = true;
            continue;
        }

        // uppercase only the next segment boundary character
        if uppercase_next {
            output.push(character.to_ascii_uppercase());
            uppercase_next = false;
            continue;
        }

        output.push(character);
    }

    output
}

#[cfg(test)]
mod tests {
    use super::{parse_host_action_names, render_host_action_source, variant_name_for_action};

    /// Parse all action literals from the intrinsic union.
    #[test]
    fn test_parse_host_action_names_collects_union_literals() {
        let source = r#"
            export type HostAction =
              | "fs.read"
              | "net.connect"
              | "gpu.render.multiDraw"
            ;
        "#;

        let names = parse_host_action_names(source);

        assert_eq!(
            names,
            vec![
                "fs.read".to_string(),
                "net.connect".to_string(),
                "gpu.render.multiDraw".to_string()
            ]
        );
    }

    /// Reject duplicate action literals in the intrinsic union.
    #[test]
    #[should_panic(expected = "duplicate host action literal: fs.read")]
    fn test_parse_host_action_names_rejects_duplicates() {
        let source = r#"
            export type HostAction =
              | "fs.read"
              | "fs.read"
            ;
        "#;

        let _ = parse_host_action_names(source);
    }

    /// Convert action names to stable enum variant names.
    #[test]
    fn test_variant_name_for_action() {
        assert_eq!(variant_name_for_action("fs.read"), "FsRead");
        assert_eq!(
            variant_name_for_action("gpu.render.multiDraw"),
            "GpuRenderMultiDraw"
        );
        assert_eq!(variant_name_for_action("3d.render"), "N3dRender");
    }

    /// Render one stable action enum source file.
    #[test]
    fn test_render_host_action_source() {
        let source = render_host_action_source(&["fs.read".to_string(), "net.connect".to_string()]);

        assert!(source.contains("pub enum HostAction"));
        assert!(source.contains("FsRead"));
        assert!(source.contains("NetConnect"));
    }
}
