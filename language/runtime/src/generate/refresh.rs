use std::fs;
use std::path::Path;

use crate::emit::write_domain_bindings;

/// Write one generated stub file when strict generation rules allow it.
pub(crate) fn write_stub_file(path: &Path, generated: &str, refresh_stubs: bool) {
    // create missing files directly
    if !path.exists() {
        write_domain_bindings(path, generated);
        return;
    }

    // do not overwrite existing files unless explicit refresh is enabled
    if !refresh_stubs {
        return;
    }

    let Ok(existing) = fs::read_to_string(path) else {
        write_domain_bindings(path, generated);
        return;
    };

    // only refresh files that are explicit generator stubs
    if !existing.contains("// generated by generate-bindings: stub, do not edit") {
        return;
    }

    if existing != generated {
        write_domain_bindings(path, generated);
    }
}

/// Write one generated stub file only when the target path is missing.
pub(crate) fn write_missing_stub_file(path: &Path, generated: &str) {
    if !path.exists() {
        write_domain_bindings(path, generated);
    }
}
