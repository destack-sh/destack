use std::path::Path;

use anyhow::Result;

use crate::generate::core::{
    Field, Item, Module, Payload, Schema, Shape, Type, Variant, write_text,
};

use super::adapter;

/// Generate TypeScript bridge declarations.
pub(in crate::generate) fn generate(root: &Path, schema: &Schema) -> Result<()> {
    for (module, names) in &schema.modules {
        let content = render_module(schema, *module, names);
        let path = module.typescript_file();

        write_text(root, path, content)?;
    }

    adapter::generate(root, schema)?;

    Ok(())
}

/// Render one TypeScript generated module.
fn render_module(schema: &Schema, module: Module, names: &[String]) -> String {
    let mut content = String::from("/* generated by destack_bridge_generate, do not edit */\n\n");
    let imports = render_imports(schema, module, names);

    if !imports.is_empty() {
        content.push_str(&imports);
        content.push('\n');
    }

    for name in names {
        let item = schema.item(name);
        content.push_str(&render_item(schema, item));
    }

    content
}

/// Render TypeScript imports referenced by one module.
fn render_imports(schema: &Schema, module: Module, names: &[String]) -> String {
    let mut content = String::new();

    for item in schema.referenced_types(names) {
        let path = module.typescript_import_path(item.module(schema));
        content.push_str(&format!(
            "import type {{ {} }} from \"{path}\";\n",
            item.name
        ));
    }

    content
}

/// Render one bridge item as a TypeScript type.
fn render_item(schema: &Schema, item: &Item) -> String {
    let mut content = String::new();
    push_doc(&mut content, item.doc(), "");

    match &item.shape {
        Shape::Struct(fields) => {
            content.push_str(&format!("export type {} = {{\n", item.name));
            for field in fields {
                content.push_str(&render_field(schema, field, "    "));
            }
            content.push_str("};\n\n");
        }
        Shape::Enum(variants) if schema.is_unit_enum(&item.name) => {
            content.push_str(&format!("export type {} = ", item.name));
            content.push_str(&render_unit_enum(variants));
            content.push_str(";\n\n");
        }
        Shape::Enum(variants) => {
            content.push_str(&format!("export type {} =\n", item.name));
            content.push_str(render_payload_enum(schema, variants).trim_end());
            content.push_str(";\n\n");
        }
    }

    content
}

/// Render one TypeScript object field.
fn render_field(schema: &Schema, field: &Field, indent: &str) -> String {
    let mut content = String::new();
    let name = field.label();
    let ty = render_field_type(schema, &field.ty);
    let optional = matches!(field.ty, Type::Option(_));
    let marker = if optional { "?" } else { "" };

    push_doc(&mut content, field.doc(), indent);
    content.push_str(&format!("{indent}readonly {name}{marker}: {ty};\n"));

    content
}

/// Render one unit enum as a string literal union.
fn render_unit_enum(variants: &[Variant]) -> String {
    variants
        .iter()
        .map(|variant| format!("{:?}", variant.label()))
        .collect::<Vec<_>>()
        .join(" | ")
}

/// Render one payload enum as a discriminated union.
fn render_payload_enum(schema: &Schema, variants: &[Variant]) -> String {
    let mut content = String::new();

    for variant in variants {
        push_doc(&mut content, variant.doc(), "    ");
        content.push_str("    | {\n");
        content.push_str(&format!(
            "          readonly kind: {:?};\n",
            variant.label()
        ));

        match &variant.payload {
            Payload::Unit => {}
            Payload::Tuple(ty) => {
                let name = variant.payload_field_name();
                let ty = render_type(schema, ty);

                content.push_str(&format!("          readonly {name}: {ty};\n"));
            }
            Payload::Struct(fields) => {
                for field in fields {
                    content.push_str(&render_field(schema, field, "          "));
                }
            }
        }

        content.push_str("      }\n");
    }

    content
}

/// Render one TypeScript field type.
fn render_field_type(schema: &Schema, ty: &Type) -> String {
    match ty {
        Type::Option(ty) => render_type(schema, ty),
        _ => render_type(schema, ty),
    }
}

/// Render one TypeScript type.
fn render_type(schema: &Schema, ty: &Type) -> String {
    match ty {
        Type::String => "string".to_string(),
        Type::Bool => "boolean".to_string(),
        Type::U8 | Type::U32 | Type::Usize => "number".to_string(),
        Type::Vec(ty) if matches!(ty.as_ref(), Type::U8) => {
            "Uint8Array | readonly number[]".to_string()
        }
        Type::Vec(ty) => format!("readonly {}[]", render_type(schema, ty)),
        Type::Option(ty) => format!("{} | undefined", render_type(schema, ty)),
        Type::Named(name) if schema.is_unit_enum(name) => name.clone(),
        Type::Named(name) => name.clone(),
    }
}

/// Append one documentation line.
fn push_doc(content: &mut String, doc: &str, indent: &str) {
    if doc.is_empty() {
        return;
    }

    content.push_str(&format!("{indent}/** {doc} */\n"));
}

impl Item {
    /// Return the module that owns this item.
    fn module(&self, schema: &Schema) -> Module {
        for (module, names) in &schema.modules {
            if names.iter().any(|name| name == &self.name) {
                return *module;
            }
        }

        panic!("bridge item {} has no module", self.name);
    }
}
