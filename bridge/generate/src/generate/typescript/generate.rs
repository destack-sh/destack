use std::path::Path;

use anyhow::Result;

use crate::generate::core::{
    Field, Item, ModulePath, Payload, Schema, SchemaModule, Shape, Type, Variant, write_text,
};

use super::adapter;

const GENERATED_HEADER: &str = "/* generated by destack_bridge_generate, do not edit */";

/// Generate TypeScript bridge declarations.
pub(in crate::generate) fn generate(root: &Path, schema: &Schema) -> Result<()> {
    for module in &schema.modules {
        let content = render_module(schema, module, &module.names);
        let path = generated_path(module);

        write_text(root, &path, content)?;
    }

    adapter::generate(root, schema)?;

    Ok(())
}

/// Return one generated TypeScript module path.
pub(super) fn generated_path(module: &SchemaModule) -> String {
    format!(
        "bridge/typescript/src/{}.generated.ts",
        module.path.slash_path()
    )
}

/// Render one TypeScript generated module.
fn render_module(schema: &Schema, module: &SchemaModule, names: &[String]) -> String {
    let mut text = Text::new();
    text.line(GENERATED_HEADER);
    text.blank();

    let imports = render_imports(schema, module, names);

    if !imports.is_empty() {
        text.raw(imports);
        text.blank();
    }

    for name in names {
        let item = schema.item(name);
        TsItem { schema, item }.render(&mut text);
    }

    text.finish()
}

/// Render TypeScript imports referenced by one module.
fn render_imports(schema: &Schema, module: &SchemaModule, names: &[String]) -> String {
    let mut text = Text::new();

    for item in schema.referenced_types(names) {
        let path = import_path(&module.path, schema.module_path(&item.name));
        text.line(format!("import type {{ {} }} from \"{path}\";", item.name));
    }

    text.finish()
}

/// Return the TypeScript import path between two generated modules.
pub(super) fn import_path(source: &ModulePath, target: &ModulePath) -> String {
    let source = source.segments();
    let target = target_segments(target);
    let source_directory = &source[..source.len() - 1];
    let mut shared = 0;

    while shared < source_directory.len()
        && shared < target.len()
        && source_directory[shared] == target[shared]
    {
        shared += 1;
    }

    let mut segments = Vec::new();
    for _ in shared..source_directory.len() {
        segments.push("..".to_string());
    }
    segments.extend(target[shared..].iter().cloned());

    let path = segments.join("/");
    if path.starts_with('.') {
        format!("{path}.js")
    } else {
        format!("./{path}.js")
    }
}

/// Return TypeScript generated target segments.
pub(super) fn target_segments(path: &ModulePath) -> Vec<String> {
    let mut segments = path.segments().to_vec();
    let index = segments.len() - 1;
    let last = &mut segments[index];
    *last = format!("{last}.generated");

    segments
}

/// Render one bridge item as a TypeScript type.
struct TsItem<'schema> {
    /// Bridge schema.
    schema: &'schema Schema,
    /// Bridge item.
    item: &'schema Item,
}

/// One generated text document.
struct Text {
    /// Generated source.
    source: String,
}

impl<'schema> TsItem<'schema> {
    /// Render this TypeScript item.
    fn render(&self, text: &mut Text) {
        let item = self.item;
        text.doc(item.doc(), "");

        match &item.shape {
            Shape::Struct(fields) => {
                text.line(format!("export type {} = {{", item.name));
                for field in fields {
                    render_field(self.schema, text, field, "    ");
                }
                text.line("};");
                text.blank();
            }
            Shape::Enum(variants) if self.schema.is_unit_enum(&item.name) => {
                text.line(format!(
                    "export type {} = {};",
                    item.name,
                    render_unit_enum(variants)
                ));
                text.blank();
            }
            Shape::Enum(variants) => {
                text.line(format!("export type {} =", item.name));
                render_payload_enum(self.schema, text, variants);
                text.line(";");
                text.blank();
            }
        }
    }
}

/// Render one TypeScript object field.
fn render_field(schema: &Schema, text: &mut Text, field: &Field, indent: &str) {
    let name = field.label();
    let ty = render_field_type(schema, &field.ty);
    let optional = matches!(field.ty, Type::Option(_));
    let marker = if optional { "?" } else { "" };

    text.doc(field.doc(), indent);
    text.line(format!("{indent}readonly {name}{marker}: {ty};"));
}

/// Render one unit enum as a string literal union.
fn render_unit_enum(variants: &[Variant]) -> String {
    variants
        .iter()
        .map(|variant| format!("{:?}", variant.label()))
        .collect::<Vec<_>>()
        .join(" | ")
}

/// Render one payload enum as a discriminated union.
fn render_payload_enum(schema: &Schema, text: &mut Text, variants: &[Variant]) {
    for variant in variants {
        text.doc(variant.doc(), "    ");
        text.line("    | {");
        text.line(format!("          readonly kind: {:?};", variant.label()));

        match &variant.payload {
            Payload::Unit => {}
            Payload::Tuple(ty) => {
                let name = variant.payload_field_name();
                let ty = render_type(schema, ty);

                text.line(format!("          readonly {name}: {ty};"));
            }
            Payload::Struct(fields) => {
                for field in fields {
                    render_field(schema, text, field, "          ");
                }
            }
        }

        text.line("      }");
    }
}

/// Render one TypeScript field type.
fn render_field_type(schema: &Schema, ty: &Type) -> String {
    match ty {
        Type::Option(ty) => render_type(schema, ty),
        _ => render_type(schema, ty),
    }
}

/// Render one TypeScript type.
fn render_type(schema: &Schema, ty: &Type) -> String {
    match ty {
        Type::String => "string".to_string(),
        Type::Bool => "boolean".to_string(),
        Type::U8 | Type::U32 | Type::Usize => "number".to_string(),
        Type::Vec(ty) if matches!(ty.as_ref(), Type::U8) => {
            "Uint8Array | readonly number[]".to_string()
        }
        Type::Vec(ty) => format!("readonly {}[]", render_type(schema, ty)),
        Type::Option(ty) => format!("{} | undefined", render_type(schema, ty)),
        Type::Named(name) if schema.is_unit_enum(name) => name.clone(),
        Type::Named(name) => name.clone(),
    }
}

impl Text {
    /// Create one empty text document.
    fn new() -> Self {
        Self {
            source: String::new(),
        }
    }

    /// Write raw generated source.
    fn raw(&mut self, source: impl AsRef<str>) {
        self.source.push_str(source.as_ref());
    }

    /// Write one line.
    fn line(&mut self, line: impl AsRef<str>) {
        self.source.push_str(line.as_ref());
        self.source.push('\n');
    }

    /// Write one blank line.
    fn blank(&mut self) {
        self.source.push('\n');
    }

    /// Write one documentation line.
    fn doc(&mut self, doc: &str, indent: &str) {
        if !doc.is_empty() {
            self.line(format!("{indent}/** {doc} */"));
        }
    }

    /// Return the generated source.
    fn finish(self) -> String {
        self.source
    }
}
