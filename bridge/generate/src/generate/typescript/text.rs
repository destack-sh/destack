pub(super) const GENERATED_HEADER: &str = "/* generated by destack_bridge_generate, do not edit */";

pub(super) struct Text {
    /// Generated source.
    source: String,
}

impl Text {
    /// Create one empty text document.
    pub(super) fn new() -> Self {
        Self {
            source: String::new(),
        }
    }

    /// Write raw generated source.
    pub(super) fn raw(&mut self, source: impl AsRef<str>) {
        self.source.push_str(source.as_ref());
    }

    /// Write one line.
    pub(super) fn line(&mut self, line: impl AsRef<str>) {
        self.source.push_str(line.as_ref());
        self.source.push('\n');
    }

    /// Write one blank line.
    pub(super) fn blank(&mut self) {
        self.source.push('\n');
    }

    /// Write one export declaration.
    pub(super) fn export(&mut self, path: &str, names: &[&str]) {
        self.line("export {");

        for name in names {
            self.line(format!("    {name},"));
        }

        self.line(format!("}} from {path:?};"));
    }

    /// Write one documentation line.
    pub(super) fn doc(&mut self, doc: &str, indent: &str) {
        if !doc.is_empty() {
            self.line(format!("{indent}/** {doc} */"));
        }
    }

    /// Return the generated source.
    pub(super) fn finish(self) -> String {
        self.source
    }
}
