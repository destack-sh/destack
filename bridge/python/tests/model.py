from __future__ import annotations

from destack import artifact, core, dir, repository, source
from destack.protocol.serde import decode_value, encode_value


def test_roundtrip_content_through_binary_and_json_codecs() -> None:
    """Roundtrip source content through generated binary and JSON codecs."""

    value = source.ContentBinary(content=bytes([1, 2, 3]))

    # roundtrip through the binary codec generated from the reflected model
    data = encode_value(value.encode)
    decoded = decode_value(data, source.decode_content)

    # roundtrip through the JSON codec generated from the same model
    payload = value.to_json()
    parsed = source.from_json_content(payload)

    assert decoded == value
    assert parsed == value


def test_roundtrip_artifact_key_through_binary_and_json_codecs() -> None:
    """Roundtrip a nested artifact key through generated codecs."""

    package = 1
    module = source.ModuleId(
        package_id=package,
        module_key=2,
    )
    profile = 3
    target = source.TargetId(
        package_id=package,
        target_key=4,
    )
    key = artifact.ArtifactKeyMirLowered(
        module=module,
        profile=profile,
        target=target,
    )

    # preserve a cross-crate artifact key through binary serde
    data = encode_value(key.encode)
    decoded = decode_value(data, artifact.decode_artifact_key)

    # preserve the same nested value through JSON serde
    payload = key.to_json()
    parsed = artifact.from_json_artifact_key(payload)

    assert decoded == key
    assert parsed == key


def test_roundtrip_revision_through_binary_and_json_codecs() -> None:
    """Roundtrip a fixed revision identity through generated codecs."""

    value = repository.Revision(value=bytes([9]) * 32)

    # fixed-size byte identities should remain byte identities
    data = encode_value(value.encode)
    decoded = decode_value(data, repository.decode_revision)

    # JSON keeps the same value using the generated byte representation
    payload = value.to_json()
    parsed = repository.from_json_revision(payload)

    assert decoded == value
    assert parsed == value


def test_resolve_generated_ir_strings_through_string_pool() -> None:
    """Resolve generated IR string ids through a public string pool."""

    data = core.StringPoolData(
        strings=[
            (11, "std"),
            (22, "math"),
            (33, "add"),
        ],
    )
    path = dir.Path(
        segments=[11, 22, 33],
    )

    # resolve raw generated StringId values through the public pool helper
    strings = core.StringPool.from_data(data)

    assert path.last_segment() == 33
    assert strings.get(22) == "math"
    assert strings.values(path.segments) == ["std", "math", "add"]
    assert strings.join(path.segments, ".") == "std.math.add"
    assert strings.intern("add") == 33
