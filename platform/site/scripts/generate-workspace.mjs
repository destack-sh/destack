import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { marked } from "marked";

import { highlightCode, highlightDestackFile } from "./highlight.mjs";

const siteDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const workspaceDirectory = join(siteDirectory, "workspace");
const outputPath = join(siteDirectory, "src/generated/workspace.ts");

marked.use({
    gfm: true,
    renderer: {
        // fenced code goes through the same highlighter as everything else
        code({ text, lang }) {
            return `<pre><code>${highlightCode(text, lang ?? "")}</code></pre>`;
        },
    },
});

await generate();

// keep regenerating while the workspace changes underneath the dev server
if (process.argv.includes("--watch")) {
    const { watch } = await import("node:fs");
    let timer;
    watch(workspaceDirectory, { recursive: true }, () => {
        clearTimeout(timer);
        timer = setTimeout(() => generate().catch(console.error), 100);
    });
    console.log("watching workspace/ for changes");
}

async function generate() {
    // collect every workspace file, depth-first, readmes ahead of their siblings
    const paths = await collectPaths(workspaceDirectory);

    // render each file once at build time: sources highlight, markdown renders
    const files = [];
    for (const path of paths) {
        const absolute = join(workspaceDirectory, path);
        const source = await readFile(absolute, "utf8");

        files.push({
            path,
            kind: kindFor(path),
            source,
            html: await renderHtml(path, absolute, source),
        });
    }

    // emit the generated module, or verify it in check mode
    const banner = "// generated by scripts/generate-workspace.mjs, do not edit\n\n";
    const types =
        "export type WorkspaceSeedFile = {\n" +
        "    path: string;\n" +
        '    kind: "source" | "markdown" | "config";\n' +
        "    source: string;\n" +
        "    html: string;\n" +
        "};\n\n";
    const data = `export const workspaceFiles: readonly WorkspaceSeedFile[] = ${JSON.stringify(files, null, 4)};\n`;
    const module = banner + types + data;

    if (process.argv.includes("--check")) {
        const existing = await readFile(outputPath, "utf8").catch(() => "");
        if (existing !== module) {
            console.error("generated workspace is stale, run: bun scripts/generate-workspace.mjs");
            process.exit(1);
        }
    } else {
        await writeFile(outputPath, module);
        console.log(`generated ${relative(siteDirectory, outputPath)} (${files.length} files)`);
    }
}

async function collectPaths(directory) {
    const collected = [];

    const walk = async (current) => {
        const entries = await readdir(current, { withFileTypes: true });
        const directories = entries.filter((entry) => entry.isDirectory()).sort(byName);
        const files = entries.filter((entry) => entry.isFile());

        // the directory's readme decides the file order, readme itself first
        const ranks = await readmeRanks(current, files);
        files.sort((left, right) => ranks.get(left.name) - ranks.get(right.name));

        for (const file of files) {
            collected.push(relative(workspaceDirectory, join(current, file.name)));
        }
        for (const child of directories) {
            await walk(join(current, child.name));
        }
    };
    await walk(directory);

    return collected;
}

async function readmeRanks(directory, files) {
    const names = files.map((file) => file.name).sort();
    const ranks = new Map(names.map((name, index) => [name, names.length + index]));
    ranks.set("README.md", -1);

    // files linked from the readme rank in link order, ahead of unlinked ones
    if (names.includes("README.md")) {
        const readme = await readFile(join(directory, "README.md"), "utf8");
        let rank = 0;
        for (const match of readme.matchAll(/\]\(([^)#?]+)\)/g)) {
            const name = match[1].split("/").at(-1);
            if (name !== "README.md" && ranks.has(name)) {
                ranks.set(name, Math.min(ranks.get(name), rank));
                rank += 1;
            }
        }
    }

    return ranks;
}

function byName(left, right) {
    return left.name.localeCompare(right.name);
}

function kindFor(path) {
    if (path.endsWith(".ds")) {
        return "source";
    }
    if (path.endsWith(".md")) {
        return "markdown";
    }

    return "config";
}

async function renderHtml(path, absolute, source) {
    if (path.endsWith(".ds")) {
        return highlightDestackFile(absolute, source);
    }
    if (path.endsWith(".md")) {
        return marked.parse(source, { async: false, gfm: true });
    }

    return highlightCode(source, "json");
}
