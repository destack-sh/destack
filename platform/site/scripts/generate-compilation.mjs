import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { highlightCode, highlightDestackFile } from "./highlight.mjs";

const siteDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const exampleDirectory = resolve(siteDirectory, "src/content/example/compilation");
const generatedFile = resolve(siteDirectory, "src/generated/compilation.ts");
const isCheck = process.argv.includes("--check");

const destackFile = resolve(exampleDirectory, "main.ds");
const destack = readFileSync(destackFile, "utf8").trimEnd();
const mir = readFileSync(resolve(exampleDirectory, "main.mir"), "utf8").trimEnd();
const javascript = readFileSync(resolve(exampleDirectory, "main.js"), "utf8").trimEnd();
const generated = renderGenerated(
    highlightDestackFile(destackFile, destack),
    highlightCode(mir, "mir"),
    highlightCode(javascript, "js"),
);

// reject stale generated output during checks
if (isCheck) {
    const current = readFileSync(generatedFile, "utf8");
    if (current !== generated) {
        throw new Error("generated compilation example is stale");
    }
}
// otherwise refresh the generated module
else {
    writeFileSync(generatedFile, generated);
}

/** Render the generated TypeScript module. */
function renderGenerated(destackHtml, mirHtml, javascriptHtml) {
    return `// Generated by scripts/generate-compilation.mjs. Do not edit.

/** Highlighted Destack source. */
export const destackHtml = ${JSON.stringify(destackHtml)};

/** Highlighted illustrative MIR. */
export const mirHtml = ${JSON.stringify(mirHtml)};

/** Highlighted illustrative JavaScript. */
export const javascriptHtml = ${JSON.stringify(javascriptHtml)};
`;
}
